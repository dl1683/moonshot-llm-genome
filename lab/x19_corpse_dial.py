    amp_met = bool(np.isfinite(deep_ratio)
                   and deep_ratio >= RATIO_DIAL_FRAC * live_ratio
                   and deep_on_frac is not None
                   and deep_on_frac >= ON_EXCESS_DIAL_FRAC)
