def run_cons(tag: str, start_sd: dict, resume_ck: Path) -> dict:
    """chunked_consolidate's arithmetic VERBATIM (e113's rig; the TAVIREN
    pool; 25 steps; NATURAL) + per-step panels + draw logging."""
    state = {"step": 0, "traj": [], "draws": []}
    if resume_ck.exists():
        state = torch.load(resume_ck, map_location="cpu", weights_only=False)
        log(f"  [{tag}] RESUMED at step {state['step']}/{CONS_STEPS}")
    if int(state.get("step", 0)) >= CONS_STEPS:
        return {"sd": state["model"], "traj": state["traj"],
                "draws": state["draws"], "resumed_final": True}
    n_pool, n_anc = inst_x_tav.shape[0], anchor_full.shape[0]
    net = fresh_net(start_sd)
    net.to(DEV)
    net.train()
    opt = torch.optim.AdamW(net.parameters(), lr=CONS_LR,
                            betas=CONS_BETAS, weight_decay=CONS_WD)
    gen = torch.Generator().manual_seed(CONS_SEED)
    if resume_ck.exists():
        net.load_state_dict(state["model"])
        net.to(DEV)
        net.train()
        opt.load_state_dict(state["opt"])
        gen.set_state(state["gen_state"])
    evl = G1.evl_load(start_sd)

    def panel(step: int) -> dict:
        sd_cpu = {k: v.detach().cpu().clone() for k, v in net.state_dict().items()}
        evl.load_state_dict(sd_cpu)
        evl.eval()
        eco = slot_ecology(evl, g0_ids, LETTER_IDS)
        row = {"step": step, "para_g0": eco["p_T"], "host_g0": eco["p_Z"],
               "ghost_g0": eco["p_Q"], "ecology": eco,
               "elapsed_s": round(time.time() - T0, 1)}
        if step in CE_MILESTONES:
            row["ce_r"] = G1.ce_fixed_cpu(evl, *r_eval_xy)
        state["traj"].append(row)
        log(f"  [{tag}] s{step:3d} PARA p(T) {row['para_g0']:.6f} | host "
            f"{row['host_g0']:.6f} | ghost {row['ghost_g0']:.6f} | PN "
            f"{eco['pn_total']:.4f}"
            + (f" | CE_R {row['ce_r']:.4f}" if "ce_r" in row else ""))
        return row

    t_burst, n_burst = E261._open_burst(f"{tag}")
    step = state["step"]
    if step == 0:
        panel(0)                                  # the t0 read
    while step < CONS_STEPS:
        step += 1
        ix = torch.randint(n_pool, (16,), generator=gen)
        aj = torch.randint(n_anc, (8,), generator=gen)
        rj = torch.randint(len(train_ids) - G1.BLOCK - 1, (8,),
                           generator=gen)
        state["draws"].append({"ix": ix.tolist(), "aj": aj.tolist(),
                               "rj": rj.tolist()})
        nw = inst_x_tav[ix].to(DEV)
        anc = torch.cat([anchor_full[aj],
                         torch.stack([train_ids[s: s + G1.BLOCK]
                                      for s in rj])], 0).to(DEV)
        x = torch.cat([nw[:, :-1], anc[:, :-1]], 0)
        y = torch.cat([nw[:, 1:], anc[:, 1:]], 0)
        m = torch.zeros(32, x.shape[1], dtype=torch.bool, device=DEV)
        m[:16] = inst_mask_tav[ix].to(DEV)
        logits, _ = net(x)
        nll = F.cross_entropy(logits.reshape(-1, logits.shape[-1]),
                              y.reshape(-1), reduction="none"
                              ).view(x.shape[0], x.shape[1])
        nm = nll[:16][m[:16]]
        cm = nll[16:]
        loss = (nm.sum() + cm.sum()) / (nm.numel() + cm.numel())
        opt.zero_grad(set_to_none=True)
        loss.backward()
        torch.nn.utils.clip_grad_norm_(net.parameters(), 1.0)
        opt.step()
        ok_t, temp = E261.burst_temp_check(f"{tag}.s{step}")
        n_burst += 1
        state["step"] = step
        panel(step)
        if step % 5 == 0 or step == CONS_STEPS or not ok_t                 or (time.time() - t_burst) > E261.BURST_MAX_S:
            state["model"] = {k: v.detach().cpu().clone()
                              for k, v in net.state_dict().items()}
            state["opt"] = opt.state_dict()
            state["gen_state"] = gen.get_state()
            torch.save(state, resume_ck)
        if not ok_t or (time.time() - t_burst) > E261.BURST_MAX_S:
            log(f"  [{tag}] burst ended at s{step} "
                f"({'thermal' if not ok_t else 'cap'}); cooldown + resume")
            E261.burst_cooldown(tag)
            t_burst, n_burst = E261._open_burst(f"{tag}-resume")
    E261.burst_cooldown(f"{tag}-end")
    sd_out = {k: v.detach().cpu().clone() for k, v in net.state_dict().items()}
    del net, opt, gen, evl
    return {"sd": sd_out, "traj": state["traj"], "draws": state["draws"]}


