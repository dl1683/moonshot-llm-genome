@torch.no_grad()
def slot_ecology(net, ids: torch.Tensor, letter_ids: dict) -> dict:
    """ONE battery pass -> every letter's mean at the last position + the
    parasite's per-context stats + the PN total. battery_cell-equivalent
    math (mean of the softmax column)."""
    net.eval()
    cols = {L: [] for L in letter_ids}
    para_col = []
    for i in range(0, ids.shape[0], 30):
        lg, _ = net(ids[i:i + 30])
        pr = F.softmax(lg[:, -1], -1)
        for L, lid in letter_ids.items():
            cols[L].append(pr[:, lid])
        para_col.append(pr[:, letter_ids["T"]])
    out = {f"p_{L}": float(torch.cat(v).mean()) for L, v in cols.items()}
    out["pn_total"] = float(sum(out[f"p_{L}"] for L in letter_ids))
    pv = torch.cat(para_col)
    out["para_median"] = float(pv.median())
    out["para_max"] = float(pv.max())
    out["para_frac_ge_005"] = float((pv >= READ_BAR).float().mean())
    return out


def certify_room_local(room, probes: int = 4) -> dict:
    """e261's certify probes for ONE locally-built room (idempotency,
    kept^2 vs k/N, DCT roundtrip; seed 26115 — e261's CERT_SEED)."""
    rng = np.random.default_rng(E261.CERT_SEED)
    out: dict = {"probes": probes, "seed": E261.CERT_SEED}
    x = rng.standard_normal(room.n)
    xr = room.recon(room.coeffs(x))
    out["dct_roundtrip_rel"] = float(np.linalg.norm(xr - x)
                                     / np.linalg.norm(x))
    idem, kept2 = [], []
    for _ in range(probes):
        x = rng.standard_normal(room.n)
        px = room.project(x)
        ppx = room.project(px)
        idem.append(float(np.linalg.norm(ppx - px) / np.linalg.norm(px)))
        kept2.append(float((px @ px) / (x @ x)))
    bar = max(5.0 * math.sqrt(2.0 * room.k) / room.n, 1e-9)
    out.update({"k": room.k, "idempotency_max": max(idem),
                "kept2_mean": float(np.mean(kept2)),
                "kept2_expect": room.k / room.n,
                "kept2_bar_10sig": bar,
                "kept2_pass": bool(abs(float(np.mean(kept2)) - room.k / room.n)
                                   <= bar),
                "idempotency_pass": bool(max(idem) <= 1e-8)})
    out["pass"] = bool(out["dct_roundtrip_rel"] <= 1e-8
                       and out["kept2_pass"] and out["idempotency_pass"])
    return out


