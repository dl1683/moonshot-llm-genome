def phase_P1(p0: dict) -> dict:
    log("P1 — THE SWAP ARM (e001 BASE + the cons curriculum: 16 ZEPHYRA "
        f"jittered-pool + 8 paired + 8 random, const lr {FT_LR}, seed "
        f"{CONS_SEED}, CPU threads 4, captures at {len(CAPTURE_STEPS)} "
        "rungs)")

    e001_sd = load_model_sd(CKPT_DIR / "e001.pt")
    resume_ck = RD / "swap_resume.pt"

    state = {"step": 0, "traj": [], "captured": {}}
    if resume_ck.exists():
        state = torch.load(resume_ck, map_location="cpu",
                           weights_only=False)
        log(f"  [swap] RESUMED at step {state['step']}/{CONS_STEPS} "
            f"({len(state['captured'])} captures restored)")

    net0 = G1.evl_load(e001_sd)                  # g1c's own net0 form
    evl = copy.deepcopy(net0)                    # the measurement twin
    base_flat64 = flat_params_cpu(net0).double().numpy()

    if int(state.get("step", 0)) >= CONS_STEPS:
        log(f"  [swap] resume ckpt already finished at "
            f"s{state['step']} — training skipped")
        return {"traj": state["traj"], "captured": state["captured"],
                "base_flat64": base_flat64}

    net = copy.deepcopy(net0).to(CPU)
    net.train()
    opt = torch.optim.AdamW(net.parameters(), lr=FT_LR, betas=(0.9, 0.95),
                            weight_decay=0.1)
    gen = torch.Generator().manual_seed(CONS_SEED)
    if resume_ck.exists():
        net.load_state_dict(state["model"])
        net.to(CPU)
        net.train()
        opt.load_state_dict(state["opt"])
        gen.set_state(state["gen_state"])

    n_pool = p0["pool_z_x"].shape[0]
    cons_anchor = p0["cons_anchor"]
    train_ids = p0["train_ids"]
    captured: dict = state["captured"]
    step = state["step"]
    traj: list = state["traj"]
    t_slice = time.time()

    def save_resume() -> None:
        torch.save({"model": {k: v.detach().cpu().clone()
                              for k, v in net.state_dict().items()},
                    "opt": opt.state_dict(), "gen_state": gen.get_state(),
                    "step": state["step"], "traj": state["traj"],
                    "captured": state["captured"]}, resume_ck)

    while step < CONS_STEPS:
        step += 1
        # ---- the cons draw (e113/G1's own order: ix 16 pool, aj 8 anchor,
        # rj 8 random) ---------------------------------------------------
        ix = torch.randint(n_pool, (16,), generator=gen)
        aj = torch.randint(cons_anchor.shape[0], (8,), generator=gen)
        rj = torch.randint(len(train_ids) - G1.BLOCK - 1, (8,),
                           generator=gen)
        nw = p0["pool_z_x"][ix]
        anc = torch.cat([cons_anchor[aj],
                         torch.stack([train_ids[s: s + G1.BLOCK]
                                      for s in rj])], 0)
        x = torch.cat([nw[:, :-1], anc[:, :-1]], 0)
        y = torch.cat([nw[:, 1:], anc[:, 1:]], 0)
        m = torch.zeros(32, x.shape[1], dtype=torch.bool)
        m[:16] = p0["pool_z_mask"][ix]
        logits, _ = net(x)
        nll = F.cross_entropy(logits.reshape(-1, logits.shape[-1]),
                              y.reshape(-1), reduction="none"
                              ).view(x.shape[0], x.shape[1])
        nm = nll[:16][m[:16]]
        cm = nll[16:]
        loss = (nm.sum() + cm.sum()) / (nm.numel() + cm.numel())
        opt.zero_grad(set_to_none=True)
        loss.backward()
        torch.nn.utils.clip_grad_norm_(net.parameters(), 1.0)
        opt.step()
        # ---- the per-step read (x42's exact form, on the twin) --------
        sd_cpu = {k: v.detach().clone() for k, v in net.state_dict().items()}
        evl.load_state_dict(sd_cpu)
        evl.eval()
        bz = G1.battery_cell(evl, p0["g0_ids"], p0["zid"])
        traj.append({"step": step, "g0_pz": bz["mean_pz"],
                     "ce_batch": float(loss.item())})
        if step in CAPTURE_STEPS and step not in captured:
            captured[step] = sd_cpu
            log(f"  [swap] CAPTURED s{step} (read {bz['mean_pz']:.6f})")
        if step % 25 == 0 or step == 1:
            log(f"  [swap] s{step:4d} g0 {bz['mean_pz']:.6f} "
                f"CE {float(loss.item()):.4f}")
        state["step"] = step
        state["traj"] = traj
        state["captured"] = captured
        if (time.time() - t_slice) > TRAIN_CAP_CPU:
            save_resume()
            log(f"  [swap] slice cap ({TRAIN_CAP_CPU:.0f}s) at s{step} "
                "— resume saved, continuing (CPU park convention)")
            t_slice = time.time()
    save_resume()
    log(f"  [swap] replay finished: {CONS_STEPS} steps, "
        f"{len(captured)} captures")
    del net, opt
    return {"traj": traj, "captured": captured,
            "base_flat64": base_flat64}


