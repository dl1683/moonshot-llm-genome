    coll_rungs = [k for k, v in ladder_cls.items()
                  if v["response_class"] == "COLLAPSE"]
    amb_rungs = [k for k, v in ladder_cls.items()
                 if v["response_class"] == "AMBIGUOUS"]
    max_lift_prior = max((ladder_cls[k]["prior_host"] for k in lift_rungs),
                         default=None)
    min_coll_prior = min((ladder_cls[k]["prior_host"] for k in coll_rungs),
                         default=None)
    monotone = bool(lift_rungs and coll_rungs
                    and max_lift_prior < min_coll_prior)
    sharp = bool(not amb_rungs and lift_rungs and coll_rungs and monotone)

    # the response-magnitude grading (the executor position's secondary,
    # scored; never a bar)
    living_move_x = [ladder_cls[k]["move_currency_x"]
                     for k, *_ in LADDER
                     if ladder_cls[k]["living_read_rule"]["p_base_gt_0.05"]
                     and ladder_cls[k]["response_class"] == "COLLAPSE"]
