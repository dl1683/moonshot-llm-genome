    for i, d in enumerate(GAUSS_DOSES):
        mv = rider["doses"][f"{d:g}x"]["move_x_band"]
        ax.annotate(f"{mv:.2f}x band", (xs[i + 1], zs[i + 1]),
                    ha="center", va="bottom", fontsize=7)
