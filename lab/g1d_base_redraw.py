def chunked_base(tag: str, corpus: CharCorpus, resume_ck: Path) -> dict:
    """THE FRESH BASE: e001's recipe VERBATIM (common.train_model: 6L/6H/
    192d/256, steps 4000, lr 1e-3, bs 64, AdamW (0.9,0.95) wd 0.1, house
    cosine warmup 100, clip 1.0, corpus-seed-1337 batch stream) in
    owner-envelope bursts; train_model's own ckpt discipline carries the
    resume (bit-identical stream: model+opt+sched+gen_state)."""
    n_steps = BASE_STEPS
    resume_step = 0
    if resume_ck.exists():
        _pre = torch.load(resume_ck, map_location="cpu", weights_only=False)
        resume_step = int(_pre.get("step", 0))
        if resume_step >= n_steps:
            log(f"  [{tag}] resume ckpt already COMPLETE at s{resume_step} — "
                f"returning the saved final state")
            return {"sd": {k: v.clone() for k, v in _pre["model"].items()},
                    "history": _pre.get("history", []), "steps_ran": n_steps,
                    "seed": BASE_SEED, "device": "resumed (final state)",
                    "devices": ["resumed"], "n_chunks": 0,
                    "chunk_table": [], "theta0_norm": None}
    set_seed(BASE_SEED)             # the e040 rule: INIT is the only seed
                                    # axis; init on CPU, then device moves
    net = TinyGPT(GB.G1B_CFG)
    assert net.num_params() == GB.G1B_PARAMS, \
        f"base param count {net.num_params()} != {GB.G1B_PARAMS}"
    theta0 = flat_params_cpu(net)
    parked, n_chunks, chunk_table, devices = False, 0, [], []
    hist: list = []
    steps_done = resume_step
    while steps_done < n_steps:
        n_chunks += 1
        dev = next_dev(f"{tag}-chunk{n_chunks}", parked)
        parked = parked or dev.type == "cpu"
        # -10 s headroom: train_model checks its budget only at eval points
        # (every 250 steps ~ a few s on GPU) — worst-case burst stays < 90 s
        cap = (TRAIN_CAP_GPU - 10.0) if dev.type == "cuda" else TRAIN_CAP_CPU
        net = net.to(dev)
        common.DEVICE = str(dev)
        devices.append(str(dev))
        t_start = time.time()
        hist = train_model(net, corpus, steps=n_steps, lr=BASE_LR,
                           batch_size=BASE_BS, max_seconds=cap,
                           eval_every=BASE_EVAL_EVERY, ckpt=resume_ck,
                           warmup=BASE_WARMUP)
        steps_done = int(hist[-1]["step"]) if hist else resume_step
        chunk_table.append({"chunk": n_chunks, "device": str(dev),
                            "seconds": round(time.time() - t_start, 1),
                            "steps_done": steps_done, "capped":
                            bool(steps_done < n_steps)})
        if steps_done >= n_steps:
            break
        if n_chunks >= 24:
            trims.append(f"{tag}: stopped at chunk {n_chunks} (cap-loop "
                         f"guard) at step {steps_done} of {n_steps}")
            break
        if not SMOKE:
            log(f"[owner envelope] cooldown {COOLDOWN_S:.0f}s before "
                f"{tag} chunk {n_chunks + 1}")
            cooldown(COOLDOWN_S)
        if torch.cuda.is_available():
            torch.cuda.empty_cache()
    common.DEVICE = "cpu"
    net = net.cpu()
    net.eval()
    sd_cpu = {k: v.detach().clone() for k, v in net.state_dict().items()}
    return {"sd": sd_cpu, "history": [
        {"step": h["step"], "train_loss": h["train_loss"],
         "val_loss": h["val_loss"]} for h in hist],
        "steps_ran": steps_done, "seed": BASE_SEED,
        "device": devices[0] if devices else "n/a", "devices": devices,
        "n_chunks": n_chunks, "chunk_table": chunk_table,
        "theta0_norm": float(torch.norm(theta0))}


def chunked_install(tag, net0, inst_x, inst_mask, anchor_full, train_ids,
                    g0_ids, r_eval_xy, zid, resume_ck: Path) -> dict:
    """E43.exposure VERBATIM arithmetic (Dmix: ix(16) install w/ name mask
    + aj(16) paired + rj(32) random; masked token-level union CE; AdamW
    (0.9,0.95) wd 0.1; lr 1e-3 x house cosine(total=1000, warmup 100);
    clip 1.0) in owner-envelope bursts with full-state resume."""
    name_bs, corp_bs, mix_random, lr = G1.NAME_BS, E43.CORP_BS, E43.MIX_RANDOM, E43.LR
    n_steps = INST_STEPS
    n_inst, n_anc = inst_x.shape[0], anchor_full.shape[0]
    state = {"step": 0, "traj": []}
    parked = False
    if resume_ck.exists():
        state = torch.load(resume_ck, map_location="cpu", weights_only=False)
        log(f"  [{tag}] RESUMED from {resume_ck.name} at step "
            f"{state['step']}/{n_steps}")
    # edge: a prior process already completed this training — return its
    # saved final state (bit-identical; no steps re-run)
    if int(state.get("step", 0)) >= n_steps:
        log(f"  [{tag}] resume ckpt already COMPLETE at s{state['step']} — "
            f"returning the saved final state")
        return {"sd": state["model"], "traj": state.get("traj", []),
                "steps_ran": n_steps, "seed": INST_GEN,
                "device": "resumed (final state)", "devices": ["resumed"],
                "n_chunks": state.get("n_chunks", 0),
                "chunk_table": state.get("chunk_table", []),
                "theta0_norm": None}
    net, opt, gen, evl = None, None, None, None
    theta0 = None
    n_chunks, chunk_table, devices = 0, [], []
    step = state["step"]
    while step < n_steps:
        n_chunks += 1
        dev = next_dev(f"{tag}-chunk{n_chunks}", parked)
        parked = parked or dev.type == "cpu"
        cap = TRAIN_CAP_GPU if dev.type == "cuda" else TRAIN_CAP_CPU
        if net is None:
            net = copy.deepcopy(net0).to(dev)
            net.train()
            opt = torch.optim.AdamW(net.parameters(), lr=lr, betas=(0.9, 0.95),
                                    weight_decay=0.1)
            gen = torch.Generator().manual_seed(INST_GEN)
            if resume_ck.exists():
                net.load_state_dict(state["model"])
                net.to(dev)
                net.train()
                opt.load_state_dict(state["opt"])
                gen.set_state(state["gen_state"])
                step = state["step"]
            theta0 = flat_params_cpu(net)
            evl = copy.deepcopy(net0).to(CPU)
        else:
            _osd = opt.state_dict()
            net = net.to(dev)
            opt = torch.optim.AdamW(net.parameters(), lr=lr, betas=(0.9, 0.95),
                                    weight_decay=0.1)
            opt.load_state_dict(_osd)
            net.train()
        devices.append(str(dev))
        t_start = time.time()
        chunk_capped = False
        for step in range(step + 1, n_steps + 1):
            f = cosine_lr(step - 1, INST_TOTAL)          # house schedule
            for g in opt.param_groups:
                g["lr"] = lr * f
            ix = torch.randint(n_inst, (name_bs,), generator=gen)
            aj = torch.randint(n_anc, (corp_bs - mix_random,), generator=gen)
            rj = torch.randint(len(train_ids) - G1.BLOCK - 1, (mix_random,),
                               generator=gen)
            corp = torch.cat([anchor_full[aj],
                              torch.stack([train_ids[s: s + G1.BLOCK]
                                           for s in rj])], 0)
            nw = inst_x[ix]
            x = torch.cat([nw[:, :-1], corp[:, :-1]], 0).to(dev)
            y = torch.cat([nw[:, 1:], corp[:, 1:]], 0).to(dev)
            m = torch.zeros(name_bs + corp_bs, x.shape[1], dtype=torch.bool,
                            device=dev)
            m[:name_bs] = inst_mask[ix].to(dev)
            logits, _ = net(x)
            nll = F.cross_entropy(logits.reshape(-1, logits.shape[-1]),
                                  y.reshape(-1), reduction="none"
                                  ).view(x.shape[0], x.shape[1])
            nm = nll[:name_bs][m[:name_bs]]
            cm = nll[name_bs:]
            loss = (nm.sum() + cm.sum()) / (nm.numel() + cm.numel())
            opt.zero_grad(set_to_none=True)
            loss.backward()
            torch.nn.utils.clip_grad_norm_(net.parameters(), 1.0)
            opt.step()
            if (step % 100 == 0 or step == n_steps or step == 1
                    or SMOKE):
                sd_cpu = {k: v.detach().cpu().clone()
                          for k, v in net.state_dict().items()}
                evl.load_state_dict(sd_cpu)
                evl.eval()
                bz = G1.battery_cell(evl, g0_ids, zid)
                ce_r = G1.ce_fixed_cpu(evl, *r_eval_xy)
                state["traj"].append({"step": step, "g0_pz": bz["mean_pz"],
                                      "ce_r": ce_r,
                                      "ce_batch": float(loss.item()),
                                      "elapsed_s": round(time.time() - t_start, 1)})
                log(f"  [{tag}] s{step:4d} g0 {bz['mean_pz']:.4f} CE_R "
                    f"{ce_r:.4f} CE {float(loss.item()):.4f}")
            if (time.time() - t_start) > cap:
                log(f"  [{tag}] chunk {n_chunks}: burst cap {cap:.0f}s at "
                    f"s{step} — resume ckpt saved")
                chunk_capped = True
                break
            if dev.type == "cuda" and step % G1.MIDRUN_POLL_EVERY == 0:
                s = gpu_status()
                if s["mem_total"] > 0 and (s["mem_used"] > 0.85 * s["mem_total"]
                                           or s["temp"] > 80):
                    device_events.append({"tag": tag, "step": step,
                                          "event": "MID-RUN PAUSE (no "
                                                   "migration)", "status": s})
                    t_p = time.time()
                    midrun_pause_wait(tag)
                    t_start += time.time() - t_p
        chunk_table.append({"chunk": n_chunks, "device": str(dev),
                            "seconds": round(time.time() - t_start, 1),
                            "steps_done": step, "capped": chunk_capped})
        torch.save({"model": {k: v.detach().cpu()
                              for k, v in net.state_dict().items()},
                    "opt": opt.state_dict(), "gen_state": gen.get_state(),
                    "step": step, "traj": state["traj"],
                    "n_chunks": n_chunks, "chunk_table": chunk_table},
                   resume_ck)
        if step >= n_steps:
            break
        if n_chunks >= 24:
            trims.append(f"{tag}: stopped at chunk {n_chunks} (cap-loop "
                         f"guard) at step {step} of {n_steps}")
            break
        if not SMOKE:
            log(f"[owner envelope] cooldown {COOLDOWN_S:.0f}s before "
                f"{tag} chunk {n_chunks + 1}")
            cooldown(COOLDOWN_S)
        if torch.cuda.is_available():
            torch.cuda.empty_cache()
    net.eval()
    sd_cpu = {k: v.detach().cpu().clone() for k, v in net.state_dict().items()}
    return {"sd": sd_cpu, "traj": state["traj"], "steps_ran": step,
            "seed": INST_GEN, "device": devices[0] if devices else "n/a",
            "devices": devices, "n_chunks": n_chunks,
            "chunk_table": chunk_table,
            "theta0_norm": float(torch.norm(theta0)) if theta0 is not None
            else None}


