def phase_P5(p2: dict, p3: dict, p4: dict, rider_b: dict) -> dict:
    log("P5 — THE COMPOSITE + P-x64a scoring + the outputs")

    # ---- the rider-B verdict -------------------------------------------
    rb = rider_b["label"]
    if rb == "CARRY":
        rb_verdict = "24315-CARRIES-ON-B"
    elif rb == "LACK":
        rb_verdict = "24315-LACKS-ON-B"
    elif rb == "KNIFE":
        rb_verdict = ("KNIFE-ON-B (neither bar fires — the named "
                      "leftover, disclosed)")
