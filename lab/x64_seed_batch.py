# P3 — RIDER A: THE ANATOMY RE-SCREEN (zero model passes)
# ======================================================================
def anatomy_features_v2(draws: list, p0: dict) -> dict:
    """The seven NAMED new-class features, computed from ONE record + the
    shared pools ONLY (no model anywhere). Frozen at birth."""
    n = len(draws)
    M = len(p0["train_ids"]) - G1.BLOCK - 1      # the rj draw range
    ix = np.asarray([d["ix"] for d in draws], dtype=np.float64)   # (n,16)
    aj = np.asarray([d["aj"] for d in draws], dtype=np.float64)   # (n,16)
    rj = np.asarray([d["rj"] for d in draws], dtype=np.float64)   # (n,32)

    # J1 — within-step joint ix x aj
    rho_ixaj = float(np.corrcoef(ix.ravel(), aj.ravel())[0, 1])
    # J2 — within-step joint ix x rj (ix repeated to 12800)
    rho_ixrj = float(np.corrcoef(
        np.repeat(ix, 2, axis=1).ravel(), rj.ravel() / M)[0, 1])
    # J3 — rj-overlap: unordered pairs of overlapping spans
    off = np.sort(rj.ravel().astype(np.int64))
    reach = np.searchsorted(off, off + G1.BLOCK - 1, side="right") - 1
    overlap_pairs = int((reach - np.arange(off.size)).sum())
    lam = (off.size * (off.size - 1) / 2.0) * (2 * G1.BLOCK - 1) / M
    # O1 — the median of the ix draws
    med_ix = float(np.median(ix))
    # O2 — the first-100 order profile: range of per-step ix means
    means100 = ix[:100].mean(axis=1) if n >= 100 else ix.mean(axis=1)
    range100 = float(means100.max() - means100.min())
    # B1 — block drift of the ix histogram (4 blocks of 100)
    blocks_ix = (ix.reshape(4, -1) if n >= 400
                 else ix.reshape(1, -1))
    hists = [np.bincount(b.ravel().astype(np.int64), minlength=60)
             for b in blocks_ix]
    chi2_pairs = []
    for h1, h2 in zip(hists[:-1], hists[1:]):
        s = h1 + h2
        m = s > 0
        chi2_pairs.append(float(((h1[m] - h2[m]) ** 2 / s[m]).sum()))
    # (a degenerate <400-step record — smoke only — has a single block:
    #  no adjacent pairs; the feature reads 0.0 by convention, disclosed)
    drift_ix = float(max(chi2_pairs)) if chi2_pairs else 0.0
    # B2 — positional drift of rj (4 blocks; max |mean - M/2|)
    blocks_rj = (rj.reshape(4, -1) if n >= 400
                 else rj.reshape(1, -1))
    drift_rj = float(max(abs(b.mean() - M / 2.0) for b in blocks_rj))

    return {
        "n_steps": n, "M": M,
        "J1_rho_ixaj": rho_ixaj,
        "J2_rho_ixrj": rho_ixrj,
        "J3_overlap_pairs": overlap_pairs, "J3_lambda_analytic": lam,
        "O1_median_ix": med_ix,
        "O2_range100": range100,
        "B1_ixdrift": drift_ix,
        "B2_rjdrift": drift_rj,
    }


