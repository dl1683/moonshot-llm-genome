# THE FROZEN RULE (x45's match + separation, x52-certified; x63's port)
# ======================================================================
def match_pairs(arm_rows: list[dict], ref_rows: list[dict]):
    """x45's nearest-read pairing: each arm row -> the ref row at minimal
    |read difference| (many-to-one allowed); window 0.10."""
    in_win, oow = [], []
    for ar in arm_rows:
        best = min(ref_rows, key=lambda rr: abs(rr["read"] - ar["read"]))
        d_read = abs(best["read"] - ar["read"])
        pair = {"arm_tag": ar["tag"], "arm_read": ar["read"],
                "ref_tag": best["tag"], "ref_read": best["read"],
                "abs_d_read": d_read, "in_window": bool(d_read <=
                                                        MATCH_WINDOW)}
        for key in PRIMARY:
            av, rv = ar["corrs"].get(key), best["corrs"].get(key)
            pair[key] = {"arm": av, "ref": rv,
                         "d": (None if av is None or rv is None
                               else av - rv)}
        (in_win if pair["in_window"] else oow).append(pair)
    return in_win, oow


def score_side(in_win: list[dict]) -> dict:
    """x45's separation scoring on the primaries (floors required)."""
    scored = {}
    for key in PRIMARY:
        ds = [p[key]["d"] for p in in_win if p[key]["d"] is not None]
        n_none = sum(1 for p in in_win if p[key]["d"] is None)
        if not ds:
            scored[key] = {"n_pairs": 0, "n_none": n_none,
                           "separates": False, "note": "no valid pairs"}
            continue
        n_pos = sum(1 for d in ds if d > 0)
        n_neg = sum(1 for d in ds if d < 0)
        dominant = "+" if n_pos >= n_neg else "-"
        sign = max(n_pos, n_neg) / len(ds)
        mad = sum(abs(d) for d in ds) / len(ds)
        scored[key] = {
            "n_pairs": len(ds), "n_none": n_none,
            "dominant_sign": dominant,
            "sign_consistency": round(sign, 4),
            "mean_abs_d": round(mad, 6),
            "floor": FLOOR_CORR, "floor_kind": "absolute 0.15 (1/sqrt(59))",
            "separates": bool(sign >= SIGN_FRAC and mad >= FLOOR_CORR),
        }
    n_pairs = max((scored[k]["n_pairs"] for k in PRIMARY), default=0)
    both = (all(scored[k].get("separates") and
                scored[k]["dominant_sign"] == "-"
                for k in PRIMARY) and n_pairs >= POWER_FLOOR_N)
    return {"scored": scored, "n_in_window": len(in_win),
            "decorrelates": bool(both),
            "power": ("ok" if n_pairs >= POWER_FLOOR_N else
                      f"UNDERPOWERED (n={n_pairs}<{POWER_FLOOR_N})")}


def score_arm(arm_rows: list[dict], rulers: dict) -> dict:
    """The frozen rule on every ruler side; DECORRELATES iff the PRIMARY
    (anneal-ruler) side separates; the co-report sides named with the
    class caveat."""
    sides = {}
    for rname, rrows in rulers.items():
        in_win, oow = match_pairs(arm_rows, rrows)
        sc = score_side(in_win)
        sc["out_of_window"] = [{"arm_tag": p["arm_tag"],
                                "arm_read": p["arm_read"],
                                "ref_tag": p["ref_tag"],
                                "abs_d_read": p["abs_d_read"]}
                               for p in oow]
        sides[rname] = sc
    primary = sides.get("anneal")
    reads = [r["read"] for r in arm_rows]
    dead_all = bool(reads) and max(reads) <= 0.10
    if primary is None:
        verdict = "UNDERPOWERED (no primary side)"
    elif primary["power"] != "ok":
        if primary["n_in_window"] == 0 and dead_all:
            verdict = ("EXECUTED-DEAD (every arm read <= 0.10; no "
                       "in-window pairs — the menu failed to even "
                       "maintain the read; decorrelation vacuous)")
        else:
            verdict = primary["power"]
    else:
        verdict = "DECORRELATED" if primary["decorrelates"] else "COHERENT"
    cold_sep = any(s["decorrelates"] for k, s in sides.items()
                   if k.startswith("pooled"))
    return {"sides": sides, "verdict": verdict,
            "class_carried_cold_side": bool(cold_sep and
                                            verdict != "DECORRELATED")}


def compare_row(mine: dict, ref: dict) -> tuple[dict, bool]:
    """x45's row-comparison form (x59/x63's copy)."""
    cell, ok = {}, True
    for bn in ("g-12", "g0", "g+12"):
        cell[f"mean:{bn}"] = {
            "mine": mine["means"][bn], "committed": ref["means"][bn],
            "abs_diff": abs(mine["means"][bn] - ref["means"][bn])}
        ok &= cell[f"mean:{bn}"]["abs_diff"] <= READ_TOL
        cell[f"alive:{bn}"] = {
            "mine": mine["alive"][bn], "committed": ref["alive"][bn],
            "abs_diff": abs(mine["alive"][bn] - ref["alive"][bn])}
        ok &= cell[f"alive:{bn}"]["abs_diff"] == 0.0
    for pair in ("g-12|g0", "g0|g+12", "g-12|g+12"):
        cell[f"corr:{pair}"] = {
            "mine": mine["corrs"][pair], "committed": ref["corrs"][pair],
            "abs_diff": abs(mine["corrs"][pair] - ref["corrs"][pair])}
        ok &= cell[f"corr:{pair}"]["abs_diff"] <= CORR_TOL
    cell["pass"] = bool(ok)
    return cell, bool(ok)


# ======================================================================
# THE REPLAY CORE (CPU; x60/x59/x63's install leg VERBATIM + the
# automated re-execution proof of the three-proof restart standard)
# ======================================================================
def reexec_proof(tag: str, step_: int, read: float) -> None:
    """PROOF-2 AUTOMATION (the three-proof restart standard): if this
    tag+step row was already logged by a PREVIOUS execution (a kill +
    relaunch), the read must reproduce (2e-6 — the log's print quantum).
    Any mismatch aborts (a determinism break is a hard texture)."""
    if not LOG_PATH.exists():
        return
    pat = re.compile(rf"\[{re.escape(tag)}\] s\s*{step_} READ ([-0-9.]+)")
    try:
        txt = LOG_PATH.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return
    m = pat.search(txt)
    if m:
        prior = float(m.group(1))
        if abs(prior - read) > 2e-6:
            raise AssertionError(
                f"RE-EXEC PROOF FAILED {tag} s{step_}: prior {prior} vs "
                f"mine {read} — determinism break")
        metrics.setdefault("restart_proofs", {}).setdefault(
            tag, []).append({"step": step_, "prior": prior,
                             "mine": read, "bit_identical": True})


def install_leg(tag: str, start_sd: dict, steps: int, seed: int,
                p0: dict, inst_x, inst_mask, rungs: set,
                resume_ck: Path, end_ck: Path, host_id: int,
                dual_id: int | None, net0_class: str,
                e001_flat64: np.ndarray, keep_end: bool = True) -> dict:
    """x53's replay_install_leg VERBATIM via x60/x59/x63's copy (the
    e043-Dmix install arithmetic: batch 16+16+32, house cosine, masked
    union CE) with instrumented rungs + the end-state save + the
    automated re-execution proof on every re-executed rung row."""
    state = {"step": 0, "draws": [], "rows": {}}
    if resume_ck.exists():
        state = torch.load(resume_ck, map_location="cpu",
                           weights_only=False)
        log(f"  [{tag}] RESUMED at step {state['step']}/{steps} "
            f"({len(state['rows'])} rows restored)")
    if int(state.get("step", 0)) >= steps:
        # already complete: the end state is the resume ck's final model
        if end_ck.exists():
            end_sd = torch.load(end_ck, map_location="cpu",
                                weights_only=False)
        else:
            end_sd = {k: v.detach().cpu().clone()
                      for k, v in state["model"].items()}
        return {"rows": state["rows"], "draws": state["draws"],
                "steps_ran": steps, "end_sd": end_sd}

    net = G1.evl_load(start_sd).to(CPU)
    net.train()
    opt = torch.optim.AdamW(net.parameters(), lr=E43.LR, betas=(0.9, 0.95),
                            weight_decay=0.1)
    gen = torch.Generator().manual_seed(seed)
    if resume_ck.exists():
        net.load_state_dict(state["model"])
        net.train()
        opt.load_state_dict(state["opt"])
        gen.set_state(state["gen_state"])
    name_bs, corp_bs, mix_random = G1.NAME_BS, E43.CORP_BS, E43.MIX_RANDOM
    n_anc_full = p0["anchor_full"].shape[0]
    train_ids = p0["train_ids"]
    step = state["step"]
    rows: dict = state["rows"]
    draws: list = state["draws"]
    t_slice = time.time()
    n_caps = 0

    def rung_row(step_: int) -> None:
        sd_cpu = {k: v.detach().cpu().clone()
                  for k, v in net.state_dict().items()}
        row = instrument(p0, sd_cpu, f"{tag}_s{step_}", host_id,
                         e001_flat64, dual_id=dual_id)
        row.update({"step": step_, "provenance": "replay (CPU desk)",
                    "net0_class": net0_class, "leg": tag})
        rows[f"{tag}_s{step_}"] = row
        reexec_proof(tag, step_, row["read"])
        log(f"  [{tag}] s{step_:4d} READ {row['read']:.6f} | dual "
            f"{(row['dual']['means']['g0'] if row.get('dual')
                else float('nan')):.6f} | |W| "
            f"{row['write_norm']:.2f} inroom {row['in_room']:.3f} | CE_R "
            f"{row['ce_r']:.4f}")

    def save_resume() -> None:
        torch.save({"model": {k: v.detach().cpu().clone()
                              for k, v in net.state_dict().items()},
                    "opt": opt.state_dict(), "gen_state": gen.get_state(),
                    "step": step, "draws": draws, "rows": rows},
                   resume_ck)

    while step < steps:
        step += 1
        f = cosine_lr(step - 1, INST_TOTAL)       # the house schedule
        for g_ in opt.param_groups:
            g_["lr"] = E43.LR * f
        ix = torch.randint(inst_x.shape[0], (name_bs,), generator=gen)
        aj = torch.randint(n_anc_full, (corp_bs - mix_random,),
                           generator=gen)
        rj = torch.randint(len(train_ids) - G1.BLOCK - 1, (mix_random,),
                           generator=gen)
        draws.append({"step": step, "ix": ix.tolist(),
                      "aj": aj.tolist(), "rj": rj.tolist()})
        corp = torch.cat([p0["anchor_full"][aj],
                          torch.stack([train_ids[s: s + G1.BLOCK]
                                       for s in rj])], 0)
        nw = inst_x[ix]
        x = torch.cat([nw[:, :-1], corp[:, :-1]], 0)
        y = torch.cat([nw[:, 1:], corp[:, 1:]], 0)
        m = torch.zeros(name_bs + corp_bs, x.shape[1],
                        dtype=torch.bool)
        m[:name_bs] = inst_mask[ix]
        logits, _ = net(x)
        nll = F.cross_entropy(logits.reshape(-1, logits.shape[-1]),
                              y.reshape(-1), reduction="none"
                              ).view(x.shape[0], x.shape[1])
        nm = nll[:name_bs][m[:name_bs]]
        cm = nll[name_bs:]
        loss = (nm.sum() + cm.sum()) / (nm.numel() + cm.numel())
        opt.zero_grad(set_to_none=True)
        loss.backward()
        torch.nn.utils.clip_grad_norm_(net.parameters(), 1.0)
        opt.step()
        if step in rungs:
            rung_row(step)
        if (time.time() - t_slice) > TRAIN_CAP_CPU:
            save_resume()
            n_caps += 1
            metrics["envelope"].setdefault("slice_caps", []).append(
                {"tag": tag, "step": step, "t": utcnow()})
            log(f"  [{tag}] slice cap at s{step} — resume saved, "
                "continuing (CPU park convention)")
            t_slice = time.time()
    save_resume()
    sd_end = {k: v.detach().cpu().clone()
              for k, v in net.state_dict().items()}
    if keep_end:
        torch.save(sd_end, end_ck)
    log(f"  [{tag}] leg finished: {steps} steps, {n_caps} slice caps, "
        f"{len(rows)} instrument rows")
    del net, opt
    return {"rows": rows, "draws": draws, "steps_ran": step,
            "end_sd": sd_end}


