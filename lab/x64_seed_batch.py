BARS4 = [SIGN_FRAC, FLOOR_CORR, SIGN_FRAC, FLOOR_CORR]


def ndist(u: list, v: list) -> float | None:
    if any(x is None for x in u + v):
        return None
    return float(math.sqrt(sum(((x - y) / bar) ** 2
                               for x, y, bar in zip(u, v, BARS4))))


def clopper_pearson(k: int, n: int, alpha: float = 0.05):
    lo = 0.0 if k == 0 else float(beta_dist.ppf(alpha / 2, k, n - k + 1))
    hi = 1.0 if k == n else float(beta_dist.ppf(1 - alpha / 2, k + 1,
                                                n - k))
    return lo, hi


