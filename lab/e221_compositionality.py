def avg_ranks(v: list[float]) -> list[float]:
    """Average ranks (1-based), exact under ties."""
    order = sorted(range(len(v)), key=lambda i: v[i])
    r = [0.0] * len(v)
    i = 0
    while i < len(order):
        j = i
        while j + 1 < len(order) and v[order[j + 1]] == v[order[i]]:
            j += 1
        avg = (i + j) / 2.0 + 1.0
        for k in range(i, j + 1):
            r[order[k]] = avg
        i = j + 1
    return r


def _pearson(xs, ys) -> float | None:
    n = len(xs)
    if n < 2:
        return None
    mx, my = sum(xs) / n, sum(ys) / n
    sxx = sum((x - mx) ** 2 for x in xs)
    syy = sum((y - my) ** 2 for y in ys)
    if sxx <= 0 or syy <= 0:
        return None
    sxy = sum((x - mx) * (y - my) for x, y in zip(xs, ys))
    return sxy / (sxx * syy) ** 0.5


def spearman(xs: list[float], ys: list[float]) -> float | None:
    """Spearman rho = Pearson on average ranks (exact under ties)."""
    if len(xs) != len(ys) or len(xs) < 2:
        return None
    return _pearson(avg_ranks(xs), avg_ranks(ys))


def _mean(v):
    return sum(v) / len(v) if v else None


def _sd(v):
    if not v:
        return None
    m = _mean(v)
    return (sum((x - m) ** 2 for x in v) / len(v)) ** 0.5


def spearman_p(rho: float, n: int) -> float | None:
    """Two-sided p for Spearman rho via the t-approximation (co-report)."""
    if rho is None or n < 4 or abs(rho) >= 1.0:
        return None
    import math
    t = abs(rho) * math.sqrt((n - 2) / (1.0 - rho * rho))
    from math import erf
    p = 2.0 * (1.0 - 0.5 * (1.0 + erf(t / 2.0 ** 0.5)))
    return p


def chi2_sf(k: int, x: float) -> float | None:
    """Chi-square survival function for k in {2, 3} (the KW co-report)."""
    import math
    if x < 0:
        return None
    if k == 2:
        return math.exp(-x / 2.0)
    if k == 3:
        return math.erfc(math.sqrt(x / 2.0)) \
            + math.sqrt(2.0 * x / math.pi) * math.exp(-x / 2.0)
    return None


def ols(X: np.ndarray, y: np.ndarray) -> dict:
    """Plain OLS via lstsq: betas, fitted, resid, R2, adj-R2, resid SD."""
    beta, *_ = np.linalg.lstsq(X, y, rcond=None)
    fitted = X @ beta
    resid = y - fitted
    n, p = X.shape
    ss_res = float(resid @ resid)
    ss_tot = float(((y - y.mean()) ** 2).sum())
    r2 = 1.0 - ss_res / ss_tot
    adj = 1.0 - (1.0 - r2) * (n - 1) / (n - p)
    dof = n - p
    return {"beta": beta, "fitted": fitted, "resid": resid, "r2": r2,
            "adj_r2": adj, "ss_res": ss_res, "ss_tot": ss_tot,
            "resid_sd": float(ss_res / dof) ** 0.5, "dof": dof}


def fam_design(fams: list[str]) -> np.ndarray:
    """[1, 5 family dummies (ref = lang)] — the family block alone."""
    cols = [np.ones(len(fams))]
    for f in FAMILY6_ORDER:
        if f == REF_FAMILY:
            continue
        cols.append(np.array([1.0 if g == f else 0.0 for g in fams]))
    return np.column_stack(cols)


def design(fams: list[str], height_cols: list[np.ndarray]) -> np.ndarray:
    """[1, 5 family dummies, *height_cols]."""
    X = fam_design(fams)
    for c in height_cols:
        X = np.column_stack([X, c])
    return X


def one_way(values: list[float], labels: list[str]) -> dict:
    """One-way layout: class means, SS/MS between and within, the ratio,
    eta^2, and the Kruskal-Wallis H (tie-corrected; co-report)."""
    classes = sorted(set(labels))
    n = len(values)
    grand = _mean(values)
    by_class = {c: [v for v, g in zip(values, labels) if g == c]
                for c in classes}
    ss_b = sum(len(by_class[c]) * (_mean(by_class[c]) - grand) ** 2
               for c in classes)
    ss_w = sum((v - _mean(by_class[g])) ** 2
               for v, g in zip(values, labels))
    c_count = len(classes)
    df_b, df_w = c_count - 1, n - c_count
    ms_b = ss_b / df_b if df_b > 0 else None
    ms_w = ss_w / df_w if df_w > 0 else None
    ratio = ms_b / ms_w if (ms_b is not None and ms_w not in (None, 0)) else None
    # Kruskal-Wallis H with tie correction
    ranks = avg_ranks(values)
    h_raw = (12.0 / (n * (n + 1))) * sum(
        len(by_class[c]) * (_mean([r for r, g in zip(ranks, labels)
                                   if g == c]) - (n + 1) / 2.0) ** 2
        for c in classes)
    tie_term = 0.0
    ordered = sorted(values)
    i = 0
    while i < n:
        j = i
        while j + 1 < n and ordered[j + 1] == ordered[i]:
            j += 1
        t = j - i + 1
        if t > 1:
            tie_term += t ** 3 - t
        i = j + 1
    corr = 1.0 - tie_term / (n ** 3 - n) if n > 1 else 1.0
    h = h_raw / corr if corr > 0 else None
    return {
        "classes": classes,
        "n": n,
        "grand_mean": grand,
        "class_n": {c: len(by_class[c]) for c in classes},
        "class_mean": {c: _mean(by_class[c]) for c in classes},
        "class_sd": {c: _sd(by_class[c]) if len(by_class[c]) > 1 else 0.0
                     for c in classes},
        "ss_between": ss_b, "ss_within": ss_w,
        "df_between": df_b, "df_within": df_w,
        "ms_between": ms_b, "ms_within": ms_w,
        "ratio_ms": ratio,
        "eta2": ss_b / (ss_b + ss_w) if (ss_b + ss_w) > 0 else None,
        "kruskal_wallis_h": h,
        "kw_p": chi2_sf(df_b, h) if h is not None else None,
    }


def git_record() -> dict:
    """The records chain's git provenance (G_RECORDS)."""
    def _git(*args) -> str:
        try:
            return subprocess.run(
                ["git", *args], cwd=str(common.REPO), capture_output=True,
                text=True, timeout=30).stdout.strip()
        except Exception as e:                            # noqa: BLE001
            return f"unavailable ({e})"
    chain = ["runs/e214/metrics.json", "runs/e214/journal.json",
             "runs/e215/metrics.json", "runs/e216/metrics.json"]
    return {
        "head": _git("rev-parse", "HEAD"),
        "records_commits": {c: _git("log", "-1", "--format=%h %ad",
                                    "--date=short", "--", c) for c in chain},
        "dirty_records": [c for c in chain
                          if _git("status", "--porcelain", "--", c) != ""],
    }


