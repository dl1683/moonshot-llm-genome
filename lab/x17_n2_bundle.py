@torch.no_grad()
def last_logits(net, ids: torch.Tensor, bs: int = 30) -> np.ndarray:
    """x16's read convention: last-position logits, fp32 forward, fp64
    cast downstream."""
    net.eval()
    outs = []
    for i in range(0, ids.shape[0], bs):
        lg, _ = net(ids[i:i + bs])
        outs.append(lg[:, -1, :].clone())
    return torch.cat(outs).numpy().astype(np.float64)


def softmax64(L: np.ndarray) -> np.ndarray:
    z = L - L.max(axis=1, keepdims=True)
    e = np.exp(z)
    return e / e.sum(axis=1, keepdims=True)


def binom_p_two_sided(k: int, n: int) -> float:
    """Exact two-sided binomial sign test (symmetric-tail, P=0.5) —
    x16's VERBATIM form."""
    if n <= 0:
        return 1.0
    lo, hi = min(k, n - k), max(k, n - k)
    denom = n * math.log(2.0)
    p = 0.0
    for i in range(0, lo + 1):
        p += math.exp(math.lgamma(n + 1) - math.lgamma(i + 1)
                      - math.lgamma(n - i + 1) - denom)
    for i in range(hi, n + 1):
        p += math.exp(math.lgamma(n + 1) - math.lgamma(i + 1)
                      - math.lgamma(n - i + 1) - denom)
    return min(max(p, 0.0), 1.0)


def skew_g1(x: np.ndarray) -> float:
    m = x.mean()
    d = x - m
    m2 = float((d ** 2).mean())
    if m2 <= 0.0:
        return 0.0
    return float((d ** 3).mean()) / m2 ** 1.5


def battery_effect(Lb: np.ndarray, Lt: np.ndarray, zid: int) -> dict:
    """x16's per-context battery read (definitions VERBATIM; summaries
    only — no raw value arrays, disclosed)."""
    n = Lb.shape[0]
    top1b = Lb.argmax(axis=1)
    top1t = Lt.argmax(axis=1)
    sb, st = np.sort(Lb, axis=1), np.sort(Lt, axis=1)
    mb = sb[:, -1] - sb[:, -2]
    mt = st[:, -1] - st[:, -2]
    dm = mt - mb
    pb, pt = softmax64(Lb), softmax64(Lt)
    idx = np.arange(n)
    Hb = -(pb * np.log(np.clip(pb, 1e-300, None))).sum(axis=1)
    Ht = -(pt * np.log(np.clip(pt, 1e-300, None))).sum(axis=1)
    dH = Ht - Hb
    dpw = pt[idx, top1b] - pb[idx, top1b]
    dlog_z = Lt[:, zid] - Lb[:, zid]
    dlog_mean = (Lt - Lb).mean(axis=1)
    dbias_z = dlog_z - dlog_mean
    stable = top1b == top1t
    squeeze = dm < -0.10 * np.maximum(mb, 1e-12)
    neg = int((dm < 0).sum())
    pos = int((dm > 0).sum())
    nzc = neg + pos
    return {
        "n_contexts": int(n),
        "top1_stability": float(stable.mean()),
        "flip_frac": float((~stable).mean()),
        "squeeze_frac": float(squeeze.mean()),
        "flip_or_squeeze_frac": float(((~stable) | squeeze).mean()),
        "dmargin": {
            "mean": float(dm.mean()), "median": float(np.median(dm)),
            "std": float(dm.std()), "skew_g1": skew_g1(dm),
            "mean_abs": float(np.abs(dm).mean()),
            "neg_share_of_nonzero": (neg / nzc) if nzc else 0.5,
            "sign_test_p_two_sided": binom_p_two_sided(neg, nzc)},
        "dentropy": {"mean": float(dH.mean()),
                     "median": float(np.median(dH)),
                     "std": float(dH.std())},
        "dp_winner": {"mean": float(dpw.mean()),
                      "frac_negative": float((dpw < 0).mean())},
        "z_bias_excess": {"mean": float(dbias_z.mean()),
                          "frac_positive": float((dbias_z > 0).mean())},
        "dlog_z_mean": float(dlog_z.mean()),
    }


def inroom_frac(room: SRCT, v64: np.ndarray) -> float:
    vn = float(np.linalg.norm(v64))
    if vn == 0.0:
        return 0.0
    return float(np.linalg.norm(room.project(v64)) / vn)


def inroom_energy_share(room: SRCT, v64: np.ndarray) -> float:
    """x15's G_INROOM_SCALED exact form: ||Pv||^2 / ||v||^2 (the SCALED
    arms' gate; the fp32 injection layer's rounding noise lands at ~1e-9
    NORM fraction == ~1e-18 ENERGY fraction — x15's committed 2.35e-18
    class; the smoke caught the units mismatch and this is the repair,
    disclosed in the commit)."""
    e = float(v64 @ v64)
    if e == 0.0:
        return 0.0
    p = room.project(v64)
    return float((p @ p) / e)


