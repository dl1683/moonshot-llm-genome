def u_dir_of(draws: dict, tag: str, room_: SRCT) -> np.ndarray:
    """Deterministically rebuild a draw's unit direction from its
    registered seed (kept for provenance/regeneration; the probe itself
    uses the in-session u_dirs)."""
    shrng = np.random.default_rng(draws[tag]["seed"])
    r_raw = shrng.standard_normal(N_PARAMS)
    p_raw = room_.project(r_raw)
    return p_raw / float(np.linalg.norm(p_raw))


