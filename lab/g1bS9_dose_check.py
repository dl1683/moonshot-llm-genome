class OwnerWindowShut(RuntimeError):
    pass


def _poll() -> dict:
    return gpu_status()


def wait_gpu_owner(tag: str) -> torch.device:
    """The launch gate: gpu_ok() + a double-poll 5 s apart (no new launches
    above 80 C; util/mem inside the common ceilings); honest stop after
    GPU_WAIT_MAX of no windows."""
    if not torch.cuda.is_available():
        device_events.append({"tag": tag, "event": "NO CUDA",
                              "t": NOW()})
        raise OwnerWindowShut("no CUDA device visible — stopping honestly "
                              "(the 10M legs are not CPU-viable in burst)")
    waited = 0.0
    while True:
        s1_ = _poll()
        ok1 = gpu_ok()
        if ok1 and s1_["temp"] <= 80.0:
            time.sleep(5.0)
            s2_ = _poll()
            if gpu_ok() and s2_["temp"] <= 80.0:
                return torch.device("cuda")
            waited += 5.0
        else:
            time.sleep(20.0)
            waited += 20.0
        if waited >= GPU_WAIT_MAX:
            device_events.append({"tag": tag, "event": "WINDOW SHUT",
                                  "waited_s": waited, "t": NOW()})
            raise OwnerWindowShut(
                f"no GPU window in {waited:.0f}s for {tag} — stopping "
                f"honestly (resume ckpts + partial metrics hold the record)")


def midrun_guard(tag: str, step: int) -> None:
    """Mid-burst thermal poll (every 25 steps): PAUSE-AND-WAIT above 80 C —
    never migrate, never past 85 C."""
    if not torch.cuda.is_available():
        return
    s = _poll()
    if s["mem_total"] > 0 and (s["temp"] > 80.0
                               or s["mem_used"] > 0.85 * s["mem_total"]):
        device_events.append({"tag": tag, "step": step,
                              "event": "MID-RUN PAUSE (no migration)",
                              "status": s, "t": NOW()})
        while True:
            time.sleep(20.0)
            s2 = _poll()
            if s2["temp"] <= 78.0 and s2["mem_used"] <= 0.8 * s2["mem_total"]:
                device_events.append({"tag": tag, "step": step,
                                      "event": "MID-RUN RESUME",
                                      "status": s2, "t": NOW()})
                return


def md5_file(p: Path) -> str:
    h = hashlib.md5()
    with open(p, "rb") as f:
        for blk in iter(lambda: f.read(1 << 20), b""):
            h.update(blk)
    return h.hexdigest()


def flat_params(net) -> torch.Tensor:
    return torch.cat([p.detach().reshape(-1) for p in net.parameters()])


