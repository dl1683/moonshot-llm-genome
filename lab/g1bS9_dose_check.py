# ======================================================================
# THE ANNEAL RUNNER (g1bS5's consolidate arithmetic, fresh from the root;
# envelope: bursts <= 150 s, cooldowns 45 s, chunk-resumable)
# ======================================================================
def run_anneal(net0_sd, pool_x, pool_mask, anchor, train_ids,
               f_eval_ids, r_eval_xy, zid) -> dict:
    tag = "ANNEAL"
    steps = ANNEAL_STEPS
    n_pool, n_anc = pool_x.shape[0], anchor.shape[0]
    resume_ck = RD / "g1bS9_anneal_resume.pt"
    RESUME_EVERY = 50 if not SMOKE else 4
    chunk_table = []
    step, traj = 0, []
    net = opt = gen = None
    n_chunks = 0
    active_s = 0.0
    if resume_ck.exists():
        _pre = torch.load(resume_ck, map_location="cpu", weights_only=False)
        if int(_pre.get("step", 0)) >= steps:
            log(f"  [{tag}] resume ckpt already COMPLETE at "
                f"s{_pre['step']} — returning the saved final state")
            return {"sd": {k: v.clone() for k, v in _pre["model"].items()},
                    "traj": _pre.get("traj", []), "steps_ran": steps,
                    "n_chunks": _pre.get("n_chunks", 0),
                    "chunk_table": _pre.get("chunk_table", []),
                    "resumed_final": True}
    net0 = G1.evl_load(net0_sd)        # the plain eval-loadable start net
    while step < steps:
        n_chunks += 1
        dev = wait_gpu_owner(f"{tag}-chunk{n_chunks}")
        t_burst = time.time()
        burst_rec = {"tag": f"{tag}-chunk{n_chunks}", "t": NOW(),
                     "temp_start_c": gpu_status()["temp"]}
        if net is None:
            net = copy.deepcopy(net0).to(dev)
            net.train()
            opt = torch.optim.AdamW(net.parameters(), lr=ANNEAL_LR,
                                    betas=(0.9, 0.95), weight_decay=0.1)
            gen = torch.Generator().manual_seed(ANNEAL_SEED)
            if resume_ck.exists():
                state = torch.load(resume_ck, map_location="cpu",
                                   weights_only=False)
                net.load_state_dict(state["model"])
                net.to(dev); net.train()
                opt.load_state_dict(state["opt"])
                gen.set_state(state["gen_state"])
                step, traj = state["step"], state.get("traj", [])
                active_s = state.get("active_s", 0.0)
                log(f"  [{tag}] RESUMED at s{step}/{steps}")
        else:
            net.train()
        evl = copy.deepcopy(net0).to(dev)
        capped = False
        for step in range(step + 1, steps + 1):
            # g1bS5_consolidate's draws VERBATIM (16 pool + 8 anchor + 8
            # random, name-masked union CE)
            ix = torch.randint(n_pool, (16,), generator=gen)
            aj = torch.randint(n_anc, (8,), generator=gen)
            rj = torch.randint(len(train_ids) - G1.BLOCK - 1, (8,),
                               generator=gen)
            nw = pool_x[ix].to(dev)
            anc = torch.cat([anchor[aj],
                             torch.stack([train_ids[s: s + G1.BLOCK]
                                          for s in rj])], 0).to(dev)
            x = torch.cat([nw[:, :-1], anc[:, :-1]], 0)
            y = torch.cat([nw[:, 1:], anc[:, 1:]], 0)
            m = torch.zeros(32, x.shape[1], dtype=torch.bool, device=dev)
            m[:16] = pool_mask[ix].to(dev)
            logits, _ = net(x)
            nll = F.cross_entropy(logits.reshape(-1, logits.shape[-1]),
                                  y.reshape(-1), reduction="none"
                                  ).view(x.shape[0], x.shape[1])
            nm = nll[:16][m[:16]]
            cm = nll[16:]
            loss = (nm.sum() + cm.sum()) / (nm.numel() + cm.numel())
            opt.zero_grad(set_to_none=True)
            loss.backward()
            torch.nn.utils.clip_grad_norm_(net.parameters(), 1.0)
            opt.step()
            if step % ANNEAL_EVAL_EVERY == 0 or step == steps or \
                    (time.time() - t_burst) > TRAIN_CAP_GPU:
                evl.load_state_dict(net.state_dict())
                evl.eval()
                bz = G1.battery_cell(evl, f_eval_ids.to(dev), zid)
                ce_r = G1.ce_fixed_cpu(evl, r_eval_xy[0].to(dev),
                                       r_eval_xy[1].to(dev))
                traj.append({"step": step, "install60_g0_pz": bz["mean_pz"],
                             "ce_r": ce_r,
                             "elapsed_s": round(active_s + time.time()
                                                - t_burst, 1)})
                log(f"  [{tag}] s{step:4d} g0 {bz['mean_pz']:.4f} CE_R "
                    f"{ce_r:.4f} ({traj[-1]['elapsed_s']:.0f}s)")
            if step % RESUME_EVERY == 0 or step == steps:
                torch.save({"model": {k: v.detach().cpu()
                                      for k, v in net.state_dict().items()},
                            "opt": opt.state_dict(),
                            "gen_state": gen.get_state(),
                            "step": step, "traj": traj,
                            "active_s": active_s + time.time() - t_burst,
                            "n_chunks": n_chunks}, resume_ck)
            if (time.time() - t_burst) > TRAIN_CAP_GPU:
                log(f"  [{tag}] chunk {n_chunks}: burst cap "
                    f"{TRAIN_CAP_GPU:.0f}s at s{step} — resume ckpt saved")
                capped = True
                break
            if step % 25 == 0:
                midrun_guard(tag, step)
        secs = round(time.time() - t_burst, 1)
        active_s += secs
        burst_rec.update({"seconds": secs, "steps_done": step,
                          "capped": capped,
                          "temp_end_c": gpu_status()["temp"],
                          "violation": False})
        envelope_bursts.append(burst_rec)
        chunk_table.append({k: burst_rec[k] for k in
                            ("tag", "seconds", "steps_done", "capped")})
        if step >= steps:
            break
        if n_chunks >= 24:
            log(f"  [{tag}] cap-loop guard at chunk {n_chunks} (s{step})")
            break
        cooldown(COOLDOWN_S)
        del evl
        if torch.cuda.is_available():
            torch.cuda.empty_cache()
    net.eval()
    sd_cpu = {k: v.detach().cpu().clone() for k, v in net.state_dict().items()}
    del net, net0
    if torch.cuda.is_available():
        torch.cuda.empty_cache()
    return {"sd": sd_cpu, "traj": traj, "steps_ran": step,
            "n_chunks": n_chunks, "chunk_table": chunk_table}


# ======================================================================
# THE WASH RUNNER (e322's committed unbiased wash on the 10M host; the
# armed net trains, the armed twin reads — the wall settles before every
# read; both arms share the seed-10902 draw sequence; G-INPUTS md5s)
# ======================================================================
def run_wash(tag: str, net0, anchor, train_ids, itos, r_eval_xy,
             gm12_ids, g0_ids, zid, resume_ck: Path) -> dict:
    ckpt_set = set(WASH_PANELS)
    n_steps = WASH_STEPS
    n_anc = anchor.shape[0]
    step, traj, sds, x_hashes = 0, [], {}, {}
    zeph_checks = 0
    net = opt = gen = None
    wall_R = getattr(net0, "R", None)
    n_chunks, chunk_table = 0, []
    active_s = 0.0
    if resume_ck.exists():
        _pre = torch.load(resume_ck, map_location="cpu", weights_only=False)
        if int(_pre.get("step", 0)) >= n_steps:
            log(f"  [{tag}] resume ckpt already COMPLETE — returning saved")
            return {"sds": _pre["sds"], "traj": _pre.get("traj", []),
                    "steps_ran": n_steps, "x_hashes": _pre.get(
                        "x_hashes", {}),
                    "zeph_violations": _pre.get("zeph", 0),
                    "n_chunks": _pre.get("n_chunks", 0),
                    "chunk_table": _pre.get("chunk_table", []),
                    "wall_R": wall_R, "resumed_final": True}
    while step < n_steps:
        n_chunks += 1
        dev = wait_gpu_owner(f"{tag}-chunk{n_chunks}")
        t_burst = time.time()
        burst_rec = {"tag": f"{tag}-chunk{n_chunks}", "t": NOW(),
                     "temp_start_c": gpu_status()["temp"]}
        if net is None:
            net = copy.deepcopy(net0).to(dev)
            net.train()
            opt = torch.optim.AdamW(net.parameters(), lr=WASH_LR,
                                    betas=(0.9, 0.95), weight_decay=0.1)
            gen = torch.Generator().manual_seed(WASH_SEED)
            theta0 = flat_params(net0).to(dev)   # the arm's displacement
                                                 # origin (the PRISTINE
                                                 # committed start; net0
                                                 # never trains — stable
                                                 # across resumes)
            if resume_ck.exists():
                state = torch.load(resume_ck, map_location="cpu",
                                   weights_only=False)
                net.load_state_dict(state["model"])
                net.to(dev); net.train()
                opt.load_state_dict(state["opt"])
                gen.set_state(state["gen_state"])
                step = state["step"]
                traj, sds = state.get("traj", []), state.get("sds", {})
                x_hashes = state.get("x_hashes", {})
                zeph_checks = state.get("zeph", 0)
                active_s = state.get("active_s", 0.0)
                log(f"  [{tag}] RESUMED at s{step}/{n_steps}")
        else:
            net.train()
        theta0 = flat_params(net0).to(dev)     # re-derived every chunk (the
                                               # pristine committed start;
                                               # stable — net0 never trains)
        evl = copy.deepcopy(net0).to(dev)      # the ARMED eval twin

        def panel(step_: int) -> None:
            """the light panel through the ARMED twin (the wall settles
            before every read — e322/e338's convention)."""
            sd_cpu = {k: v.detach().cpu().clone()
                      for k, v in net.state_dict().items()}
            evl.load_state_dict(sd_cpu)
            evl.eval()
            gz = G1.battery_cell(evl, gm12_ids.to(dev), zid)
            gz0 = G1.battery_cell(evl, g0_ids.to(dev), zid)
            ce_r = G1.ce_fixed_cpu(evl, r_eval_xy[0].to(dev),
                                   r_eval_xy[1].to(dev))
            d_raw = float(torch.norm(flat_params(net) - theta0))
            traj.append({"step": step_, "g_m12_mean_pz": gz["mean_pz"],
                         "g0_mean_pz": gz0["mean_pz"],
                         "frac_argmax_z": gz["frac_argmax_z"],
                         "ce_r": ce_r,
                         "disp_raw": d_raw, "R": wall_R,
                         "d_proj": min(d_raw, wall_R) if wall_R else None,
                         "elapsed_s": round(active_s + time.time()
                                            - t_burst, 1)})
            r_ = traj[-1]
            log(f"  [{tag}] s{r_['step']:3d} RULER g-12 "
                f"{r_['g_m12_mean_pz']:.4f} | g0 {r_['g0_mean_pz']:.4f} | "
                f"CE_R {r_['ce_r']:.4f} | |d| {r_['disp_raw']:.4f}"
                + ("  <-- BELOW 0.05" if r_["step"] > 0
                   and r_["g_m12_mean_pz"] < READ_BAR else ""))

        if step == 0:
            panel(0)                            # t0 = the committed read
            sds[0] = {k: v.detach().cpu().clone()
                      for k, v in net.state_dict().items()}
        capped = False
        for step in range(step + 1, n_steps + 1):
            # e322's run_wash draws VERBATIM (aj 16 of the 60 install
            # anchors, rj 16 random)
            aj = torch.randint(n_anc, (16,), generator=gen)
            rj = torch.randint(len(train_ids) - G1.BLOCK - 1, (16,),
                               generator=gen)
            anc = anchor[aj]
            rnd = torch.stack([train_ids[s: s + G1.BLOCK] for s in rj])
            for w in rnd:                      # name-free VERIFY (hard-fail)
                txt = "".join(itos[int(c)] for c in w[:64]) + \
                      "".join(itos[int(c)] for c in w[192:])
                if "ZEPH" in txt:
                    zeph_checks += 1
            x = torch.cat([anc[:, :-1], rnd[:, :-1]], 0)
            y = torch.cat([anc[:, 1:], rnd[:, 1:]], 0)
            x_hashes[step] = hashlib.md5(
                x.contiguous().numpy().tobytes()).hexdigest()
            xd, yd = x.to(dev), y.to(dev)
            logits, _ = net(xd)                # <- the wall projects here
            loss = F.cross_entropy(logits.reshape(-1, logits.shape[-1]),
                                   yd.reshape(-1))
            opt.zero_grad(set_to_none=True)
            loss.backward()
            torch.nn.utils.clip_grad_norm_(net.parameters(), 1.0)
            opt.step()
            if step in ckpt_set:
                panel(step)
                if step in (1, WASH_STEPS):
                    sds[step] = {k: v.detach().cpu().clone()
                                 for k, v in net.state_dict().items()}
            if (time.time() - t_burst) > TRAIN_CAP_GPU:
                capped = True
                break
            if step % 25 == 0:
                midrun_guard(tag, step)
        # persist the resume (full state; bit-identical continuation)
        torch.save({"model": {k: v.detach().cpu().clone()
                              for k, v in net.state_dict().items()},
                    "opt": opt.state_dict(),
                    "gen_state": gen.get_state(), "step": step,
                    "traj": traj, "sds": {k: v for k, v in sds.items()},
                    "x_hashes": x_hashes, "zeph": zeph_checks,
                    "active_s": active_s + time.time() - t_burst,
                    "n_chunks": n_chunks, "chunk_table": chunk_table},
                   resume_ck)
        secs = round(time.time() - t_burst, 1)
        active_s += secs
        burst_rec.update({"seconds": secs, "steps_done": step,
                          "capped": capped,
                          "temp_end_c": gpu_status()["temp"],
                          "violation": False})
        envelope_bursts.append(burst_rec)
        chunk_table.append({k: burst_rec[k] for k in
                            ("tag", "seconds", "steps_done", "capped")})
        if step >= n_steps:
            break
        if n_chunks >= 24:
            log(f"  [{tag}] cap-loop guard at chunk {n_chunks}")
            break
        cooldown(COOLDOWN_S)
        del evl
        if torch.cuda.is_available():
            torch.cuda.empty_cache()
    return {"sds": sds, "traj": traj, "steps_ran": step,
            "x_hashes": x_hashes, "zeph_violations": zeph_checks,
            "n_chunks": n_chunks, "chunk_table": chunk_table,
            "wall_R": wall_R}


