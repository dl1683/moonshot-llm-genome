def softmax64(L: np.ndarray) -> np.ndarray:
    z = L - L.max(axis=1, keepdims=True)
    e = np.exp(z)
    return e / e.sum(axis=1, keepdims=True)


def z_excess(Lb: np.ndarray, Lt: np.ndarray, zid: int) -> dict:
    """x16's Z-bias excess: per-context [dlogit(Z) - mean dlogit]."""
    dz = Lt[:, zid] - Lb[:, zid]
    dm = (Lt - Lb).mean(axis=1)
    ex = dz - dm
    return {"mean": float(ex.mean()), "median": float(np.median(ex)),
            "std": float(ex.std()),
            "frac_positive": float((ex > 0).mean()),
            "values": ex.tolist()}


def battery_effect(Lb: np.ndarray, Lt: np.ndarray, zid: int) -> dict:
    """x16's per-context battery read, VERBATIM (stability, dmargin +
    sign test, dentropy, dp(winner), the Z-bias excess)."""
    n = Lb.shape[0]
    top1b = Lb.argmax(axis=1)
    top1t = Lt.argmax(axis=1)
    sb, st = np.sort(Lb, axis=1), np.sort(Lt, axis=1)
    mb = sb[:, -1] - sb[:, -2]
    mt = st[:, -1] - st[:, -2]
    dm = mt - mb
    pb, pt = softmax64(Lb), softmax64(Lt)
    idx = np.arange(n)
    Hb = -(pb * np.log(np.clip(pb, 1e-300, None))).sum(axis=1)
    Ht = -(pt * np.log(np.clip(pt, 1e-300, None))).sum(axis=1)
    dH = Ht - Hb
    dpw = pt[idx, top1b] - pb[idx, top1b]
    stable = top1b == top1t
    squeeze = dm < -0.10 * np.maximum(mb, 1e-12)
    flip_or_squeeze = (~stable) | squeeze
    neg = int((dm < 0).sum())
    pos = int((dm > 0).sum())
    nzc = neg + pos
    return {
        "n_contexts": int(n),
        "top1_stability": float(stable.mean()),
        "flip_frac": float((~stable).mean()),
        "squeeze_frac": float(squeeze.mean()),
        "flip_or_squeeze_frac": float(flip_or_squeeze.mean()),
        "dmargin": {"mean": float(dm.mean()),
                    "median": float(np.median(dm)),
                    "std": float(dm.std()), "skew_g1": skew_g1(dm),
                    "mean_abs": float(np.abs(dm).mean()),
                    "neg_share_of_nonzero": (neg / nzc) if nzc else 0.5,
                    "neg": neg, "pos": pos,
                    "sign_test_p_two_sided": binom_p_two_sided(neg, nzc),
                    "quantiles": quantiles(dm)},
        "dentropy": {"mean": float(dH.mean()),
                     "median": float(np.median(dH)),
                     "std": float(dH.std()), "skew_g1": skew_g1(dH),
                     "quantiles": quantiles(dH)},
        "dp_winner": {"mean": float(dpw.mean()),
                      "median": float(np.median(dpw)),
                      "std": float(dpw.std()),
                      "frac_negative": float((dpw < 0).mean()),
                      "quantiles": quantiles(dpw)},
        "z_bias_excess": z_excess(Lb, Lt, zid),
    }


