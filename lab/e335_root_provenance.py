def adjudicate(wash: dict) -> dict:
    traj = wash["traj"]
    reads = {r["step"]: r["g0_mean_pz"] for r in traj}
    t0 = reads[0]
    s100 = reads[max(reads)]
    retention = s100 / t0
    band = wash["band"]
    panel_steps = [s for s in WASH_PANELS if s > 0 and s in reads]
    first_below = next((s for s in panel_steps if reads[s] < READ_BAR), None)
    all_ge = all(reads[s] >= READ_BAR for s in panel_steps)

    if first_below is not None:
        verdict = "WASHES-OUT"
        clause = (f"the standing read fell below {READ_BAR} at wash panel "
                  f"s{first_below} (t0 {t0:.6f} -> s{first_below} "
                  f"{reads[first_below]:.6f}; s{max(reads)} {s100:.6f}; "
                  f"retention {retention:.4f})")
    elif all_ge and band["lo"] <= retention <= band["hi"]:
        verdict = "WASH-PROOF"
        clause = (f"the read >= {READ_BAR} at every panel (min "
                  f"{min(reads[s] for s in panel_steps):.6f}) with "
                  f"retention {retention:.4f} inside the installed-fact "
                  f"band [{band['lo']:.4f}, {band['hi']:.4f}]")
    elif all_ge:
        verdict = "PARTIAL-DECAY"
        clause = (f"the read >= {READ_BAR} at every panel but retention "
                  f"{retention:.4f} falls below the installed-fact band "
                  f"[{band['lo']:.4f}, {band['hi']:.4f}] — survival "
                  f"without the installed-fact class's kinetics")
    else:
        verdict = "TEXTURE"
        clause = "unreadable residue (see table)"

    adj = {
        "bars_verbatim": REGISTERED["bars_verbatim"],
        "operationalization": REGISTERED["operationalization"],
        "reads": {str(k): v for k, v in reads.items()},
        "t0": t0, "s_end": s100, "retention": retention,
        "first_panel_below_bar": first_below,
        "min_panel_read": min(reads[s] for s in panel_steps),
        "P-e335a": {"guess": REGISTERED["P-e335a"]["my_guess"],
                    "hit": (verdict == "WASHES-OUT")},
        "verdict": verdict,
        "clause": clause,
        "composite_order": "TEXTURE -> WASHES-OUT -> WASH-PROOF -> "
                           "PARTIAL-DECAY",
    }
    return adj


