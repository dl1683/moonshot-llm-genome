def main() -> None:
    log(f"E335 — THE ROOT'S PROVENANCE (smoke={SMOKE}) -> {RD}")
    metrics["birth_commit"] = git_head()
    write_partial("startup (bars + P-e335a registered, committed at "
                  "birth)")
    set_seed(33500)             # global init only; every RNG is its own

    # ---------------- P0: the protocol rebuild (bit-consistent) -----------
    corpus = CharCorpus(REPO / "data" / "input.txt", seed=1337)
    stoi, itos = corpus.stoi, corpus.itos
    zid = stoi["Z"]
    train_ids, val_ids = corpus.train, corpus.val
    train_text = "".join(itos[int(i)] for i in train_ids)
    val_text = "".join(itos[int(i)] for i in val_ids)
    corpus_zeph = train_text.count("ZEPH")
    metrics["gates"]["G_NAMEFREE"] = {
        "corpus_zeph_count": corpus_zeph, "pass": bool(corpus_zeph == 0)}

    import random
    host_occ = []
    for host in G1.HOSTS:
        for p in E43.find_occ(train_text, host):
            if p >= 280 and p + len(host) + G1.POST_CAP <= len(train_ids):
                host_occ.append((p, host))
    rng = random.Random(E43.SPLICE_RNG)
    rng.shuffle(host_occ)
    install_occ = host_occ[:60]
    mix = {"FLORIZEL": sum(1 for _, h in install_occ if h == "FLORIZEL"),
           "ELIZABETH": sum(1 for _, h in install_occ if h == "ELIZABETH")}
    metrics["gates"]["G_SPLICE"] = {"install_mix": mix,
                                    "pass": bool(mix == {"FLORIZEL": 19,
                                                         "ELIZABETH": 41})}
    assert metrics["gates"]["G_SPLICE"]["pass"], f"splice drift {mix}"

    bat_ids = {}
    for j in G1.GEOS:
        cs = [train_text[p - G1.PRE - j: p] for p, _ in install_occ]
        bat_ids[j] = torch.stack([corpus.encode(c) for c in cs])
    metrics["gates"]["G_BATTERY"] = {
        "shapes": {f"g{j:+d}": list(bat_ids[j].shape) for j in G1.GEOS},
        "pass": bool(list(bat_ids[-12].shape) == [60, G1.PRE - 12]
                     and list(bat_ids[0].shape) == [60, G1.PRE]
                     and list(bat_ids[12].shape) == [60, G1.PRE + 12])}
    assert metrics["gates"]["G_BATTERY"]["pass"], \
        f"battery drift {metrics['gates']['G_BATTERY']}"

    anchor_full = torch.stack([train_ids[p - G1.PRE: p - G1.PRE + G1.BLOCK]
                               for p, _ in install_occ])   # (60, 256)
    metrics["gates"]["G_ANCHORBANK"] = {
        "shape": list(anchor_full.shape),
        "note": "e322's wash anchor bank: the 60 original-host corpus "
                "windows (the install contexts' own corpus)",
        "pass": bool(anchor_full.shape == (60, G1.BLOCK))}

    r_eval_x, r_eval_y = G1.val_windows(val_ids, val_text, 60,
                                        G1.R_EVAL_SEED)
    r_eval_xy = (r_eval_x, r_eval_y)

    # ---------------- G_PARENTS: every artifact md5-bound ------------------
    parents = []
    for fname, bound in WALK_MD5.items():
        p = CKPT_DIR / fname
        ok = p.exists() and md5of(p) == bound
        parents.append({"file": f"runs/checkpoints/{fname}",
                        "md5": bound, "pass": bool(ok)})
    for label, path, bound in (
            ("g1c_root metrics", G1C_METRICS, G1C_METRICS_MD5),
            ("g1b metrics", G1B_METRICS, G1B_METRICS_MD5),
            ("g1bR metrics", G1BR_METRICS, G1BR_METRICS_MD5),
            ("e322 metrics", E322_METRICS, E322_METRICS_MD5),
            ("x32 metrics", X32_METRICS, X32_METRICS_MD5),
            ("x34 metrics", X34_METRICS, X34_METRICS_MD5),
            ("x35 metrics", X35_METRICS, X35_METRICS_MD5)):
        ok = path.exists() and md5of(path) == bound
        parents.append({"file": str(path.relative_to(REPO)).replace("\\", "/"),
                        "md5": bound, "pass": bool(ok)})
    metrics["gates"]["G_PARENTS"] = {
        "claim": "the root + every lineage artifact read is md5-bound "
                 "(frozen at birth)",
        "parents": parents,
        "pass": bool(all(x["pass"] for x in parents))}
    assert metrics["gates"]["G_PARENTS"]["pass"], \
        f"md5 bind failed: {[x for x in parents if not x['pass']]}"
    log(f"P0: G_PARENTS PASS ({len(parents)} artifacts md5-bound); "
        "G_NAMEFREE/G_SPLICE/G_BATTERY/G_ANCHORBANK gated")
    write_partial("P0 gated (md5 binds + battery rebuild)")

    # ---------------- CUT 1 -------------------------------------------------
    cut1 = phase_A(corpus, stoi, train_ids, val_ids, train_text, val_text,
                   bat_ids, r_eval_xy, zid)

    # ---------------- CUT 2 -------------------------------------------------
    wash = phase_B(corpus, stoi, train_ids, train_text, bat_ids, r_eval_xy,
                   zid, anchor_full, itos)
    metrics["cut2_wash"] = {
        "config": {"steps": WASH_STEPS, "seed": WASH_SEED,
                   "anchor_bank": "the 60 original-host windows",
                   "batch": f"{WASH_ANC_BS} anchors + {WASH_RND_BS} random",
                   "lr": WASH_LR, "betas": list(WASH_BETAS), "wd": WASH_WD,
                   "clip": WASH_CLIP, "panels": list(WASH_PANELS),
                   "start": "the BARE g1c root (no install, no ball)",
                   "net0_class": "ROOT (bare)",
                   "rig": "e322's run_wash arithmetic VERBATIM (the "
                          "committed 100-step unbiased wash convention)"},
        "traj": wash["traj"], "n_draws": len(wash["draws"]),
        "zeph_violations": wash["zeph"],
        "band": wash["band"], "taught_band": wash["taught_band"],
    }
    metrics["gates"]["G_WASHRIG"] = {
        "claim": "the wash rig is e322's committed convention (seed 10902, "
                 "60-anchor bank, 16+16, all-token CE, AdamW (0.9,0.95) "
                 "wd 0.1 lr 1e-3, clip 1.0, panels) with the one "
                 "registered read adaptation (battery g0; disclosed)",
        "name_free_guard_violations": wash["zeph"],
        "pass": bool(wash["zeph"] == 0)}
    write_partial("cut 2 (the wash discriminator) run")

    # ---------------- ADJUDICATION -------------------------------------------
    adj = adjudicate(wash)
    metrics["adjudication"] = adj
    metrics["gates"]["G_ENVELOPE"] = {
        "claim": "zero hard thermal violations; polls logged",
        "max_temp_c": max((r["temp"] for r in thermal_log), default=None),
        "hard_violations": sum(1 for r in thermal_log
                               if r["temp"] >= E261.TEMP_HARD),
        "pass": bool(all(r["temp"] < E261.TEMP_HARD for r in thermal_log))}
    gates_pass = all(bool(g.get("pass")) for g in metrics["gates"].values())
    if not gates_pass:
        adj["verdict"] = "TEXTURE"
        adj["clause"] = ("hard-gate failure: "
                         + ", ".join(k for k, g in metrics["gates"].items()
                                     if not g.get("pass"))
                         + " — nothing adjudicated (the lineage's abort "
                           "clause); tables verbatim")
        metrics["adjudication"] = adj
    metrics["status"] = ("SMOKE: nothing adjudicated" if SMOKE else
                         f"COMPLETE: {adj['verdict']}")

    make_png(cut1, wash, adj)
    metrics["git_head_final"] = git_head()
    metrics["date_completed"] = common.now_iso()
    write_partial("adjudicated + png written")
    write_report(cut1, wash, adj)
    if not SMOKE:
        try:
            import subprocess
            for f in ("REPORT.md", "e335_root_provenance.png",
                      "metrics.json"):
                subprocess.run(["git", "add", str(RD / f)], cwd=str(REPO),
                               timeout=10)
        except Exception:                                   # noqa: BLE001
            pass
    log(f"DONE — verdict {adj['verdict']} (gates "
        f"{sum(1 for g in metrics['gates'].values() if g.get('pass'))}/"
        f"{len(metrics['gates'])})")


