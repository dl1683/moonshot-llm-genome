# P3 — THE DESK REPRODUCTIONS (x48's pooled re-scores + N1 + co-movement)
# ======================================================================
def phase_P3(p0: dict) -> dict:
    log("P3 — the desk reproductions (x48's forms, exact)")
    x45m, e343m, e344m, x48m = (p0["recs"]["x45"], p0["recs"]["e343"],
                                 p0["recs"]["e344"], p0["recs"]["x48"])
    sub = 0

    def repro(name, scored, committed, keys=("dominant_sign",
                                             "sign_consistency",
                                             "mean_abs_d")):
        nonlocal sub
        ok, detail = True, {}
        for prof, c in committed.items():
            s = scored.get(prof, {})
            for k in keys:
                if c.get(k) is None:
                    continue
                good = ((s.get(k) == c[k]) if isinstance(c[k], str)
                        else (s.get(k) is not None
                              and abs(s[k] - c[k]) < DESK_TOL))
                detail[f"{prof}.{k}"] = {"recomputed": s.get(k),
                                         "committed": c[k],
                                         "match": bool(good)}
                ok &= good
        metrics["gates"][name] = {"detail": detail, "pass": bool(ok)}
        sub += len(detail)
        return ok

    x45_pairs = x45m["match"]["pairs"]
    e343_pairs = e343m["match"]["pairs"]
    e344_pairs = e344m["match"]["pairs"]
    repro("G_X45REPRO", score_pairs(x45_pairs),
          {"r_g-12|g0": x45m["adjudication"]["separations"]["r_g-12|g0"],
           "r_g0|g+12": x45m["adjudication"]["separations"]["r_g0|g+12"]})
    repro("G_E343REPRO", score_pairs(e343_pairs),
          {"r_g-12|g0": e343m["adjudication"]["separations"]["r_g-12|g0"],
           "r_g0|g+12": e343m["adjudication"]["separations"]["r_g0|g+12"]})
    repro("G_E344REPRO", score_pairs(e344_pairs),
          {"r_g-12|g0": e344m["adjudication"]["separations"]["r_g-12|g0"],
           "r_g0|g+12": e344m["adjudication"]["separations"]["r_g0|g+12"]})
    # x48's pooled component re-scores (the pooled re-scores the dispatch names)
    upper_pairs = [p for p in e343_pairs if p["zeph_step"] >= 100]
    compA = [p for p in x45_pairs
             if (p["walk_tag"].startswith("walk_cons_")
                 or p["walk_tag"] == "walk_s700")
             and p["walk_tag"] != "walk_cons_s300"]
    pooled = compA + upper_pairs
    repro("G_X48POOLED", score_pairs(pooled),
          {p: x48m["P_T328a"]["pooled"][p] for p in PRIMARY})
    repro("G_X48COMPA", score_pairs(compA),
          {p: x48m["P_T328a"]["componentA_walk_cons"][p] for p in PRIMARY})
    log("P3: the separation re-scores reproduce (x45/e343/e344 + x48's "
        "pooled components)")

    # ---- the N1 refit + the co-movement (x48's exact forms) ------------
    n1_rows = e344m["n1_rider"]["rows"]
    band = e344m["n1_rider"]["pool"]["read_band"]
    excl = set(e344m["n1_rider"]["pool"]["excluded_tags"])
    inb = [r for r in n1_rows
           if r["tag"] not in excl
           and band[0] - 1e-12 <= r["read"] <= band[1] + 1e-12]
    ages = np.array([r["age"] for r in inb], float)
    z = (ages - ages.mean()) / ages.std()
    menus = np.array([r["menu"] for r in inb])
    r1 = np.array([r["r1"] for r in inb], float)
    X_age = np.column_stack([np.ones(len(inb)), z])
    X_menu = np.column_stack([np.ones(len(inb)),
                              (menus == "cons").astype(float),
                              (menus == "varied").astype(float)])
    X_full = np.column_stack([X_age, X_menu[:, 1:]])
    _, _, R2_age = ols(X_age, r1)
    _, _, R2_menu = ols(X_menu, r1)
    beta_full, pred_full, R2_full = ols(X_full, r1)
    resid = {r["tag"]: float(rr) for r, rr in zip(inb, r1 - pred_full)}
    fits = e344m["n1_rider"]["fits"]["r(g-12|g0)"]
    top2 = sorted(resid.items(), key=lambda kv: kv[1])[:2]
    n1_detail = {
        "n_in_band": len(inb),
        "R2_age": {"recomputed": round(R2_age, 10),
                   "committed": fits["R2_age"]},
        "R2_menu": {"recomputed": round(R2_menu, 10),
                    "committed": fits["R2_menu"]},
        "R2_full": {"recomputed": round(R2_full, 10),
                    "committed": fits["R2_full"]},
        "beta_full": {"recomputed": [round(float(b), 10)
                                     for b in beta_full],
                      "committed": fits["beta_full_fit"]},
        "top2_residuals": top2,
    }
    n1_ok = (abs(R2_age - fits["R2_age"]) < 5e-7
             and abs(R2_menu - fits["R2_menu"]) < 5e-7
             and abs(R2_full - fits["R2_full"]) < 5e-7
             and all(abs(a - b) < 5e-7
                     for a, b in zip(beta_full, fits["beta_full_fit"]))
             and [t for t, _ in top2] == ["anneal_s125", "walk_cons_s125"])
    metrics["gates"]["G_N1REFIT"] = {"detail": n1_detail,
                                     "pass": bool(n1_ok)}
    sub += 6
    log(f"P3: N1 refit exact (R2 {R2_age:.4f}/{R2_menu:.4f}/"
        f"{R2_full:.4f}; top-2 {top2})")

    shared = [25, 50, 75, 100, 125, 150, 175, 200, 225, 250, 275]
    w_res = [resid[f"walk_cons_s{s}"] for s in shared]
    a_res = [resid[f"anneal_s{s}"] for s in shared]
    r_wa = pearson(w_res, a_res)
    com_ok = r_wa is not None and \
        abs(r_wa - x48m["co_movement"]["r_walk_anneal"]) < 5e-4
    metrics["gates"]["G_COMOVE"] = {
        "r_walk_anneal": round(r_wa, 4) if r_wa is not None else None,
        "committed": x48m["co_movement"]["r_walk_anneal"],
        "tolerance": 5e-4,
        "pass": bool(com_ok)}
    sub += 1
    log(f"P3: co-movement r(walk,anneal) = {r_wa:.4f} (x48 committed "
        f"{x48m['co_movement']['r_walk_anneal']})")

    metrics["gate_subcount_P3"] = sub
    write_partial("P3 the desk reproductions done")
    return {"resid": resid, "ages_mean": float(ages.mean()),
            "ages_std": float(ages.std()), "beta_full":
            [float(b) for b in beta_full], "inb_tags":
            [r["tag"] for r in inb], "r1_map":
            {r["tag"]: r["r1"] for r in inb}}


