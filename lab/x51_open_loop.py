# ---- x45's paired elicitation correlations (ported VERBATIM) --------------
def paired_corr(x: list[float], y: list[float]):
    mx, my = sum(x) / 60, sum(y) / 60
    cov = sum((x[i] - mx) * (y[i] - my) for i in range(60))
    vx = math.sqrt(sum((v - mx) ** 2 for v in x))
    vy = math.sqrt(sum((v - my) ** 2 for v in y))
    return cov / (vx * vy) if vx > 0 and vy > 0 else None


# ---- e261's SRCT room (the census ruler; rebuilt + bit-bound) -------------
class SRCT:
    """e261's room VERBATIM (the projector; the basis never materialized):
    P x = D . idct(mask_S(dct(D . x))), fp64 pocketfft."""

    def __init__(self, n: int, k: int, seed_d: int, seed_s: int):
        assert 0 < k <= n
        self.n, self.k = int(n), int(k)
        g = torch.Generator().manual_seed(seed_d)
        self.D = torch.where(torch.rand(n, generator=g) < 0.5,
                             -1.0, 1.0).numpy().astype(np.float64)
        g2 = torch.Generator().manual_seed(seed_s)
        self.S = torch.randperm(n, generator=g2)[:self.k].sort().values \
            .numpy()
        self.mask = np.zeros(n, dtype=np.float64)
        self.mask[self.S] = 1.0
        self.seed_d, self.seed_s = seed_d, seed_s

    def project(self, x64: np.ndarray) -> np.ndarray:
        c = sf.dct(self.D * x64, type=2, norm="ortho", workers=4)
        c *= self.mask
        return self.D * sf.idct(c, type=2, norm="ortho", workers=4)


# ---- x48's frozen separation scorer (ported VERBATIM) ---------------------
def score_pairs(pairs, profiles=PRIMARY):
    """x45's frozen separation rule: over IN-WINDOW pairs, d_i = r_arm - r_anneal;
    dominant sign, sign consistency, mean|d|. Decorrelation rule (co-reported):
    sign - AND consistency >= 0.75 AND mean|d| >= 0.15."""
    out = {}
    for p in profiles:
        ds = [pr[p]["d"] for pr in pairs if pr.get("in_window", True)
              and pr[p]["d"] is not None]
        n_none = sum(1 for pr in pairs if pr.get("in_window", True)
                     and pr[p]["d"] is None)
        if not ds:
            out[p] = {"n": 0, "n_none": n_none, "dominant_sign": None,
                      "sign_consistency": None, "mean_abs_d": None,
                      "separates_decorrelated": False}
            continue
        pos = sum(1 for d in ds if d > 0)
        neg = sum(1 for d in ds if d < 0)
        dom = "+" if pos >= neg else "-"
        cons = max(pos, neg) / len(ds)
        out[p] = {
            "n": len(ds), "n_none": n_none,
            "dominant_sign": dom,
            "sign_consistency": round(cons, 4),
            "mean_abs_d": round(float(np.mean(np.abs(ds))), 6),
            "n_pos": pos, "n_neg": neg,
            "separates_decorrelated": bool(
                dom == "-" and cons >= SIGN_FRAC
                and np.mean(np.abs(ds)) >= FLOOR_CORR),
        }
    return out


def pearson(a, b):
    a, b = np.asarray(a, float), np.asarray(b, float)
    if len(a) < 3 or a.std() == 0 or b.std() == 0:
        return None
    return float(np.corrcoef(a, b)[0, 1])


def perm_p(r_obs, a, b, seed=COMOVE_SEED, n=N_PERM):
    """One-sided p for r >= r_obs under label shuffle (frozen seed)."""
    if r_obs is None:
        return None
    rng = np.random.default_rng(seed)
    a = np.asarray(a, float)
    cnt = 0
    for _ in range(n):
        rp = pearson(rng.permutation(a), b)
        if rp is not None and rp >= r_obs:
            cnt += 1
    return cnt / n


def ols(X, y):
    beta, *_ = np.linalg.lstsq(X, y, rcond=None)
    pred = X @ beta
    ss_res = float(np.sum((y - pred) ** 2))
    ss_tot = float(np.sum((y - y.mean()) ** 2))
    return beta, pred, 1.0 - ss_res / ss_tot


