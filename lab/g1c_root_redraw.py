# THE n=2-ROOT OVERLAY: the claim's statistic (W1 fresh-root vs W1
# locked-root at the SAME wash seed) — reference trajectories read from
# runs/g1b/metrics.json.

def plot(path, trace, disp_table, wall, verdict, clause, gates_pass,
         root_cells, geos_root, rgeo, bar_flat, bar_strict, bars_read, REF,
         root_gate_deviation):
    import textwrap
    fig, axes = plt.subplots(2, 2, figsize=(15.5, 10.5))
    col_fresh, col_locked = "darkorange", "seagreen"
    f3 = lambda v: "n/a" if v is None else f"{v:.3f}"
    f4 = lambda v: "n/a" if v is None else f"{v:.4f}"

    def series(rows):
        pts = [(r["freeze_steps"], r["gm12"]) for r in rows]
        return [p[0] for p in pts], [p[1] for p in pts]

    # (0,0) THE n=2-ROOT OVERLAY: W1 fresh vs locked + the controls
    ax = axes[0, 0]
    xs, ys = series(REF["traces"]["W1"])
    ax.plot(xs, ys, "s--", ms=6, lw=1.8, color=col_locked, alpha=0.9,
            label=f"W1 R=0.7 — LOCKED root (g1b, wash 10902; root g-12 "
                  f"{REF['root_gm12']:.3f})")
    xs, ys = series(trace["W1"])
    ax.plot(xs, ys, "s-", ms=8, lw=2.4, color=col_fresh, alpha=0.95,
            label=f"W1 R=0.7 — FRESH root (g1c, same wash 10902; root g-12 "
                  f"{root_cells['gm12']:.3f})")
    xs, ys = series(REF["traces"]["C"])
    ax.plot(xs, ys, "o--", ms=4, lw=1.2, color=col_locked, alpha=0.5,
            label="C no wall — locked root (ref)")
    xs, ys = series(trace["C"])
    ax.plot(xs, ys, "o-", ms=5, lw=1.6, color=col_fresh, alpha=0.6,
            label="C no wall — fresh root")
    ax.axhline(bar_flat, ls="--", lw=1.6, color="black", alpha=0.85,
               label=f"0.9xroot flat bar {bar_flat:.3f}")
    ax.axhline(bar_strict, ls=":", lw=1.2, color="gray", alpha=0.8,
               label=f"strict 0.9/0.9156xroot {bar_strict:.3f} (co-report)")
    for yv, col in ((G1.MAINTAIN_BAR, "seagreen"), (G1.SHUT_BAR, "tab:purple")):
        ax.axhline(yv, ls="--", lw=1.1, color=col, alpha=0.8)
    ax.axhline(G1.EXPRESS_BAR, ls=":", lw=1.0, color="gray", alpha=0.5)
    ax.annotate(f"fresh root {root_cells['gm12']:.3f}", (0, root_cells["gm12"]),
                textcoords="offset points", xytext=(6, 4), fontsize=7.5)
    ax.set_xlabel("neutral-wash steps from the committed root")
    ax.set_ylabel("g-12 (absolute mean p(Z), install-60 battery)")
    ax.set_ylim(-0.03, 1.05)
    ax.legend(fontsize=7, loc="center right")
    ax.set_title("THE ANCHORED BALL at R=0.7 — the n=2-ROOT overlay "
                 "(2.74M, wash seed 10902 held)", fontsize=10)

    # (0,1) THE CLAIM'S STATISTIC per root: flat-phase min + dip + C min
    ax = axes[0, 1]
    z = lambda v: 0.0 if v is None else v        # None -> 0 bar + n/a label
    labels = ["locked root\n(g1b ref)", "FRESH root\n(g1c)"]
    w1_fp = [min(REF["W1_g_m12"][str(s)] for s in FLAT_PHASE_CK),
             bars_read["flat_phase_min"]]
    w1_dip = [REF["W1_g_m12"]["2"], bars_read["dip_at_2"]]
    c_min = [REF["C_min"], wall["C"]["min_gm12"]]
    xpos = np.arange(2)
    b1 = ax.bar(xpos - 0.22, [z(v) for v in w1_fp], width=0.2,
                color=col_locked, alpha=0.9,
                label="W1 flat-phase min {10..300}")
    b2 = ax.bar(xpos, [z(v) for v in w1_dip], width=0.2, color=col_fresh,
                alpha=0.9, label="W1 dip @+2")
    b3 = ax.bar(xpos + 0.22, [z(v) for v in c_min], width=0.2,
                color="crimson", alpha=0.55, label="C min (all ckpts)")
    ax.axhline(bar_flat, ls="--", lw=1.4, color="black", alpha=0.85,
               label=f"0.9xroot bar (fresh) {bar_flat:.3f}")
    ax.axhline(G1.MAINTAIN_BAR, ls="--", lw=1.2, color="seagreen", alpha=0.8)
    ax.axhline(G1.SHUT_BAR, ls=":", lw=1.1, color="tab:purple", alpha=0.8)
    for bars, raw in ((b1, w1_fp), (b2, w1_dip), (b3, c_min)):
        for b, v in zip(bars, raw):
            ax.annotate(f3(v), (b.get_x() + b.get_width() / 2, b.get_height()),
                        ha="center", va="bottom", fontsize=7)
    ax.set_xticks(xpos)
    ax.set_xticklabels(labels)
    ax.set_ylabel("g-12")
    ax.set_ylim(0, 1.02)
    ax.legend(fontsize=7.5, loc="center right")
    ax.set_title("THE CLAIM'S STATISTIC per root (the g1bR wash band mins "
                 "0.746-0.803 in the background)", fontsize=10)

    # (1,0) DISPLACEMENT: W1 fresh vs the wall (reference co-plotted)
    ax = axes[1, 0]
    ref_rows = [r for r in REF["disp_table"]["W1"] if "g_m12_light" in r]
    ax.plot([r["step"] for r in ref_rows], [r["cum_disp"] for r in ref_rows],
            "s--", ms=5, lw=1.4, color=col_locked, alpha=0.8,
            label="W1 locked root (ref)")
    rows = [r for r in disp_table["W1"] if "g_m12_light" in r]
    ax.plot([r["step"] for r in rows], [r["cum_disp"] for r in rows],
            "s-", ms=7, lw=2.0, color=col_fresh, alpha=0.95,
            label="W1 fresh root")
    ax.axhline(R_CLAIM, ls="--", lw=1.2, color="k", alpha=0.7)
    ax.axhline(R_CLAIM + G1.PIN_FUZZ_BAR, ls=":", lw=1.0, color="k",
               alpha=0.5)
    ax.annotate(f"R={R_CLAIM} (+pin {R_CLAIM + G1.PIN_FUZZ_BAR})", (0.99, R_CLAIM),
                xycoords=("axes fraction", "data"), ha="right", fontsize=7.5)
    rows = [r for r in disp_table["C"] if "g_m12_light" in r]
    ax.plot([r["step"] for r in rows], [r["cum_disp"] for r in rows],
            "o--", ms=4, lw=1.2, color=col_fresh, alpha=0.5,
            label="C fresh root (no wall)")
    ax.set_xlabel("wash step")
    ax.set_ylabel(r"raw $\|\theta_t-\theta_0\|_2$ at checkpoints")
    ax.legend(fontsize=7, loc="lower right")
    ax.set_title("DISPLACEMENT vs the wall (G-PIN) — the control free-runs",
                 fontsize=10)

    # (1,1) THE VERDICT PANEL
    ax = axes[1, 1]
    ax.axis("off")
    y = 0.97
    ax.text(0.02, y, "G1C-ROOT — THE WALL'S ROOT REDRAW (n=2-root overlay)",
            fontsize=11, va="top", family="monospace", weight="bold")
    y -= 0.055
    ax.text(0.02, y, f"gates: {'ALL PASS' if gates_pass else 'FAILURE'} | "
            f"root: ruler g{rgeo:+d} {geos_root[rgeo]:.4f} "
            f"(bar {ROOT_BAR}; g-12 {root_cells['gm12']:.4f} vs locked "
            f"{G1B_ROOT_GM12:.4f})"
            + ("  [ROOT-GATE DEVIATION: coin-flip zone]"
               if root_gate_deviation else ""), fontsize=7.2, va="top",
            family="monospace")
    y -= 0.034
    for tag, col in (("W1", col_fresh), ("C", "crimson")):
        g = wall[tag]["g_m12"]
        seq = " -> ".join(f"+{s}:{g[s]:.4f}" for s in sorted(g))
        ax.text(0.02, y, f"  {tag} (fresh root): {seq}", fontsize=6.4,
                va="top", family="monospace", color=col)
        y -= 0.028
    y -= 0.006
    ax.text(0.02, y, f"  flat bar {f4(bar_flat)} | W1 flat-phase min "
            f"{f4(bars_read['flat_phase_min'])} | dip@+2 "
            f"{f4(bars_read['dip_at_2'])} | strict co-report "
            f"{f4(bar_strict)}: {'holds' if bars_read['strict_coreport_hold'] else 'NO'}",
            fontsize=6.8, va="top", family="monospace")
    y -= 0.03
    ax.text(0.02, y, f"  FLAT-AT-PIN {bars_read['flat_at_pin']} (|d| "
            f"{f4(bars_read['flat_delta'])}) | C dead at +"
            f"{wall['C']['first_ck_le_bar']}", fontsize=6.8, va="top",
            family="monospace")
    y -= 0.044
    ax.text(0.02, y, f"VERDICT: {verdict}", fontsize=10, va="top",
            family="monospace", weight="bold", color="darkred")
    y -= 0.044
    for wd in textwrap.wrap(clause, width=92, break_long_words=False):
        ax.text(0.02, y, f"  {wd}", fontsize=6.8, va="top", family="monospace")
        y -= 0.026

    fig.suptitle("G1C-ROOT — the wall's 2.74M protection at a FRESH root "
                 f"(install gen 24313 -> 24314, everything else verbatim) "
                 f"-> {verdict}", fontsize=11)
    fig.tight_layout(rect=(0, 0, 1, 0.95))
    fig.savefig(path, dpi=130)
    plt.close(fig)


