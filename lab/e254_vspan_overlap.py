def gram_from_memmap(gm) -> np.ndarray:
    """The regenerated scaled-unit Gram (e234's gram_and_dots math)."""
    s = gm.shape[0]
    G = np.zeros((s, s), dtype=np.float64)
    N = gm.shape[1]
    for a in range(0, N, CHUNK):
        b = min(a + CHUNK, N)
        C = np.asarray(gm[:, a:b], dtype=np.float64)
        G += C @ C.T
    return G


def dots_vs_cache(gm, gnorms_half: np.ndarray, x: torch.Tensor) -> np.ndarray:
    """<g_s, x> for s = 1..HALF in TRUE units, from the fp16 cache rows +
    journaled norms (x a full-length fp32/fp64 tensor)."""
    N = gm.shape[1]
    out = np.zeros(HALF, dtype=np.float64)
    inv_scale = 1.0 / CACHE_SCALE
    for a in range(0, N, CHUNK):
        b = min(a + CHUNK, N)
        C = torch.from_numpy(
            np.ascontiguousarray(gm[:, a:b])).to(torch.float64)
        out += (C @ x[a:b].to(torch.float64)).numpy()
        del C
    return out * (gnorms_half * inv_scale)


def span_masses(gdotv: np.ndarray, xnorm2: float, cA_ladder: dict) -> dict:
    """||P_k v||^2/||v||^2 per k in the ladder."""
    out = {}
    for k, cA in cA_ladder.items():
        proj = cA.T @ gdotv
        out[k] = float(proj @ proj / xnorm2) if xnorm2 > 0 else float("nan")
    return out


def null_sweep(states_by_wash: dict, snaps_by_wash: dict,
               norms_by_wash: dict, N: int) -> dict:
    """THE RANDOM-SUBSPACE NULL: fresh gaussian-subspace draws; per draw
    K_NULL_MAX gaussian vectors over all N coords from disclosed
    per-(seed, chunk) PCG streams (fp32 generation, fp64 algebra); the
    exact orthonormalized projection d^T R^{-1} d via the Gram inverse.
    Returns {(wash, state, k): np.ndarray(n_draws)}."""
    keys = [(w, st) for w in states_by_wash for st in states_by_wash[w]]
    draws = {(w, st, k): np.zeros(N_NULL_DRAWS)
             for w, st in keys for k in K_LADDER}
    t0 = time.time()
    for di in range(N_NULL_DRAWS):
        seed = NULL_SEED_BASE + NULL_SEED_STRIDE * di
        R = np.zeros((K_NULL_MAX, K_NULL_MAX), dtype=np.float64)
        d = {(w, st): np.zeros(K_NULL_MAX, dtype=np.float64)
             for w, st in keys}
        for ci, a in enumerate(range(0, N, CHUNK_NULL)):
            b = min(a + CHUNK_NULL, N)
            g = torch.Generator().manual_seed(
                seed + NULL_CHUNK_STRIDE * ci)
            Z = torch.randn(K_NULL_MAX, b - a, generator=g,
                            dtype=torch.float32).to(torch.float64).numpy()
            R += Z @ Z.T
            for w, st in keys:
                d[(w, st)] += Z @ snaps_by_wash[w][st][a:b].to(
                    torch.float64).numpy()
            del Z
        for w, st in keys:
            vnorm2 = norms_by_wash[w][st]
            for k in K_LADDER:
                dk = d[(w, st)][:k]
                Rk = R[:k, :k]
                draws[(w, st, k)][di] = float(
                    dk @ np.linalg.solve(Rk, dk)) / vnorm2
        if (di + 1) % 5 == 0 or di == N_NULL_DRAWS - 1:
            log(f"  [null] draw {di + 1}/{N_NULL_DRAWS} "
                f"({time.time() - t0:.0f}s)")
    return draws


def fact_hot_read(snaps: dict, fact_masks: dict) -> dict:
    """v's L1 share on the fact battery's hot-coordinate sets vs random
    coordinate sets of the same size (n draws)."""
    N = len(fact_masks[K_LADDER_HOT[0]])
    out = {}
    for st, v in snaps.items():
        v64 = v.to(torch.float64)
        tot = float(v64.sum())
        for k_hot, mask in fact_masks.items():
            size = int(mask.sum())
            share = float(v64[torch.from_numpy(mask)].sum() / tot)
            rng = np.random.default_rng(3_254_000 + k_hot + 97 * st)
            rand = np.empty(N_NULL_DRAWS)
            for i in range(N_NULL_DRAWS):
                idx = rng.choice(N, size=size, replace=False)
                rand[i] = float(v64[torch.from_numpy(idx)].sum() / tot)
            out[(st, k_hot)] = {
                "fact_share": share, "random_mean": float(rand.mean()),
                "random_min": float(rand.min()),
                "random_max": float(rand.max()),
                "enrichment": share / float(rand.mean())
                if rand.mean() > 0 else float("nan"),
                "n_coords": size}
        del v64
    return out


