def true_gram(G_scaled: np.ndarray, gnorms: np.ndarray) -> np.ndarray:
    """e234's decompose() Gram math VERBATIM: scaled-unit Gram -> true-unit
    raw-gradient Gram (rows reweighted by journaled norms, /2^28)."""
    S = G_scaled.shape[0]
    Gn = G_scaled.copy()
    for t in range(S):
        Gn[t] *= gnorms[t]
        Gn[:, t] *= gnorms[t]
    Gn /= float(CACHE_SCALE ** 2)
    return Gn


def basis_coeffs(Gn: np.ndarray, half: int, knee_max_i: int, cap: int):
    """e234's basis_of VERBATIM on the first-half block: the knee-k top
    eigenvectors, coefficient columns orthonormalized by 1/sqrt(lambda).
    Returns (k, cA_k, evec, evals_desc, meta)."""
    ev, evec = np.linalg.eigh(Gn[:half, :half])
    order = np.argsort(ev)[::-1]
    ev, evec = ev[order], evec[:, order]
    gaps = [(float(ev[i - 1] - ev[i]), i + 1)
            for i in range(1, min(knee_max_i, len(ev) - 1) + 1)]
    k = max(gaps)[1] if gaps else 1
    capped = False
    if k > cap:
        k, capped = cap, True
    c = evec[:, :k] / np.sqrt(np.clip(ev[:k], 1e-12, None))
    meta = {"spectrum": ev.tolist(), "knee_k": int(k), "k_capped": capped,
            "var_frac_at_k": float(ev[:k].sum() / ev.sum()) if ev.sum() > 0
            else None, "gaps": [g for g, _ in gaps]}
    return k, c, evec, ev, meta


def coverage_median(Gn: np.ndarray, gnorms: np.ndarray, cA: np.ndarray,
                    half: int) -> float:
    """e234's coverage_A median: the fraction of each SECOND-half step's
    squared L2 inside the first-half basis (from the Gram alone)."""
    B_A = cA.T @ Gn[:half, half:]                # (k, S-half)
    wind2 = np.einsum("ij,ij->j", B_A, B_A)
    return float(np.median(wind2 / (gnorms[half:] ** 2)))


def ladder_from(evec: np.ndarray, evals: np.ndarray) -> dict:
    """The k-ladder of coefficient matrices (columns orthonormalized)."""
    return {k: evec[:, :k] / np.sqrt(np.clip(evals[:k], 1e-12, None))
            for k in K_LADDER}


