@torch.no_grad()
def battery_read(net, ids: torch.Tensor, zid: int, bs: int = 30) -> dict:
    """G1.battery_cell's exact form + x15/x17's honesty riders + the
    per-context fraction the READS-class clauses need."""
    net.eval()
    pzs, tops, ents, amax = [], [], [], 0.0
    for i in range(0, ids.shape[0], bs):
        lg, _ = net(ids[i:i + bs])
        pr = F.softmax(lg[:, -1], -1)
        pzs.append(pr[:, zid])
        tops.append(pr.max(-1).values)
        ents.append(-(pr * torch.log(pr.clamp_min(1e-30))).sum(-1))
        amax += float((lg[:, -1].argmax(-1) == zid).float().sum())
    p = torch.cat(pzs)
    return {"mean_pz": float(p.mean()), "median_pz": float(p.median()),
            "frac_pz_ge_0.5": float((p >= 0.5).float().mean()),
            "frac_pz_ge_0.05": float((p >= 0.05).float().mean()),
            "frac_argmax_z": amax / ids.shape[0],
            "rider_mean_top1_p": float(torch.cat(tops).mean()),
            "rider_mean_entropy": float(torch.cat(ents).mean())}


def inroom_frac(room: SRCT, v64: np.ndarray) -> float:
    vn = float(np.linalg.norm(v64))
    if vn == 0.0:
        return 0.0
    return float(np.linalg.norm(room.project(v64)) / vn)


def inroom_energy_share(room: SRCT, v64: np.ndarray) -> float:
    """x15's G_INROOM_SCALED exact form: ||Pv||^2 / ||v||^2 (energy share,
    NOT norm fraction — x17's smoke-caught units repair, carried)."""
    e = float(v64 @ v64)
    if e == 0.0:
        return 0.0
    p = room.project(v64)
    return float((p @ p) / e)


