    ctrl_G_FL, ctrl_G_PI = _arm_gates("CONTROL", out_ctrl["sd"],
                                      resume_ctrl, out_ctrl)
    ctrl_G_FL["g0_arm"] = float(ctrl_g0)
    ctrl_G_FL["pass"] = bool(abs(ctrl_G_FL["g0_reload"] - ctrl_g0)
                             <= 2e-6)
    assert ctrl_G_FL["pass"] and ctrl_G_PI["pass"], \
        f"CONTROL arm gates FAILED: {ctrl_G_FL} {ctrl_G_PI}"
    metrics["gates"]["G_FACTLOAD_CONTROL"] = ctrl_G_FL
    metrics["gates"]["G_PROTOIDENT_CONTROL"] = ctrl_G_PI
    log(f"P4 CONTROL G_FACTLOAD + G_PROTOIDENT PASS (gen_state md5 "
        f"{ctrl_G_PI['gen_state_md5'][:10]}...)")
    log(f"P4 ARM A CONTROL: s1 {ctrl_s1:.6e} (committed "
        f"{canon_s1_committed:.6e}, rel "
        f"{G_CANONCTRL['s1_rel_diff']:.2e}); post g0 {ctrl_g0:.6f} "
        f"(committed {canon_post_g0_committed:.6f}, rel "
        f"{G_CANONCTRL['post_g0_rel_diff']:.2e}) — PASS")
    write_partial("ARM A the control reruns the canon: gates PASS")

    # ================= P5: ARM B — THE BODY-CONTROL (canon step 1) =======
    log("=" * 78)
    log("ARM B — THE BODY-CONTROL: the canon's step 1 through THIS cell's "
        "body, UNMODIFIED (the code path's inertness gate)")
    bstate, btraj, bled = step_one(CANON_GEN, swap=False)
    G_BODYCTRL = {
        "form": "the body's step 1, unmodified, equals the control arm's "
                "step 1 (s1 rel <= 1e-6) — the code path is inert before "
                "the swap is read",
        "s1_body": float(btraj["g0_pz"]),
        "s1_control": float(ctrl_s1),
        "rel_diff": float(abs(btraj["g0_pz"] / ctrl_s1 - 1.0)),
        "pass": bool(abs(btraj["g0_pz"] / ctrl_s1 - 1.0) <= 1e-6),
    }
    assert G_BODYCTRL["pass"], f"G_BODYCTRL FAILED: {G_BODYCTRL}"
    metrics["gates"]["G_BODYCTRL"] = G_BODYCTRL
    log(f"P5 ARM B BODY-CONTROL: s1 {btraj['g0_pz']:.6e} vs control "
        f"{ctrl_s1:.6e} (rel {G_BODYCTRL['rel_diff']:.2e}) — PASS")
    write_partial("ARM B the body-control gate PASSED")

    # ================= P6: ARM C — THE SWAP ==============================
    log("=" * 78)
    log(f"ARM C — THE SWAP: the canon's run with the FIRST MINIBATCH = "
        f"gen {SURVIVE_GEN}'s first triplet (md5-gated); steps 2-400 = "
        f"the canon's own batches via the rig's resume path")
    cstate, ctraj, cled = step_one(SURVIVE_GEN, swap=True)
    resume_swap = CKPT_DIR / ("smoke_e328_swap_resume.pt" if SMOKE
                              else "e328_swap_resume.pt")
    torch.save(cstate, resume_swap)
    log(f"  [ARM C] step-1 state saved to {resume_swap.name} "
        f"(s1 {ctraj['g0_pz']:.6e}, ce {ctraj['ce_batch']:.6f})")
    out_swap = E261.chunked_install(
        "e328:SWAP", ROOM_MODE, G1.evl_load(base_sd), rooms, win_bank,
        inst_mask, anchor_full, train_ids, g0_ids, gm12_ids, r_eval_xy,
        zid, resume_swap, dev)
    E261.burst_cooldown("post-swap")
    swap_traj = out_swap["traj"]
    swap_s1 = traj_get(swap_traj, 1)
    swap_s100 = traj_get(swap_traj, 100)
    swap_s400 = traj_get(swap_traj, 400 if not SMOKE else E261.INST_STEPS)
    swap_net = G1.evl_load(out_swap["sd"])
    swap_g0 = G1.battery_cell(swap_net, g0_ids, zid)["mean_pz"]
    swap_gm12 = G1.battery_cell(swap_net, gm12_ids, zid)["mean_pz"]
    swap_gp12 = G1.battery_cell(swap_net, bat_ids[12], zid)["mean_pz"]
    swap_ce_r = G1.ce_fixed_cpu(swap_net, *r_eval_xy)
    swap_flat = flat_params_cpu(swap_net)
    swap_norm = float(np.linalg.norm(
        swap_flat.double().numpy().astype(np.float64) - base_flat_np))
    swap_loads = rooms.displacement_loads(swap_flat - base_flat, ROOM_MODE)
    swap_d_to_ctrl = float(np.linalg.norm(
        (swap_flat - ctrl_flat).double().numpy().astype(np.float64)))
    del swap_net

    G_SWAPRESUME = {
        "form": "the swap arm's steps 2-400 ARE the canon's own batches: "
                "the resume handed the rig the canon's generator state "
                "after its own first triplet (md5-bound in G_BATCHMD5); "
                "the swap's step-1 traj row came from the gated body "
                "(ARM B)",
        "steps_ran": int(out_swap["steps_ran"]),
        "resumed_final": bool(out_swap.get("resumed_final", False)),
        "traj_steps": [t["step"] for t in swap_traj],
        "swap_first_batch_md5s": {k: G_BATCHMD5[k] for k in
                                  ("swap_ix_md5", "swap_aj_md5",
                                   "swap_rj_md5")},
        "pass": bool(int(out_swap["steps_ran"]) == E261.INST_STEPS
                     and swap_traj[0]["step"] == 1),
    }
    assert G_SWAPRESUME["pass"], f"G_SWAPRESUME FAILED: {G_SWAPRESUME}"
    metrics["gates"]["G_SWAPRESUME"] = G_SWAPRESUME

    swap_G_FL, swap_G_PI = _arm_gates("SWAP", out_swap["sd"],
                                      resume_swap, out_swap)
    swap_G_FL["g0_arm"] = float(swap_g0)
    swap_G_FL["pass"] = bool(abs(swap_G_FL["g0_reload"] - swap_g0) <= 2e-6)
    assert swap_G_FL["pass"] and swap_G_PI["pass"], \
        f"SWAP arm gates FAILED: {swap_G_FL} {swap_G_PI}"
    metrics["gates"]["G_FACTLOAD_SWAP"] = swap_G_FL
    metrics["gates"]["G_PROTOIDENT_SWAP"] = swap_G_PI
    # THE STREAM-IDENTITY GATE: both arms' generators end in the SAME
    # state — the control consumed the canon's triplet at step 1, the
    # swap consumed it before step 1 (and used 32401's for the page);
    # steps 2-400 drew identical batches in both arms by construction
    G_SWAPRESUME["final_gen_state_md5_swap"] = swap_G_PI["gen_state_md5"]
    G_SWAPRESUME["final_gen_state_md5_control"] = ctrl_G_PI["gen_state_md5"]
    G_SWAPRESUME["streams_converged"] = bool(
        swap_G_PI["gen_state_md5"] == ctrl_G_PI["gen_state_md5"])
    assert G_SWAPRESUME["streams_converged"], \
        "the arms' generator streams did not converge — the swap's later "\
        "batches are not the canon's"
    log(f"P6 SWAP G_FACTLOAD + G_PROTOIDENT PASS; the streams CONVERGED "
        f"(both arms' final gen_state md5 "
        f"{swap_G_PI['gen_state_md5'][:10]}...)")
    log(f"P6 ARM C SWAP: s1 {swap_s1:.6e}; s100 "
        f"{'-' if swap_s100 is None else format(swap_s100, '.4f')}; "
        f"post g0 {swap_g0:.6f}; norm {swap_norm:.4f}; in-room "
        f"{swap_loads['in_own_room']:.4f}; ||swap-ctrl|| "
        f"{swap_d_to_ctrl:.4f}")
    write_partial("ARM C the swap run landed")

    # ================= P7: the adjudication (the frozen bars) ============
    swap_ratio = swap_s1 / max(prior, RATIO_DEN_FLOOR)
    ctrl_ratio = ctrl_s1 / max(prior, RATIO_DEN_FLOOR)
    if swap_ratio >= FLIPS_BAR:
        verdict = "FLIPS-TO-SURGE"
    elif swap_ratio <= STAYS_BAR:
        verdict = "STAYS-NO-SURGE"
    else:
        verdict = "SWAP-GAP-LANDS"
    P_e328a_hit = (verdict == "STAYS-NO-SURGE")
    P_e328x32_hit = (verdict == "STAYS-NO-SURGE")

    adjudication = {
        "prior": float(prior),
        "swap_s1": float(swap_s1), "swap_ratio": float(swap_ratio),
        "ctrl_s1": float(ctrl_s1), "ctrl_ratio": float(ctrl_ratio),
        "bars": {"FLIPS-TO-SURGE >= 1e3": FLIPS_BAR,
                 "STAYS-NO-SURGE <= 1.2": STAYS_BAR},
        "verdict": verdict,
        "P_e328a": {"lean": "STAYS-NO-SURGE (weakly)",
                    "hit": bool(P_e328a_hit)},
        "P_e328x32": {"call": "STAYS-NO-SURGE (x32 THREE-DEATHS mapping)",
                      "hit": bool(P_e328x32_hit)},
        "the_formation_axes_no_bar": {
            "control": {"s100": (float(ctrl_s100)
                                 if ctrl_s100 is not None else None),
                        "post_g0": float(ctrl_g0),
                        "write_norm": ctrl_norm,
                        "in_own_room": ctrl_loads["in_own_room"],
                        "gm12": float(ctrl_gm12), "gp12": float(ctrl_gp12),
                        "ce_r": float(ctrl_ce_r)},
            "swap": {"s100": (float(swap_s100)
                              if swap_s100 is not None else None),
                     "post_g0": float(swap_g0),
                     "write_norm": swap_norm,
                     "in_own_room": swap_loads["in_own_room"],
                     "gm12": float(swap_gm12), "gp12": float(swap_gp12),
                     "ce_r": float(swap_ce_r)},
            "committed_canon": {"post_g0": float(canon_post_g0_committed)},
            "l2_between_arms": swap_d_to_ctrl,
            "note": "REPORT ONLY (no bar): the swap's formation vs the "
                    "control's — the only matched comparator (both from "
                    "the base, this session, one delta: the first page)",
        },
        "the_swap_step1_fingerprint": {
            "traj_row": ctraj if not SMOKE else ctraj,
            "ledger_row": cled,
            "note": "the swapped first page's own fingerprint (ce_batch "
                    "vs the canon's own committed 1.0701713562011719 — "
                    "the batch content differs by construction)",
        },
    }
    metrics["adjudication"] = adjudication
    log(f"P7 ADJUDICATION: swap s1/prior = {swap_ratio:.4f} -> {verdict} "
        f"(control {ctrl_ratio:.4f}); P-e328a "
        f"{'HIT' if P_e328a_hit else 'MISSED'}; P-e328x32 "
        f"{'HIT' if P_e328x32_hit else 'MISSED'}")
    write_partial(f"P7 adjudicated: {verdict}")

    # ================= P8: the figure + REPORT ===========================
    fig, axes = plt.subplots(1, 2, figsize=(14.5, 6.4))
    ax = axes[0]
    steps_c = [t["step"] for t in ctrl_traj]
    g0_c = [t["g0_pz"] for t in ctrl_traj]
    steps_s = [t["step"] for t in swap_traj]
    g0_s = [t["g0_pz"] for t in swap_traj]
    ax.plot(steps_c, g0_c, "o-", color="#d62728", label="CONTROL (canon "
            "verbatim, from the BASE)")
    ax.plot(steps_s, g0_s, "s-", color="#1f77b4", label="SWAP (canon + "
            "32401's first page)")
    ax.axhline(float(prior), color="grey", ls="--", lw=1,
               label=f"prior (e001) {prior:.2e}")
    ax.set_xlabel("install step"); ax.set_ylabel("g0 read p(Z)")
    ax.set_yscale("log")
    ax.set_title(f"e328 — THE FIRST PAGE: {verdict}\nswap s1/prior = "
                 f"{swap_ratio:.4f} (FLIPS bar >= 1e3, STAYS bar <= 1.2)")
    ax.grid(alpha=0.25); ax.legend(fontsize=8)
    ax2 = axes[1]
    ax2.bar(["write norm"], [ctrl_norm], color="#d62728", alpha=0.7,
            label="control")
    ax2.bar(["write norm"], [swap_norm], color="#1f77b4", alpha=0.7,
            label="swap")
    ax2.bar(["in-own-room"], [ctrl_loads["in_own_room"]],
            color="#d62728", alpha=0.7)
    ax2.bar(["in-own-room"], [swap_loads["in_own_room"]],
            color="#1f77b4", alpha=0.7)
    ax2.set_title("the formation axes (report, no bar)\n"
                  f"||swap - control|| = {swap_d_to_ctrl:.4f}")
    ax2.grid(alpha=0.25, axis="y"); ax2.legend(fontsize=8)
    fig.tight_layout()
    png = RD / "e328_first_page.png"
    fig.savefig(png, dpi=130)
    log(f"P8: figure -> {png.name}")

    lines = []
    lines.append("# e328 — THE FIRST PAGE (the batch swap)\n")
    lines.append(f"Run: {now_iso()} ({'SMOKE' if SMOKE else 'FULL'}). "
                 "The canon's committed install (from the BASE, K10K, "
                 "gen 24314) with its first minibatch swapped for gen "
                 "32401's; everything else held by construction.\n")
    lines.append("\n## THE ADJUDICATION (the frozen bars)\n")
    lines.append(f"- swap s1 = {swap_s1:.6e}; prior = {prior:.6e}; "
                 f"ratio = {swap_ratio:.6f}")
    lines.append(f"- control s1 = {ctrl_s1:.6e} (committed "
                 f"{canon_s1_committed:.6e}); ratio = {ctrl_ratio:.6f}")
    lines.append(f"- **VERDICT: {verdict}** (FLIPS >= 1e3; STAYS <= 1.2; "
                 "the residue = SWAP-GAP-LANDS, named at birth)")
    lines.append(f"- P-e328a (dispatch lean STAYS-NO-SURGE, weakly): "
                 f"{'HIT' if P_e328a_hit else 'MISSED'}")
    lines.append(f"- P-e328x32 (x32's registered call STAYS-NO-SURGE, "
                 f"from runs/x32/metrics.json): "
                 f"{'HIT' if P_e328x32_hit else 'MISSED'}")
    lines.append("\n## THE FORMATION AXES (report, no bar)\n")
    lines.append("| arm | s100 | post g0 | write norm | in-own-room | "
                 "gm12 | gp12 | CE_R |")
    lines.append("|---|---|---|---|---|---|---|---|")
    fa = adjudication["the_formation_axes_no_bar"]
    def _f4(v):
        return "-" if v is None else f"{v:.4f}"
    for nm, a in (("CONTROL", fa["control"]), ("SWAP", fa["swap"])):
        lines.append(f"| {nm} | {_f4(a['s100'])} | {a['post_g0']:.6f} | "
                     f"{a['write_norm']:.4f} | {a['in_own_room']:.4f} | "
                     f"{a['gm12']:.4f} | {a['gp12']:.4f} | "
                     f"{a['ce_r']:.4f} |")
    lines.append(f"\n||swap - control||_2 = {swap_d_to_ctrl:.4f} (the "
                 "whole-run footprint of swapping one page).")
    lines.append("\n## THE SWAP'S FIRST PAGE (fingerprint)\n")
    lines.append(f"- ce_batch {ctraj['ce_batch']:.10f} (the canon's own "
                 "committed first page: 1.0701713562011719 — read from "
                 "e264 at runtime; the contents differ by construction)")
    lines.append(f"- kept {cled['kept_frac']:.6f}; v_exc pre "
                 f"{cled['v_excess_pre']:.3f} post "
                 f"{cled['v_excess_post']:.3f}")
    lines.append("\n## GATES\n")
    gp = {k: v.get("pass", True) for k, v in metrics["gates"].items()}
    metrics["gates_summary"] = {"n_gate_classes": len(gp),
                                "n_pass": sum(1 for v in gp.values() if v),
                                "detail": gp}
    lines.append(f"{metrics['gates_summary']['n_pass']}/"
                 f"{metrics['gates_summary']['n_gate_classes']} gate "
                 "classes PASS.\n")
    report = RD / "REPORT.md"
    report.write_text("\n".join(lines), encoding="utf-8")

    metrics["status"] = f"ADJUDICATED: {verdict}" + (
        " (SMOKE — nothing adjudicated)" if SMOKE else "")
    metrics["date_completed"] = now_iso()
    metrics["outputs"] = [f"runs/{NAME}/{n}" for n in
                          ("metrics.json", "REPORT.md",
                           "e328_first_page.png")]
    save_json(RD / "metrics.json", E43.jsonable(metrics))
    log(f"P8: REPORT + metrics -> runs/{NAME}/")

    gs = metrics["gates_summary"]
    assert gs["n_pass"] == gs["n_gate_classes"], \
        f"gate failures: {gs['detail']}"
    log(f"DONE ({'SMOKE' if SMOKE else 'FULL'}): {verdict}; gates "
        f"{gs['n_pass']}/{gs['n_gate_classes']}")


