def make_png(p2: dict, ktable: list, verdict: str, walk_geo: float,
             reduced_cut: float, rider_table: dict) -> None:
    fig, axs = plt.subplots(2, 2, figsize=(13, 9))
    fig.suptitle("x36 THE PAGE LADDER — where in the authored stream the "
                 "seat-purchasing content lives", fontsize=11)

    # (1) the read trajectories per K
    ax = axs[0][0]
    for K in LADDER_FRESH:
        rows = sorted(p2["legs"][K]["rows"].values(),
                      key=lambda r: r["step"])
        ax.plot([r["step"] for r in rows], [r["read"] for r in rows],
                marker="o", ms=3, label=f"k{K} ({K}/300 neutral)")
    ax.axhline(DEAD_CUT, color="gray", ls=":", lw=1)
    ax.axhline(READ_HOLD_SMALL, color="green", ls=":", lw=1)
    ax.set_yscale("log")
    ax.set_xlabel("cons step"); ax.set_ylabel("host read p(Z) g0 (log)")
    ax.set_title("THE READS: the host read's fate per K")
    ax.legend(fontsize=8)

    # (2) the decorrelation profile: geo_mad per K vs the walk + floor
    ax = axs[0][1]
    ks = [row["K"] for row in ktable]
    geos = [row["geo_mad"] if row["geo_mad"] is not None else 0.0
            for row in ktable]
    cols = ["tab:blue" if row["state"] == "AT-STRENGTH"
            else ("tab:orange" if row["state"] == "REDUCED" else "tab:red")
            for row in ktable]
    ax.bar([str(k) for k in ks], geos, color=cols)
    ax.axhline(FLOOR_CORR, color="k", ls="--", lw=1,
               label=f"floor {FLOOR_CORR}")
    ax.axhline(walk_geo, color="tab:blue", ls=":", lw=1,
               label=f"walk geo {walk_geo:.3f}")
    ax.axhline(reduced_cut, color="tab:orange", ls=":", lw=1,
               label=f"reduced cut {reduced_cut:.3f}")
    ax.set_xlabel("K (pages swapped)"); ax.set_ylabel("geo_mad (anneal)")
    ax.set_title("THE DECORRELATION PROFILE per K")
    ax.legend(fontsize=7)

    # (3) the free rider: |W| + in_room at the last rider rung
    ax = axs[1][0]
    labels = [row["arm"] for row in ktable]
    last_rung = rider_table.get(str(max(int(k) for k in rider_table))
                                ) if rider_table else {}
    wvals = [last_rung.get(row["arm"], {}).get("write_norm", float("nan"))
             for row in ktable]
    rvals = [last_rung.get(row["arm"], {}).get("in_room", float("nan"))
             for row in ktable]
    ax2 = ax.twinx()
    ax.bar(labels, wvals, color="tab:gray", alpha=0.7, label="|W|")
    ax2.plot(labels, rvals, color="tab:red", marker="s", label="in_room")
    ax.set_ylabel("|W| (fp64 vs e001)"); ax2.set_ylabel("K10K in-room")
    ax.set_title("THE FREE RIDER: the name-blind census per arm "
                 "(last matched rung)")

    # (4) the verdict + the state table
    ax = axs[1][1]
    ax.axis("off")
    lines = [f"VERDICT: {verdict}", ""]
    for row in ktable:
        lines.append(f"k{row['K']:<3} {row['state']:<28} "
                     f"max_read {row['max_read']}")
    lines += ["", f"walk_geo_mad {walk_geo:.4f} | reduced_cut "
              f"{reduced_cut:.4f} (0.6x, at-the-floor)",
              f"P-x36a: {metrics.get('p_x36a_score', {}).get('n_hit', '?')}"
              "/3 scored calls hit"]
    ax.text(0.02, 0.98, "\n".join(lines), fontsize=9, va="top",
            family="monospace")
    fig.tight_layout(rect=(0, 0, 1, 0.95))
    fig.savefig(RD / "x36_page_ladder.png", dpi=140)
    plt.close(fig)


