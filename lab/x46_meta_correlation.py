def pearson(a, b):
    n = len(a)
    ma, mb = sum(a) / n, sum(b) / n
    ca = [x - ma for x in a]
    cb = [x - mb for x in b]
    num = sum(x * y for x, y in zip(ca, cb))
    da = math.sqrt(sum(x * x for x in ca))
    db = math.sqrt(sum(x * x for x in cb))
    if da == 0 or db == 0:
        return None
    return num / (da * db)


def _rank(v):
    order = sorted(range(len(v)), key=lambda i: v[i])
    r = [0.0] * len(v)
    i = 0
    while i < len(order):
        j = i
        while j + 1 < len(order) and v[order[j + 1]] == v[order[i]]:
            j += 1
        avg = (i + j) / 2.0 + 1.0
        for k in range(i, j + 1):
            r[order[k]] = avg
        i = j + 1
    return r


def spearman(a, b):
    return pearson(_rank(a), _rank(b))


def perm_null(D, L, seed=46046, draws=200000):
    """The permutation null of Pearson r for THIS D vector (L permuted).
    Exact enumeration for n <= 8; seeded Monte Carlo above.
    Returns (null_list, exact_flag)."""
    n = len(D)
    null = []
    if n <= 8:
        for perm in itertools.permutations(range(n)):
            null.append(pearson(D, [L[i] for i in perm]))
        return null, True
    rng = random.Random(seed)
    for _ in range(draws):
        perm = list(range(n))
        rng.shuffle(perm)
        null.append(pearson(D, [L[i] for i in perm]))
    return null, False


def null_p_and_crit(D, L, r_obs, null):
    """One-sided positive p and the 95th-percentile critical r of the null."""
    cnt = sum(1 for r in null if r is not None and r >= r_obs - 1e-12)
    p = cnt / len(null)
    srt = sorted(r for r in null if r is not None)
    k = math.ceil(0.95 * len(srt))
    crit = srt[min(k, len(srt)) - 1]
    return p, crit


