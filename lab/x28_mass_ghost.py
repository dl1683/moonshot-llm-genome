def run_anti(tag: str, start_sd: dict, gen_seed: int, resume_ck: Path,
             capture_events: tuple[int, ...] = ()) -> dict:
    """e321's erase loop VERBATIM (e322's port; SGD-M ascent on the HOST's
    name-only CE, B_E equal-share cap, dose-gated lr) + the extended
    ecology panel + state captures. CPU device (this cell's lane)."""
    estate = {"event": 0, "S_anti": 0.0, "panel": [], "trace": [],
              "n_capped": 0, "captures": {}, "gen_seed": gen_seed}
    if resume_ck.exists():
        estate = torch.load(resume_ck, map_location="cpu",
                            weights_only=False)
        log(f"  [{tag}] RESUMED at event {estate['event']}/{N_ANTI}")
    if int(estate.get("event", 0)) >= N_ANTI:
        return {"panel": estate["panel"], "trace": estate["trace"],
                "final_sd": estate["model"], "captures":
                    estate.get("captures", {}),
                "S_anti": estate["S_anti"], "n_capped": estate["n_capped"],
                "resumed_final": True}
    net = G1.evl_load(start_sd).to(CPU)
    net.train()
    opt_A = torch.optim.SGD(net.parameters(), lr=LR_ANTI_MAX,
                            momentum=ANTI_MOMENTUM,
                            weight_decay=ANTI_WD)
    agen = torch.Generator().manual_seed(gen_seed)
    if resume_ck.exists():
        net.load_state_dict(estate["model"])
        net.to(CPU)
        net.train()
        opt_A.load_state_dict(estate["optA"])
        agen.set_state(estate["agen_state"])
    evl = G1.evl_load(start_sd)
    params_live = list(net.parameters())
    t_burst, n_burst = E261._open_burst(f"{tag}")
    ev = estate["event"]
    while ev < N_ANTI:
        ev += 1
        # (i) the anti batch: ix(16) draws of the HOST's windows (verbatim)
        ix = torch.randint(inst_x.shape[0], (G1.NAME_BS,), generator=agen)
        nw = inst_x[ix]
        x_i = nw[:, :-1].to(CPU)
        y_i = nw[:, 1:].to(CPU)
        m_i = inst_mask[ix].to(CPU)
        logits_i, _ = net(x_i)
        nll_i = F.cross_entropy(
            logits_i.reshape(-1, logits_i.shape[-1]),
            y_i.reshape(-1), reduction="none"
        ).view(x_i.shape[0], x_i.shape[1])
        nm_i = nll_i[m_i]
        name_ce = nm_i.mean()
        loss_anti = -name_ce
        net.zero_grad(set_to_none=True)
        loss_anti.backward()
        torch.nn.utils.clip_grad_norm_(net.parameters(), 1.0)
        # (ii) the dose gate (the host's read at the event instant)
        sd_gate = {k: v.detach().cpu().clone()
                   for k, v in net.state_dict().items()}
        evl.load_state_dict(sd_gate)
        evl.eval()
        read_gate = G1.battery_cell(evl, g0_ids, zid)["mean_pz"]
        dose_t = min(1.0, read_gate / DOSE_FULL_LEVEL)
        lr_target = LR_ANTI_MAX * dose_t
        # (iii) the B_E cap (e294's equal-share form, momentum-aware)
        be_sq = 0.0
        st = opt_A.state
        for p in params_live:
            d = st.get(p)
            buf_prev = (d.get("momentum_buffer")
                        if isinstance(d, dict) else None)
            v = (p.grad.detach() if buf_prev is None
                 else ANTI_MOMENTUM * buf_prev + p.grad.detach())
            be_sq += float(v.square().sum().item())
        b_norm = math.sqrt(max(be_sq, 0.0))
        remaining = N_ANTI - ev + 1
        share_e = max(B_E - estate["S_anti"], 0.0) / remaining
        cap_e = share_e / max(b_norm, 1e-12)
        lr_e = min(lr_target, cap_e)
        capped = bool(cap_e < lr_target)
        if capped:
            estate["n_capped"] += 1
        for g_ in opt_A.param_groups:
            g_["lr"] = lr_e
        theta_b_ = torch.cat([p.detach().reshape(-1)
                              for p in net.parameters()])
        opt_A.step()
        with torch.no_grad():
            d_step = torch.cat([p.detach().reshape(-1)
                                for p in net.parameters()]) - theta_b_
        realized = float(d_step.norm().item())
        estate["S_anti"] += realized
        estate["trace"].append({
            "event": ev, "name_ce": float(name_ce.item()),
            "read_gate": read_gate, "dose": dose_t,
            "lr_target": lr_target, "cap_e": cap_e, "lr_applied": lr_e,
            "capped": capped, "b_norm": b_norm, "share_e": share_e,
            "realized": realized, "S_anti": estate["S_anti"]})
        ok_t, temp = E261.burst_temp_check(f"{tag}.e{ev}")
        n_burst += 1
        estate["event"] = ev
        if ev % PANEL_EVERY == 0 or ev == N_ANTI:
            sd_cpu = {k: v.detach().cpu().clone()
                      for k, v in net.state_dict().items()}
            evl.load_state_dict(sd_cpu)
            evl.eval()
            eco = slot_ecology(evl, g0_ids, LETTER_IDS)
            row = {"event": ev, "host_g0": eco["p_Z"],
                   "para_g0": eco["p_T"], "ghost_g0": eco["p_Q"],
                   "ghost2_g0": eco["p_N"], "ghost3_g0": eco["p_B"],
                   "ecology": eco, "S_anti": estate["S_anti"],
                   "elapsed_s": round(time.time() - T0, 1)}
            estate["panel"].append(row)
            log(f"  [{tag}] panel e{ev}: host {row['host_g0']:.6f} | PARA "
                f"(T, massless) {row['para_g0']:.6f} | GHOST (Q, MASS) "
                f"{row['ghost_g0']:.6f} | PN {eco['pn_total']:.4f} | "
                f"S_anti {row['S_anti']:.4f}")
            estate["model"] = {k: v.detach().cpu().clone()
                               for k, v in net.state_dict().items()}
            estate["optA"] = opt_A.state_dict()
            estate["agen_state"] = agen.get_state()
            torch.save(estate, resume_ck)
        if ev in capture_events:
            estate["captures"][str(ev)] = {
                k: v.detach().cpu().clone() for k, v in
                net.state_dict().items()}
            log(f"  [{tag}] CAPTURED state at event {ev}")
        if not ok_t or (time.time() - t_burst) > E261.BURST_MAX_S:
            estate["model"] = {k: v.detach().cpu().clone()
                               for k, v in net.state_dict().items()}
            estate["optA"] = opt_A.state_dict()
            estate["agen_state"] = agen.get_state()
            torch.save(estate, resume_ck)
            log(f"  [{tag}] cadence break at e{ev}; checkpoint + resume")
            E261.burst_cooldown(tag)
            t_burst, n_burst = E261._open_burst(f"{tag}-resume")
    E261.burst_cooldown(f"{tag}-end")
    final_sd = {k: v.detach().cpu().clone()
                for k, v in net.state_dict().items()}
    del net, opt_A, agen, evl
    return {"panel": estate["panel"], "trace": estate["trace"],
            "final_sd": final_sd, "captures": estate.get("captures", {}),
            "S_anti": estate["S_anti"], "n_capped": estate["n_capped"]}


