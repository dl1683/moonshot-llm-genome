def apply_flat64(net, flat64: np.ndarray, offsets, shapes) -> None:
    """theta <- flat64 (fp64 arithmetic) cast fp32 into the params —
    e311/e321's applied-state convention."""
    f32 = flat64.astype(np.float32)
    with torch.no_grad():
        for p, (a, b), shp in zip(net.parameters(), offsets, shapes):
            p.copy_(torch.from_numpy(f32[a:b]).reshape(shp))


def inroom_relresid(room, v64: np.ndarray) -> float:
    vn = float(np.linalg.norm(v64))
    if vn == 0.0:
        return 0.0
    pv = room.project(v64)
    return float(np.linalg.norm(pv - v64) / vn)


def inroom_frac(room, v64: np.ndarray) -> float:
    vn = float(np.linalg.norm(v64))
    if vn == 0.0:
        return 0.0
    return float(np.linalg.norm(room.project(v64)) / vn)


@torch.no_grad()
def slot_ecology(net, ids: torch.Tensor, letter_ids: dict) -> dict:
    """ONE battery pass -> every letter's mean at the last position + the
    GHOST's per-context stats + the PN total (e322's slot_ecology, the
    ghost column parametrized to Q)."""
    net.eval()
    cols = {L: [] for L in letter_ids}
    for i in range(0, ids.shape[0], 30):
        lg, _ = net(ids[i:i + 30])
        pr = F.softmax(lg[:, -1], -1)
        for L, lid in letter_ids.items():
            cols[L].append(pr[:, lid])
    out = {f"p_{L}": float(torch.cat(v).mean()) for L, v in cols.items()}
    out["pn_total"] = float(sum(out[f"p_{L}"] for L in letter_ids))
    qv = torch.cat(cols["Q"])
    out["ghost_median"] = float(qv.median())
    out["ghost_max"] = float(qv.max())
    out["ghost_frac_ge_005"] = float((qv >= 0.05).float().mean())
    return out


