class SpanProjector:
    """e246's fixed-span adapter, LOADED here from e246_late_span.pt for
    the observational span co-read ONLY (never a write): cos-to-span of
    displacements + per-step gradient in-span fractions."""

    def __init__(self, Vp: torch.Tensor, params_ref, dev: torch.device):
        self.k = int(Vp.shape[0])
        self.P = int(Vp.shape[1])
        self.slices = []
        off = 0
        for p in params_ref:
            n = p.numel()
            self.slices.append(Vp[:, off:off + n].to(dev, torch.float64)
                               .contiguous())
            off += n
        assert off == self.P, f"span flat size {off} != {self.P}"
        # per-coordinate span energy (for the set-capture read)
        col_e = (Vp.double() ** 2).sum(0)
        self.col_energy_cpu = col_e

    def grad_in_span_frac(self, params) -> float:
        """||S^T g||/||g|| on the post-clip gradient (fp64, GPU; the
        FULL cross-slice two-pass form)."""
        params = list(params)
        c_full = torch.zeros(self.k, dtype=torch.float64,
                             device=self.slices[0].device)
        gn2 = 0.0
        for p, S in zip(params, self.slices):
            g64 = p.grad.detach().reshape(-1).to(torch.float64)
            c_full += S @ g64
            gn2 += float(g64 @ g64)
        return math.sqrt(float(c_full @ c_full)) / math.sqrt(gn2) \
            if gn2 > 0 else 0.0

    def cos_to_span(self, flat_cpu: torch.Tensor) -> float:
        """||S^T d|| / ||d|| — the amplitude fraction of a displacement
        inside the span (fp64, CPU; the full cross-slice form)."""
        d64 = flat_cpu.to(torch.float64)
        n2 = float(d64 @ d64)
        c_full = torch.zeros(self.k, dtype=torch.float64)
        off = 0
        for S in self.slices:
            n = S.shape[1]
            Sc = S.detach().to(CPU)
            c_full += Sc @ d64[off:off + n]
            off += n
        s2 = float(c_full @ c_full)
        return math.sqrt(s2) / math.sqrt(n2) if n2 > 0 else 0.0

    def set_capture(self, flat_idx: torch.Tensor) -> float:
        """The fraction of the span's coordinate energy inside a
        coordinate set (observational; fp64 CPU)."""
        ce = self.col_energy_cpu[flat_idx.to(CPU).long()]
        return float(ce.sum() / self.col_energy_cpu.sum())


class CoordMaskProjector:
    """THE DIRECTION-SET PROJECTOR (the cell's only intervention): per-
    parameter 0/1 masks (the exact orthogonal projector onto a coordinate
    subspace) + the v-map's fp32 GPU slices for the measured-load ledger.

    The ledger (fp64 per-parameter dots): gn = ||g||, gpn = ||g'||,
    kept_frac = ||g'||/||g||, v_excess_pre = (sum g^2 v / ||g||^2)/mean_v
    (e257's qov convention at step level), v_excess_post = same on g'.
    VHEAVY/VLIGHT write p.grad *= w; FREE computes the ledger READ ONLY
    (the verbatim trajectory)."""

    def __init__(self, set_idx: torch.Tensor, n_params: int, params_ref,
                 v_flat64: torch.Tensor, dev: torch.device):
        mask_flat = torch.zeros(n_params, dtype=torch.bool)
        mask_flat[set_idx.to(CPU).long()] = True
        self.k = int(set_idx.numel())
        self.n = int(n_params)
        self.mean_v = float(v_flat64.mean())
        v32 = v_flat64.to(torch.float32)
        self.masks, self.v32 = [], []
        off = 0
        for p in params_ref:
            n = p.numel()
            self.masks.append(mask_flat[off:off + n].to(dev).contiguous())
            self.v32.append(v32[off:off + n].to(dev).contiguous())
            off += n
        assert off == n_params, f"mask flat size {off} != {n_params}"

    def step_hook(self, params, mode: str) -> dict:
        params = list(params)
        gn2 = gpn2 = num_pre = num_post = 0.0
        with torch.no_grad():
            for p, w, v in zip(params, self.masks, self.v32):
                g64 = p.grad.detach().reshape(-1).to(torch.float64)
                v64 = v.to(torch.float64)
                g2 = g64 * g64
                gn2 += float(g2.sum())
                num_pre += float((g2 * v64).sum())
                if mode != "FREE":
                    g64m = g64 * w.to(torch.float64)
                    g2m = g64m * g64m
                    gpn2 += float(g2m.sum())
                    num_post += float((g2m * v64).sum())
                    p.grad.mul_(w.reshape(p.shape))   # the smoke's catch #2:
                    # the mask is flat; the write needs the param's shape
                else:
                    gpn2 = gn2
                    num_post = num_pre
        gn = math.sqrt(gn2)
        return {"gn": gn, "gpn": math.sqrt(gpn2),
                "kept_frac": math.sqrt(gpn2) / gn if gn > 0 else 0.0,
                "v_excess_pre": (num_pre / gn2 / self.mean_v)
                if gn2 > 0 else 0.0,
                "v_excess_post": (num_post / gpn2 / self.mean_v)
                if gpn2 > 0 else 0.0}


def displacement_loads(flat_cpu: torch.Tensor, v_flat64: torch.Tensor,
                       mask_flat: torch.Tensor | None) -> dict:
    """The measured loads of a displacement (flat CPU fp64, the
    net.parameters() basis): the v-excess (e257's qov convention) + the
    optional mass-in-set fraction. Pure fp64 algebra."""
    d64 = flat_cpu.to(torch.float64).double()
    d2 = d64 * d64
    tot = float(d2.sum())
    out = {"v_excess": float((d2 * v_flat64).sum() / tot
                             / float(v_flat64.mean())) if tot > 0 else 0.0}
    if mask_flat is not None:
        out["mass_in_set"] = float(d2[mask_flat].sum() / tot) \
            if tot > 0 else 0.0
    return out


