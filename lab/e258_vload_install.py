def make_vmap_plot(rd, v64, heavy_idx, light_idx, k, arms_rec, comp,
                   step_norm_diffs, moment_rows, thermal_log, span_capture,
                   verdict):
    """THE INSTRUMENT FIGURE: the v-map + the sets, the measured per-arm
    loads, the certification, and the thermal envelope."""
    fig, axes = plt.subplots(2, 2, figsize=(15.0, 10.0))
    col = {"VHEAVY": "#c0392b", "VLIGHT": "#1a6faf", "FREE": "#e67e22"}

    # (0,0) THE V-MAP (sorted v, log scale, the sets shaded)
    ax = axes[0, 0]
    sv, _ = torch.sort(v64)
    stride = max(1, len(sv) // 4000)
    svv = sv[::stride].clamp(min=1e-30).numpy()
    xs = np.linspace(0, 1, len(svv))
    ax.semilogy(xs, svv, lw=1.6, color="#8e44ad")
    ax.axvspan(0, k / len(sv), color="#1a6faf", alpha=0.30,
               label=f"VLIGHT set (k={k}; load "
               f"{float(v64[light_idx].mean()) / float(v64.mean()):.4f}x)")
    ax.axvspan(1 - k / len(sv), 1, color="#c0392b", alpha=0.30,
               label=f"VHEAVY set (k={k}; load "
               f"{float(v64[heavy_idx].mean()) / float(v64.mean()):.1f}x)")
    ax.set_xlabel("coordinate rank (sorted by v)")
    ax.set_ylabel("v (the standing second moment)")
    ax.legend(fontsize=7.4, loc="upper center")
    ax.grid(alpha=0.25, which="both")
    ax.set_title("THE V-MAP at the committed g1c root (20-step seed-10902 "
                 "history, fp64 recursion)", fontsize=10)

    # (0,1) THE MEASURED LOADS per arm
    ax = axes[0, 1]
    names = list(ARMS)
    w = 0.27
    xs = np.arange(len(names))
    pre = [arms_rec[a]["install"]["ledger_v_excess_pre_median"]
           for a in names]
    post = [arms_rec[a]["install"]["ledger_v_excess_post_median"]
           for a in names]
    droot = [arms_rec[a]["root"]["displacement_loads"]["v_excess"]
             for a in names]
    ax.bar(xs - w, [p if p is not None else 0 for p in pre], width=w,
           color="#7fb3d5", alpha=0.9, label="install |g| v-excess (ledger med)")
    ax.bar(xs, [p if p is not None else 0 for p in post], width=w,
           color="#1a6faf", alpha=0.9, label="install |g'| v-excess (applied)")
    ax.bar(xs + w, droot, width=w, color="#c0392b", alpha=0.65,
           label="root displacement v-excess")
    ax.axhline(1.0, color="k", ls=":", lw=0.9, label="the uniform baseline")
    for i, a in enumerate(names):
        misset = arms_rec[a]["root"]["displacement_loads"].get("mass_in_set")
        if misset is not None:
            ax.annotate(f"in-set {misset:.2f}", (i + w, droot[i]),
                        ha="center", fontsize=6.4, color="dimgray")
    ax.set_xticks(xs)
    ax.set_xticklabels(names, fontsize=8)
    ax.set_ylabel("v-excess (measured; e257's qov convention)")
    ax.set_yscale("symlog", linthresh=1.0)
    ax.legend(fontsize=6.8, loc="best")
    ax.grid(alpha=0.25, axis="y")
    ax.set_title("THE MEASURED PER-ARM LOADS (never nominal); span capture "
                 f"VH {span_capture['vheavy']:.3f} / VL "
                 f"{span_capture['vlight']:.3f}", fontsize=9.5)

    # (1,0) THE CERTIFICATION (G_STEP per step + G_MOMENT at archives)
    ax = axes[1, 0]
    ax.semilogy(range(1, len(step_norm_diffs) + 1), step_norm_diffs, "o-",
                ms=5, lw=1.6, color="#1a6faf",
                label=f"G_STEP rel diff (max {max(step_norm_diffs):.1e}, "
                      f"bar 1e-3)")
    for ka, row in sorted(moment_rows.items()):
        ax.axhline(row["v_max_abs_diff"] / max(row["v_max"], 1e-30),
                   ls="--", lw=0.9, alpha=0.7,
                   label=f"G_MOMENT v-rel @{ka} "
                         f"{row['v_max_abs_diff'] / max(row['v_max'], 1e-30):.1e}")
    ax.set_xlabel("history step")
    ax.set_ylabel("relative difference (log)")
    ax.legend(fontsize=7.0)
    ax.grid(alpha=0.25, which="both")
    ax.set_title("THE V-MAP'S CERTIFICATION (e240's stack, 2.74M form)",
                 fontsize=10)

    # (1,1) the kept-fraction ledger + the thermal envelope
    ax = axes[1, 1]
    for arm in ARMS:
        led = arms_rec[arm]["install"]["ledger"]
        xs_l = sorted(int(s) for s in led)
        get = lambda s: led[s] if s in led else led[str(s)]
        ax.plot(xs_l, [get(s)["kept_frac"] for s in xs_l], "o-",
                ms=3.2, lw=1.3, color=col[arm], alpha=0.9,
                label=f"ARM-{arm} ||g'||/||g||")
    ax.set_xlabel("install step")
    ax.set_ylabel("the kept-gradient fraction (dose honesty)")
    ax.legend(fontsize=7.4)
    ax.grid(alpha=0.25)
    axb = ax.twinx()
    if thermal_log:
        axb.plot([r["t"] for r in thermal_log], [r["temp"] for r in thermal_log],
                 "-", lw=0.8, color="dimgray", alpha=0.7)
        axb.axhline(TEMP_EARLY_END, color="crimson", ls=":", lw=1.0)
        axb.axhline(TEMP_HARD, color="crimson", ls="--", lw=1.2)
        axb.set_ylabel("GPU temp (C) per-step polls", color="dimgray")
        axb.tick_params(axis="y", colors="dimgray")
    ax.set_title("THE KEPT-FRACTION LEDGER + the thermal envelope (bursts "
                 "end at the 78C margin)", fontsize=9.5)

    fig.suptitle("E258 — the instrument page: the v-map, the direction "
                 "sets, the measured loads, the certification", fontsize=11)
    fig.tight_layout(rect=(0, 0, 1, 0.94))
    fig.savefig(rd / "e258_vmap_instrument.png", dpi=130)
    plt.close(fig)


