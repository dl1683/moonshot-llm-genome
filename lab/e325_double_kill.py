def git_head() -> str:
    try:
        return subprocess.run(["git", "rev-parse", "HEAD"], cwd=str(REPO),
                              capture_output=True, text=True,
                              timeout=10).stdout.strip()
    except Exception:                                       # noqa: BLE001
        return "unavailable"


def git_commit_push(msg: str, paths: list[str], allow_empty: bool = False):
    """Commit ONLY this cell's paths; push to origin main. Foreign staged
    paths (the shared-index race x29 documented) are unstaged + retried
    once, disclosed."""
    import shutil
    for attempt in range(2):
        try:
            if paths:
                subprocess.run(["git", "add", *paths], cwd=str(REPO),
                               check=True, timeout=60)
            r = subprocess.run(["git", "commit", "-m", msg]
                               + (["--allow-empty"] if allow_empty else []),
                               cwd=str(REPO), capture_output=True, text=True,
                               timeout=60)
            if r.returncode != 0:
                err = (r.stdout + r.stderr)
                if "foreign" in err.lower() or "paths" in err.lower():
                    staged = subprocess.run(
                        ["git", "diff", "--cached", "--name-only"],
                        cwd=str(REPO), capture_output=True, text=True,
                        timeout=10).stdout.split()
                    foreign = [p for p in staged
                               if not (p.startswith("lab/e325")
                                       or p.startswith("runs/e325/"))]
                    if foreign and attempt == 0:
                        subprocess.run(["git", "reset", "--", *foreign],
                                       cwd=str(REPO), timeout=30)
                        log(f"[git] HOOK: foreign staged paths unstaged + "
                            f"retry (disclosed): {foreign}")
                        continue
                log(f"[git] commit skipped: {err.strip()[:200]}")
                return git_head()
            subprocess.run(["git", "push", "origin", "main"], cwd=str(REPO),
                           capture_output=True, text=True, timeout=120)
            h = git_head()
            log(f"[git] committed + pushed {h[:12]}: {msg[:90]}")
            return h
        except Exception as e:                              # noqa: BLE001
            log(f"[git] ERROR: {e}")
            return git_head()
    return git_head()


