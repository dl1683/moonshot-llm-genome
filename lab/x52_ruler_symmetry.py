def match_arm(arm_rows: list[dict], pool_rows: list[dict]) -> list[dict]:
    """x45's frozen nearest-read pairing: each arm row -> the pooled
    reference row at minimal |read difference| (many-to-one allowed);
    state-identity exclusion (a row never pairs its own state)."""
    pairs = []
    for a in arm_rows:
        cands = [r for r in pool_rows if r["tag"] != a["tag"]]
        best = min(cands, key=lambda r: abs(r["read"] - a["read"]))
        d_read = abs(best["read"] - a["read"])
        pair = {
            "arm_tag": a["tag"], "arm_read": a["read"],
            "arm_src": a["src"], "arm_net0": a.get("net0_class"),
            "ref_tag": best["tag"], "ref_read": best["read"],
            "ref_strata": best["strata"], "ref_x42": best.get("x42_rungs"),
            "ref_net0": best.get("net0_class"),
            "abs_d_read": d_read,
            "in_window": bool(d_read <= MATCH_WINDOW),
        }
        for key in ALL_KEYS:
            av = row_observable(a, key)
            rv = row_observable(best, key)
            pair[key] = {"arm": av, "ref": rv,
                         "d": (None if av is None or rv is None
                               else av - rv)}
        pairs.append(pair)
    return pairs


def floor_for(key: str, pairs_in_window: list[dict]):
    """x45's frozen floors (verbatim kinds)."""
    if key == "write_norm":
        vals = [(abs(p[key]["arm"]) + abs(p[key]["ref"])) / 2
                for p in pairs_in_window if p[key]["d"] is not None]
        base = (sum(vals) / len(vals)) if vals else 0.0
        return FLOOR_NORM_REL * base, f"relative 0.15 x mean pair norm = {FLOOR_NORM_REL * base:.3f}"
    if key == "in_room":
        return FLOOR_INROOM, "absolute 0.05"
    if key.startswith("alive"):
        return FLOOR_ALIVE, "absolute 0.10 (x40's clause)"
    return FLOOR_CORR, "absolute 0.15 (1/sqrt(59))"


def score_pairs(pairs: list[dict]) -> dict:
    """x45's frozen separation scoring over IN-WINDOW pairs; P-T334a's
    decorrelation form (sign - + consistency >= 0.75) co-scored per key."""
    in_window = [p for p in pairs if p["in_window"]]
    out = {}
    for key in ALL_KEYS:
        ds = [p[key]["d"] for p in in_window if p[key]["d"] is not None]
        n_none = sum(1 for p in in_window if p[key]["d"] is None)
        if not ds:
            out[key] = {"n_pairs": 0, "n_none": n_none,
                        "dominant_sign": None,
                        "sign_consistency": None, "mean_abs_d": None,
                        "floor": None, "separates": False,
                        "decorrelated_form": False,
                        "note": "no valid pairs"}
            continue
        n_pos = sum(1 for d in ds if d > 0)
        n_neg = sum(1 for d in ds if d < 0)
        dom = "+" if n_pos >= n_neg else "-"
        cons = max(n_pos, n_neg) / len(ds)
        mean_abs_d = sum(abs(d) for d in ds) / len(ds)
        floor, floor_kind = floor_for(key, in_window)
        out[key] = {
            "n_pairs": len(ds), "n_none": n_none,
            "dominant_sign": dom,
            "sign_consistency": round(cons, 4),
            "mean_abs_d": round(mean_abs_d, 6),
            "floor": round(floor, 6), "floor_kind": floor_kind,
            "separates": bool(cons >= SIGN_FRAC and mean_abs_d >= floor),
            # P-T334a's own form (the walk bar): sign - at >= 0.75
            "decorrelated_form": bool(dom == "-" and cons >= SIGN_FRAC),
        }
    return out


