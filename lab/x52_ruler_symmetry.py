def emergence_shape(live: dict) -> dict:
    """x50's frozen emergence rule on the dense C(s) curve (T channel)."""
    rows = sorted((r for k, r in live["rows"].items()
                   if k.startswith("rider_")),
                  key=lambda r: r["step"])
    curve = [{
        "step": r["step"], "read": r["read"],
        "r1": r["corrs"]["g-12|g0"], "r2": r["corrs"]["g0|g+12"],
        "C": (min(r["corrs"]["g-12|g0"], r["corrs"]["g0|g+12"])
              if r["corrs"]["g-12|g0"] is not None
              and r["corrs"]["g0|g+12"] is not None else None),
        "raw_collapse": bool(r["corrs"]["g-12|g0"] is not None
                             and r["corrs"]["g-12|g0"] <= RAW_BAR),
    } for r in rows]
    seq = [c for c in curve if c["C"] is not None]
    coherent_runs, cur = [], []
    for c in seq:
        if c["C"] >= COH_BAR:
            cur.append(c)
        else:
            if len(cur) >= MIN_COH_RUNGS:
                coherent_runs.append(cur)
            cur = []
    if len(cur) >= MIN_COH_RUNGS:
        coherent_runs.append(cur)
    before = after = None
    for run in coherent_runs:
        last_coh_step = run[-1]["step"]
        rest = [c for c in seq if c["step"] > last_coh_step]
        for c in rest:
            w0, w1 = c["step"], min(c["step"] + AFTER_SPAN, ANNEAL_STEPS)
            win = [q for q in seq if w0 <= q["step"] <= w1]
            if len(win) >= 2 and all(q["C"] <= DECO_LEVEL for q in win):
                before, after = run, c
                break
        if after is not None:
            break
    em = {"coh_bar": COH_BAR, "deco_level": DECO_LEVEL,
          "n_dense_rungs": len(seq),
          "coherent_runs": ([[c["step"] for c in run]
                             for run in coherent_runs] or None),
          "before_state": ([c["step"] for c in before] if before else None),
          "after_state_start": (after["step"] if after else None)}
    if before is not None and after is not None:
        s_lo, s_hi = before[-1]["step"], after["step"]
        width = s_hi - s_lo
        inside = [c for c in seq if s_lo <= c["step"] <= s_hi]
        deltas = [inside[i + 1]["C"] - inside[i]["C"]
                  for i in range(len(inside) - 1)]
        frac_neg = (sum(1 for d in deltas if d < 0) / len(deltas)
                    if deltas else 0.0)
        shape = ("STEP" if width <= STEP_WIDTH
                 else ("RAMP" if width <= RAMP_WIDTH
                       and frac_neg >= RAMP_MONO else "OSCILLATION"))
        em.update({"window": [s_lo, s_hi], "width_steps": width,
                   "frac_negative_deltas": round(frac_neg, 4),
                   "shape": shape})
    else:
        em["sub_class"] = ("NO-BEFORE (never >= 2 consecutive coherent "
                           "rungs)" if not coherent_runs
                           else "NO-AFTER (no sustained <= 0.50 window)")
    # the two-act clause (P-T333a's askable half): an early oscillating
    # emergence (window starting <= ~30) AND a sharp consolidation
    # (width <= 10) — x50's walk showed [s10,s30] + [s50,s55]
    two_act = None
    if "window" in em:
        two_act = bool(em["window"][0] <= 30 and em["width_steps"] <= 10)
    em["two_act_repeats"] = two_act
    em["walks_reference_shape"] = {"x50_walk": ("emergence [s10,s30] "
                                                "OSCILLATION; "
                                                "consolidation [s50,s55] "
                                                "single 5-step drop"),
                                   "clause": ("TWO-ACT-REPEATS iff an "
                                              "emergence window starts "
                                              "<= s30 AND its "
                                              "consolidation width is "
                                              "<= 10 steps")}
    em["raw_collapse_hits"] = [c["step"] for c in curve
                               if c["raw_collapse"]]
    em["s125_fine_window"] = [{"step": c["step"], "r1": c["r1"],
                               "r2": c["r2"], "C": c["C"]}
                              for c in curve if 112 <= c["step"] <= 138]
    return {"curve": curve, "emergence": em}


def phase_P3(p2: dict) -> dict:
    log("P3 — THE RIDER ADJUDICATION (the ruler-internal tests + the "
        "emergence shape)")
