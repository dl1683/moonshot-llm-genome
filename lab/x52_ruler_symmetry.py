def rider_internal_dense(live: dict, x45m: dict) -> dict:
    """The dense ruler-internal test: the 62 NON-panel dense rungs (arm)
    vs the 14 committed ruler rows in-window (reference), x45's rules."""
    ruler_tags = ([f"anneal_s{s}" for s in sorted(PANEL_STEPS)]
                  + ["ann_s0", "ann_s300"])
    arm_rows, ref_rows = [], []
    for k, r in live["rows"].items():
        if k.startswith("rider_") and r["step"] not in PANEL_STEPS:
            arm_rows.append(r)
    for t in ruler_tags:
        r = x45m["anneal"]["panels"][t]
        rr = dict(r)
        rr["tag"] = t
        ref_rows.append(rr)
    pairs = []
    for a in arm_rows:
        cands = [r for r in ref_rows if r["tag"] != a["tag"]]
        best = min(cands, key=lambda r: abs(r["read"] - a["read"]))
        d_read = abs(best["read"] - a["read"])
        pair = {"arm_tag": a["tag"], "arm_read": a["read"],
                "arm_step": a["step"], "arm_grain": a.get("grain"),
                "ref_tag": best["tag"], "ref_read": best["read"],
                "ref_provenance": best.get("provenance"),
                "abs_d_read": d_read,
                "in_window": bool(d_read <= MATCH_WINDOW)}
        for key in ALL_KEYS:
            av = row_observable(a, key)
            rv = row_observable(best, key)
            pair[key] = {"arm": av, "ref": rv,
                         "d": (None if av is None or rv is None
                               else av - rv)}
        pairs.append(pair)
    scored = score_pairs(pairs)
    return {"pairs": pairs, "scored": scored,
            "n_arm": len(arm_rows), "n_ref": len(ref_rows),
            "n_in_window": sum(1 for p in pairs if p["in_window"]),
            "note": ("arm-side = the replay's non-panel dense rungs "
                     "(62 at full grain); ruler-side = the committed "
                     "panels s25..s300 + the ann_s0/ann_s300 anchors "
                     "(the ruler's actual composition in-window)")}


