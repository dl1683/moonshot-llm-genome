def flat_params_cpu(net) -> torch.Tensor:
    return torch.cat([p.detach().reshape(-1).cpu()
                      for p in net.parameters()]).clone()


@torch.no_grad()
def site_read(net, ids: torch.Tensor, bs: int = 30) -> dict:
    """x24's site_read VERBATIM (works on every net whose forward returns
    (logits, ...) — CommittedGPT and TinyGPT both do)."""
    net.eval()
    rows, tops, ents = [], [], []
    for i in range(0, ids.shape[0], bs):
        lg, _ = net(ids[i:i + bs])
        pr = F.softmax(lg[:, -1], -1)
        rows.append(pr)
        tops.append(pr.max(-1).values)
        ents.append(-(pr * torch.log(pr.clamp_min(1e-30))).sum(-1))
    probs = torch.cat(rows)                       # [60, vocab]
    return {"probs": probs,
            "rider_mean_top1_p": float(torch.cat(tops).mean()),
            "rider_mean_entropy": float(torch.cat(ents).mean())}


def name_read(site: dict, cid: int) -> dict:
    """x24's name_read VERBATIM (the committed statistics)."""
    p = site["probs"][:, cid]
    lg = torch.log(p.clamp_min(1e-30))
    return {"mean_pz": float(p.mean()), "median_pz": float(p.median()),
            "frac_pz_ge_0.5": float((p >= 0.5).float().mean()),
            "frac_pz_ge_0.05": float((p >= 0.05).float().mean()),
            "frac_argmax_z": float((site["probs"].argmax(-1) == cid)
                                   .float().mean()),
            "mean_log_pz": float(lg.mean())}


def inroom_frac(room, v64: np.ndarray) -> float:
    vn = float(np.linalg.norm(v64))
    if vn == 0.0:
        return 0.0
    return float(np.linalg.norm(room.project(v64)) / vn)


def inroom_energy_share(room, v64: np.ndarray) -> float:
    e = float(v64 @ v64)
    if e == 0.0:
        return 0.0
    p = room.project(v64)
    return float((p @ p) / e)


def _ranks(v):
    order = sorted(range(len(v)), key=lambda i: v[i])
    r = [0.0] * len(v)
    i = 0
    while i < len(order):
        j = i
        while j + 1 < len(order) and v[order[j + 1]] == v[order[i]]:
            j += 1
        avg = (i + j) / 2.0 + 1.0
        for k in range(i, j + 1):
            r[order[k]] = avg
        i = j + 1
    return r


def spearman(x, y) -> float:
    rx, ry = _ranks(list(x)), _ranks(list(y))
    mx, my = sum(rx) / len(rx), sum(ry) / len(ry)
    num = sum((a - mx) * (b - my) for a, b in zip(rx, ry))
    den = math.sqrt(sum((a - mx) ** 2 for a in rx)
                    * sum((b - my) ** 2 for b in ry))
    return num / den if den > 0 else 0.0


def make_gauss(N: int, seed: int = GAUSS_SEED,
               norm: float = GAUSS_NORM) -> np.ndarray:
    """x25's construction: default_rng(seed).standard_normal(N), fp64,
    normalized to the exact matched dose (in place)."""
    rng = np.random.default_rng(seed)
    g = rng.standard_normal(N)
    g *= (norm / float(np.linalg.norm(g)))
    return g


def unflat_like(sd: dict, flat64: np.ndarray) -> dict:
    out, off = {}, 0
    for k in sd:
        n = sd[k].numel()
        out[k] = torch.from_numpy(
            np.ascontiguousarray(flat64[off:off + n])) \
            .reshape(sd[k].shape)
        off += n
    return out


