def arm_wash_summary(w: dict) -> dict:
    reads = {r["step"]: r["read_g0_pT"] for r in w["traj"]}
    t0v = reads[0]
    s1 = reads.get(1)
    s_end = reads[max(reads)]
    panel_steps = [s for s in E38.WASH_PANELS if s > 0 and s in reads]
    return {"t0": t0v, "s1": s1, "s_end": s_end,
            "end_step": max(reads), "retention": s_end / t0v,
            "min_panel_read": min(reads[s] for s in panel_steps),
            "all_panels_ge_005": all(reads[s] >= READ_BAR
                                     for s in panel_steps),
            "s1_alive": (None if s1 is None else bool(s1 >= READ_BAR)),
            "traj": w["traj"]}


def leg_reads(traj: list[dict]) -> dict:
    """the leg-boundary reads + the leg tail means (the robustness
    co-report)."""
    reads = {r["step"]: r["read_g0_pT"] for r in traj}
    out = {}
    for L in LEGS:
        tail = [v for s, v in reads.items()
                if L - TAIL_WINDOW < s <= L]
        out[L] = {"t0": reads[L],
                  "tail_mean": (sum(tail) / len(tail)) if tail else None,
                  "tail_n": len(tail)}
    return out


