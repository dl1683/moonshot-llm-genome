    n_pool, n_anc = pool_x.shape[0], cons_anchor.shape[0]
    train_ids = p0["train_ids"]
    g0_ids, gm12_ids = p0["g0_ids"], p0["gm12_ids"]
    tid, zid = p0["tid"], p0["zid"]

    state = {"step": 0, "traj": [], "draws": []}
    if resume_ck.exists():
        state = torch.load(resume_ck, map_location="cpu", weights_only=False)
        log(f"  [ANNEAL] RESUMED at step {state['step']}/{n_steps}")

    leg_snapshots: dict[int, dict] = {}
    for L in LEGS:
        fp = RD / f"x43_anneal_leg{L}.pt"
        if fp.exists():
            art = torch.load(fp, map_location="cpu", weights_only=False)
            leg_snapshots[L] = {k: v for k, v in art["model"].items()}
            log(f"  [ANNEAL] leg {L} snapshot already on disk")

    if int(state.get("step", 0)) >= n_steps and len(leg_snapshots) == len(LEGS):
        log("  [ANNEAL] resume ckpt already COMPLETE at "
            f"s{state['step']} (all {len(LEGS)} legs snapshotted)")
        return {"traj": state["traj"], "draws": state["draws"],
                "leg_sds": leg_snapshots, "steps_ran": n_steps,
                "resumed_final": True}

    net0 = G1.evl_load(theta_sd)             # the plain load (uncommitted)
    have_cuda = torch.cuda.is_available()
    dev = torch.device("cuda") if have_cuda else CPU
    if have_cuda:
        t_burst = E38.E261._open_burst("ANNEAL-leg1")[0]
    else:
        device_events.append({"tag": "ANNEAL", "event": "NO CUDA — CPU PARK",
                              "cap_s": TRAIN_CAP_CPU})
        log("  [gpu] no CUDA device — the anneal parks to CPU (recorded; "
            "cap 1800s)")
        t_burst = time.time()

    net = copy.deepcopy(net0).to(dev)
    net.train()
    opt = torch.optim.AdamW(net.parameters(), lr=ANNEAL_LR,
                            betas=ANNEAL_BETAS, weight_decay=ANNEAL_WD)
    gen = torch.Generator().manual_seed(ANNEAL_SEED)
    evl = copy.deepcopy(net0).to(CPU)         # the CPU eval twin
    if resume_ck.exists():
        net.load_state_dict(state["model"])
        net.to(dev)
        net.train()
        opt.load_state_dict(state["opt"])
        gen.set_state(state["gen_state"])

    def panel(step: int) -> float:
        sd_cpu = {k: v.detach().cpu().clone()
                  for k, v in net.state_dict().items()}
        evl.load_state_dict(sd_cpu)
        evl.eval()
        pt = G1.battery_cell(evl, g0_ids, tid)       # THE READ p(T)@g0
        pt12 = G1.battery_cell(evl, gm12_ids, tid)
        pz = G1.battery_cell(evl, g0_ids, zid)       # the host watch
        ce_r = G1.ce_fixed_cpu(evl, *p0["r_eval_xy"])
        cur = flat_params_cpu(net)
        row = {"step": step, "read_g0_pT": pt["mean_pz"],
               "gm12_pT": pt12["mean_pz"], "host_g0_pZ": pz["mean_pz"],
               "ce_r": ce_r, "disp": float(torch.norm(
                   cur - flat_params_cpu(net0))),
               "elapsed_s": round(time.time() - T0, 1)}
        state["traj"].append(row)
        log(f"  [ANNEAL] s{step:4d} READ p(T) {row['read_g0_pT']:.4f} | "
            f"gm12 {row['gm12_pT']:.4f} | host p(Z) "
            f"{row['host_g0_pZ']:.4f} | CE_R {row['ce_r']:.4f}"
            + ("  *** LEG BOUNDARY ***" if step in LEGS else ""))
        return float(row["read_g0_pT"])

    def snapshot_leg(step: int, read: float) -> None:
        sd_leg = {k: v.detach().cpu().clone()
                  for k, v in net.state_dict().items()}
        # the reload-verify (e341's final-read repro convention, 2e-6)
        vnet = G1.evl_load(sd_leg)
        vnet.eval()
        vread = G1.battery_cell(vnet, g0_ids, tid)["mean_pz"]
        del vnet
        ok = abs(vread - read) <= READ_TOL
        assert ok, (f"leg {step} snapshot reload-verify FAILED: "
                    f"{vread} vs {read}")
        fp = RD / f"x43_anneal_leg{step}.pt"
        torch.save({"model": sd_leg,
                    "meta": {"experiment": NAME, "arm": f"leg{step}",
                             "desc": (f"the extended varied anneal's "
                                      f"step-{step} state (e311's TAVIREN "
                                      f"subject + the cons's e113 "
                                      f"annealing continued, seed "
                                      f"{ANNEAL_SEED})"),
                             "seed": ANNEAL_SEED, "steps": step,
                             "pool_size": int(pool_x.shape[0]),
                             "reload_read": vread}}, fp)
        leg_snapshots[step] = sd_leg
        log(f"  [leg] step-{step} state snapshotted + reload-verified "
            f"({vread:.10f}) -> {fp.name}")

    def save_resume() -> None:
        torch.save({"model": {k: v.detach().cpu().clone()
                              for k, v in net.state_dict().items()},
                    "opt": opt.state_dict(), "gen_state": gen.get_state(),
                    "step": state["step"], "traj": state["traj"],
                    "draws": state["draws"]}, resume_ck)

    step = state["step"]
    n_bursts = 1
    if step == 0:
        panel(0)
    while step < n_steps:
        step += 1
        # e341's draws VERBATIM (one generator, interleaved order — the
        # stream G_STREAM proves identical to e341's first 300)
        ix = torch.randint(n_pool, (16,), generator=gen)
        aj = torch.randint(n_anc, (8,), generator=gen)
        rj = torch.randint(len(train_ids) - G1.BLOCK - 1, (8,),
                           generator=gen)
        state["draws"].append({"step": step, "ix": ix.tolist(),
                               "aj": aj.tolist(), "rj": rj.tolist()})
        nw = pool_x[ix].to(dev)
        anc = torch.cat([cons_anchor[aj],
                         torch.stack([train_ids[s: s + G1.BLOCK]
                                      for s in rj])], 0).to(dev)
        x = torch.cat([nw[:, :-1], anc[:, :-1]], 0)
        y = torch.cat([nw[:, 1:], anc[:, 1:]], 0)
        m = torch.zeros(32, x.shape[1], dtype=torch.bool, device=dev)
        m[:16] = pool_mask[ix].to(dev)
        logits, _ = net(x)
        nll = F.cross_entropy(logits.reshape(-1, logits.shape[-1]),
                              y.reshape(-1), reduction="none"
                              ).view(x.shape[0], x.shape[1])
        nm = nll[:16][m[:16]]
        cm = nll[16:]
        loss = (nm.sum() + cm.sum()) / (nm.numel() + cm.numel())
        opt.zero_grad(set_to_none=True)
        loss.backward()
        torch.nn.utils.clip_grad_norm_(net.parameters(), ANNEAL_CLIP)
        opt.step()
        state["step"] = step
        if step % PANEL_EVERY == 0 or step == n_steps or SMOKE:
            read = panel(step)
            if step in LEGS and step not in leg_snapshots:
                snapshot_leg(step, read)
        if have_cuda:
            ok_t, _t = E38.E261.burst_temp_check(f"ANNEAL.s{step}")
            if not ok_t:
                save_resume()
                log("  [ANNEAL] burst ended (thermal margin); cooldown + "
                    "resume next pass")
                E38.E261.burst_cooldown("ANNEAL")
                t_burst = E38.E261._open_burst(
                    f"ANNEAL-leg{sum(1 for L in LEGS if L <= step) + 1}"
                    )[0]
                n_bursts += 1
        if (time.time() - t_burst) > E38.E261.BURST_MAX_S:
            save_resume()
            log("  [ANNEAL] burst cap; cooldown + resume next pass")
            if have_cuda:
                E38.E261.burst_cooldown("ANNEAL")
                t_burst = E38.E261._open_burst(
                    f"ANNEAL-leg{sum(1 for L in LEGS if L <= step) + 1}"
                    )[0]
                n_bursts += 1
    if have_cuda:
        E38.E261.burst_cooldown("ANNEAL-end")
    save_resume()
    # resume-completeness: every leg snapshotted (a resume that skipped a
    # boundary can no longer recover it — this asserts it never happened)
    assert all(L in leg_snapshots for L in LEGS), \
        f"legs missing snapshots: {[L for L in LEGS if L not in leg_snapshots]}"
    log(f"  [ANNEAL] COMPLETE: {n_steps} steps, {n_bursts} bursts, "
        f"{len(leg_snapshots)} leg snapshots")
    del net, opt, evl, net0
    if torch.cuda.is_available():
        torch.cuda.empty_cache()
    return {"traj": state["traj"], "draws": state["draws"],
            "leg_sds": leg_snapshots, "steps_ran": step,
            "resumed_final": False}


