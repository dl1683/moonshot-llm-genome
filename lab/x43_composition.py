def main() -> None:
    log(f"X43 — THE COMPOSITION CELL (smoke={SMOKE}) -> {RD}")
    metrics["birth_commit"] = BIRTH_COMMIT_PINNED
    write_partial("startup (bars registered, committed at birth)")
    set_seed(43001)              # global init only; every RNG is its own

    # ---- the harness's own phases (verbatim by import) ------------------
    p0 = E38.phase_P0()                        # the protocol rebuild
    p1 = E38.phase_P1(p0)                      # the subject (e311's)
    theta0 = p1["theta0"]
    p2x = phase_P2x()                          # the port + class gates
    pools = phase_P3x(p0)                      # the varied pool
    refs = p2x["refs"]

    # ---- THE ANNEAL, EXTENDED (one continuous stream, leg snapshots) ----
    log("=" * 78)
    log("PHASE A — THE ANNEAL, EXTENDED (the cons's e113 protocol driven "
        f"past its 300-step horizon: legs {list(LEGS)})")
    anneal = anneal_extend(theta0, pools["pool_v_x"], pools["pool_v_mask"],
                           pools["cons_anchor"], p0,
                           RD / "anneal_resume.pt")
    phase_stream(anneal["draws"])              # G_STREAM (the proof)
    legs = leg_reads(anneal["traj"])
    metrics["legs"] = {str(L): legs[L] for L in LEGS}
    metrics["anneal"] = {"steps": anneal["steps_ran"],
                         "seed": ANNEAL_SEED,
                         "n_leg_snapshots": len(anneal["leg_sds"])}
    write_partial("the anneal complete (legs read)")

    # ---- the bands (the harness's own reader) ---------------------------
    p3 = E38.phase_P3()

    # ---- THE COMMITS + THE WASHES (the composition) ----------------------
    log("=" * 78)
    log("PHASE B — THE COMPOSITION (commit(0.7) at every leg + the "
        "matched-anneal bare twin; e322's wash, bit-identical draws)")
    washes = {}
    nets = {}
    for L in LEGS:
        nets[L] = fire_commit(anneal["leg_sds"][L], f"LEG{L}")
    bare900 = G1.evl_load(anneal["leg_sds"][LEGS[-1]])  # the bare twin

    legs_order = [(f"LEG{L}-COMMIT", nets[L], True) for L in LEGS]
    legs_order.append(("LEG900-BARE", bare900, False))
    for i, (tag, net0, armed) in enumerate(legs_order):
        if i and torch.cuda.is_available():
            E38.E261.burst_cooldown(f"between-{tag}")
        washes[tag] = E38.wash_arm(tag, net0,
                                   RD / f"wash_{tag}_resume.pt", p0,
                                   armed=armed)
        del net0
    summaries = {tag: arm_wash_summary(w) for tag, w in washes.items()}
    metrics["washes"] = {k: {kk: vv for kk, vv in s.items() if kk != "traj"}
                         for k, s in summaries.items()}

    # ---- the match gates + the adjudication -------------------------------
    p6 = phase_P6x(washes, legs, refs)
    adj = adjudicate_x43(legs,
                         {f"LEG{L}-COMMIT": summaries[f"LEG{L}-COMMIT"]
                          for L in LEGS},
                         summaries["LEG900-BARE"],
                         p3["band"], refs, [])
    metrics["adjudication"] = adj
    metrics["thermal"] = {"max_temp": (max((r["temp"] for r in thermal_log),
                                           default=None)),
                          "polls": len(thermal_log),
                          "device_events": device_events}
    metrics["status"] = ("DONE (smoke; nothing adjudicated)" if SMOKE
                         else f"DONE: {adj['verdict']}")
    metrics["git_head_final"] = git_head()
    metrics["completed_utc"] = utcnow()
    save_json(RD / "metrics.json", metrics)

    make_png(adj, legs, anneal["traj"], p3["band"], refs)
    write_report(adj, legs, anneal["traj"], p3["band"], refs, p6)
    log(f"X43 VERDICT: {adj['verdict']}")


if __name__ == "__main__":
    main()
