def fire_commit(theta: dict, tag: str):
    """e341's fire_commit VERBATIM (itself the harness's phase_P2 firing
    lines): CommittedGPT(G1B_CFG) -> load_state_dict(theta) ->
    commit(0.7)."""
    net0 = G1.CommittedGPT(GB.G1B_CFG)       # the 2.74M family (GB rebind)
    net0.load_state_dict(theta)              # the body == the leg state
    net0.commit(E38.EVENT_R)                 # THE EVENT (R = the W1 dial)
    body, _anch = G1.split_anchored_sd(net0.state_dict())
    md = max(float((body[k].float() - theta[k].float()).abs().max())
             for k in theta)
    anch_ok = all(torch.equal(net0._anchor(n), p.detach())
                  for n, p in net0.named_parameters())
    g = {"arm": tag, "R": net0.R, "body_max_abs_diff": md,
         "anchors_bit_equal": bool(anch_ok),
         "anchored": bool(net0.anchored),
         "claim": (f"the {tag} armed net's body == the leg's annealed "
                   f"state bit-exact; the anchors bit-equal the "
                   f"parameters (the wall inert before the first "
                   f"forward)"),
         "pass": bool(abs(net0.R - E38.EVENT_R) <= 1e-6 and md == 0.0
                      and anch_ok and net0.anchored)}
