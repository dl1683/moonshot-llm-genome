# P3 — THE DRAW-ANATOMY DESK READ (zero model passes; the modifier hunt)
# ======================================================================
def anatomy_features(draws: list, p0: dict) -> dict:
    """The six named features, computed from ONE record + the shared
    pools ONLY (no model anywhere). Frozen at birth; see the docstring."""
    inst_a_x = p0["inst_a_x"]
    inst_a_mask = p0["inst_a_mask"]
    anchor_full = p0["anchor_full"]
    train_ids = p0["train_ids"]
    n = len(draws)
    ix = np.asarray([d["ix"] for d in draws], dtype=np.int64)   # (n,16)
    aj = np.asarray([d["aj"] for d in draws], dtype=np.int64)   # (n,16)
    rj = np.asarray([d["rj"] for d in draws], dtype=np.int64)   # (n,32)

    # F1 — the name-window win-rate chi2 (60 bins)
    counts = np.bincount(ix.ravel(), minlength=60).astype(np.float64)
    e = ix.size / 60.0
    chi2 = float(((counts - e) ** 2 / e).sum())

    # the batch content (shared pools, only indices differ)
    ixt = torch.as_tensor(ix)
    ajt = torch.as_tensor(aj)
    rjt = torch.as_tensor(rj)
    nt = inst_a_x[ixt]                       # (n,16,256)
    at = anchor_full[ajt]                    # (n,16,256)
    idx = rjt[..., None] + torch.arange(G1.BLOCK)
    rt = train_ids[idx]                      # (n,32,256)
    name_token_mass = int(inst_a_mask[ixt].sum())

    # F2 — the unigram token-mass (counts; TV computed pairwise later)
    uni = (np.bincount(nt.reshape(-1).numpy(), minlength=65)
           + np.bincount(at.reshape(-1).numpy(), minlength=65)
           + np.bincount(rt.reshape(-1).numpy(), minlength=65))

    # F4 — the character-bigram entropy over the full batch content
    bg = np.zeros(65 * 65, dtype=np.int64)
    for t in (nt, at, rt):
        tt = t.reshape(-1, G1.BLOCK).to(torch.int64)
        bgi = (tt[:, :-1] * 65 + tt[:, 1:]).reshape(-1).numpy()
        bg += np.bincount(bgi, minlength=65 * 65)
    p = bg.astype(np.float64) / bg.sum()
    p = p[p > 0]
    H = float(-(p * np.log2(p)).sum())

    # F3 — the positional spread (rj offsets: std + corpus coverage)
    off = rj.ravel().astype(np.float64)
    std = float(off.std())
    hits = np.zeros(len(train_ids), dtype=bool)
    for s in rj.ravel():
        hits[s:s + G1.BLOCK] = True
    coverage = float(hits.sum() / len(hits))

    # F5 — the lag-1 index autocorrelation (ix primary; aj co-report)
    def lag1(arr: np.ndarray) -> float:
        x = arr.ravel().astype(np.float64)
        a, b = x[:-1], x[1:]
        if a.std() == 0 or b.std() == 0:
            return float("nan")
        return float(np.corrcoef(a, b)[0, 1])

    lag1_ix, lag1_aj = lag1(ix), lag1(aj)

    # F6 — the early coupon speed (first 96 draws = 6 steps x 16)
    coupon96_ix = int(np.unique(ix[:6]).size)
    coupon96_aj = int(np.unique(aj[:6]).size)

    return {
        "n_steps": n,
        "F1_chi2_name_winrate": chi2,
        "F1_hottest_bin": int(counts.argmax()),
        "F1_coldest_bin": int(counts.argmin()),
        "F2_unigram_counts": uni.tolist(),
        "F2_name_token_mass": name_token_mass,
        "F3_rj_std": std,
        "F3_corpus_coverage": coverage,
        "F4_bigram_entropy_bits": H,
        "F5_lag1_ix": lag1_ix,
        "F5_lag1_aj": lag1_aj,
        "F6_coupon96_ix": coupon96_ix,
        "F6_coupon96_aj": coupon96_aj,
    }


