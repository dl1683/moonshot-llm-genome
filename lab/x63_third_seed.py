    feats = {sd: anatomy_features(rec, p0)
             for sd, rec in records.items()}
    for sd, f in feats.items():
        log(f"  [anatomy {sd}] F1 chi2 {f['F1_chi2_name_winrate']:.1f} | "
            f"F3 std {f['F3_rj_std']:.0f} cov {f['F3_corpus_coverage']:.4f}"
            f" | F4 H {f['F4_bigram_entropy_bits']:.5f} | F5 lag1 "
            f"{f['F5_lag1_ix']:+.4f} | F6 {f['F6_coupon96_ix']}")

    # ---- the pairwise separation read (24314 vs 24315 = the verdict) ---
    a, b, c = feats["24314"], feats["24315"], feats["24316"]
    ua = np.asarray(a["F2_unigram_counts"], dtype=np.float64)
    ub = np.asarray(b["F2_unigram_counts"], dtype=np.float64)
    uc = np.asarray(c["F2_unigram_counts"], dtype=np.float64)
    tv_ab = float(0.5 * np.abs(ua / ua.sum() - ub / ub.sum()).sum())
    tv_ac = float(0.5 * np.abs(ua / ua.sum() - uc / uc.sum()).sum())
    tv_bc = float(0.5 * np.abs(ub / ub.sum() - uc / uc.sum()).sum())

    def between(v14: float, v15: float, v16: float) -> str:
        lo, hi = min(v14, v15), max(v14, v15)
        if lo < v16 < hi:
            return "BETWEEN"
        return ("24314-side" if abs(v16 - v14) < abs(v16 - v15)
                else "24315-side")

    table = {}

    def add_row(fid: str, name: str, key: str, thr, note: str):
        v14, v15, v16 = a[key], b[key], c[key]
        diff = abs(v14 - v15)
        sep = diff >= thr
        table[fid] = {
            "feature": name, "key": key,
            "v_24314": v14, "v_24315": v15, "v_24316": v16,
            "abs_diff_14_15": diff, "threshold": thr,
            "separates": bool(sep),
            "v_24316_position": between(v14, v15, v16),
            "note": note,
        }

    add_row("F1", "name-window win-rate chi2 (dof 59)",
            "F1_chi2_name_winrate", ANAT_T["F1_chi2"],
            "the 60-bin ix histogram's dispersion vs uniform")
