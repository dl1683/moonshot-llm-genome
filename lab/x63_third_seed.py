    net.eval()
    row: dict = {"tag": tag}
    percell = {}
    alive, means = {}, {}
    for bn, bk in BATTERIES:
        pv = battery_percell(net, p0[bk], name_id)
        percell[bn] = [float(v) for v in pv]
        alive[bn] = float((pv >= READ_BAR).float().mean())
        means[bn] = float(pv.mean())
        ref = G1.battery_cell(net, p0[bk], name_id)["mean_pz"]
