    make_report(p2, p3)

    metrics["status"] = ("ADJUDICATED (smoke)" if SMOKE
                         else "ADJUDICATED")
    metrics["git_head_final"] = git_head()
    metrics["date_finished"] = utcnow()
    metrics["birth_commit"] = metrics.get("birth_commit") or BIRTH_COMMIT
    save_json(RD / "metrics.json", metrics)
    log("P4 complete — metrics.json + REPORT.md + PNG written")
    return {"composite": composite, "P_x63a": p_x63a}


