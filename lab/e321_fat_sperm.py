def apply_flat64(net, flat64: np.ndarray, offsets, shapes) -> None:
    """theta <- flat64 (fp64 arithmetic) cast fp32 into the params —
    e311's applied-state convention (itself e314's)."""
    f32 = flat64.astype(np.float32)
    with torch.no_grad():
        for p, (a, b), shp in zip(net.parameters(), offsets, shapes):
            p.copy_(torch.from_numpy(f32[a:b]).reshape(shp))


def inroom_relresid(room, v64: np.ndarray) -> float:
    """||P v - v|| / ||v|| — the exact in-room residual (the SEED's gate)."""
    vn = float(np.linalg.norm(v64))
    if vn == 0.0:
        return 0.0
    pv = room.project(v64)
    return float(np.linalg.norm(pv - v64) / vn)


def inroom_frac(room, v64: np.ndarray) -> float:
    """||P v|| / ||v|| — the in-room FRACTION (the TRIGGER's zero-bearer
    gate: exactly out-of-room => ~0; e311's corrected convention)."""
    vn = float(np.linalg.norm(v64))
    if vn == 0.0:
        return 0.0
    return float(np.linalg.norm(room.project(v64)) / vn)


def perctx_p(net, ids: torch.Tensor, zid: int, bs: int = 30) -> list[float]:
    """The FULL per-context distribution: p(zid) at the last position of
    each of the battery's windows (the FAT-SEED-READS bar's quantity)."""
    net.eval()
    out: list[float] = []
    with torch.no_grad():
        for i in range(0, ids.shape[0], bs):
            lg, _ = net(ids[i:i + bs])
            pr = F.softmax(lg[:, -1], -1)
            out += [float(x) for x in pr[:, zid]]
    return out


