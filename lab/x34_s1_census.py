def centroid(pts):
    return (float(np.mean([r["log10_s1"] for r in pts])),
            float(np.mean([r["log10_ratio"] for r in pts])))


def dist(pt, c):
    return math.hypot(pt["log10_s1"] - c[0], pt["log10_ratio"] - c[1])


def radius(pts, c):
    return max(dist(p, c) for p in pts)


