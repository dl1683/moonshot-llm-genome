def md5_of(path: Path) -> str:
    h = hashlib.md5()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def jload(rel: str) -> dict:
    with open(ROOT / rel, encoding="utf-8") as f:
        return json.load(f)


def get(d, *path, default=None):
    """Path get with explicit failure (no silent defaults on value paths)."""
    cur = d
    for p in path:
        if not isinstance(cur, dict) or p not in cur:
            if default is not None:
                return default
            raise KeyError("/".join(map(str, path)))
        cur = cur[p]
    return cur


def ckpt_traj(rel: str) -> list[dict]:
    st = torch.load(ROOT / rel, map_location="cpu", weights_only=False)
    tr = st.get("traj")
    if not tr:
        raise ValueError(f"{rel}: no traj in checkpoint")
    return tr


