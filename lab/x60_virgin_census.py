    log(f"WRITE CONTROL: {g_nb['standing']} (per-subject tables in "
        "metrics.write_control)")

    # ---- THE LEDGER -------------------------------------------------------
    base = p0["base_means"]
    base_host = {"a": base["Q"], "b": base["N"]}
    base_guest = {"a": base["N"], "b": base["Q"]}
    ledger = {}
    for host in ("a", "b"):
        htab = {}
        for k in (0, 7, 12):
            tag = f"{host}_k{k}"
            row_k = {"provenance": f"mine ({tag}; flip scheme "
                     f"{'inherited e346 k7' if k == 7 else ('inherited x55 k12' if k == 12 else 'all-guest')})",
                     "committed": False,
                     "host": {}, "guest": {}, "s1_host": None,
                     "s1_guest": None}
            for s in FATE_STEPS:
                r = arms[tag]["rows"].get(f"{tag}_s{s}")
