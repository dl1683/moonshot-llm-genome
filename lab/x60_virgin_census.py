    metrics["gates"]["G_INSTALLFLOOR"] = g_fl
    log(f"G_INSTALLFLOOR PASS: A {ra:.4f} / B {rb:.4f} >= "
        f"{INSTALL_FLOOR} (the lottery's survive mode)")
    write_partial("P1 complete (the formations certified + floored)")
    return {"cert": cert, "inst_a": inst_a, "inst_b": inst_b}


