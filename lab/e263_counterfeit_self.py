def run_install(tag: str, net0, fact_x, fact_y, corp, syn_row, u1g, u2g,
                ladder: set, resume_ck: Path, n_steps: int,
                stop_band=None) -> dict:
    """One install arm. The e043-Dmix form at the archive's scale: per
    step, 4 identical fact windows (CE masked to the answer position) +
    4 corpus windows x 128 (full CE), union-normalized; AdamW (0.9,0.95)
    wd 0.1 const lr 5e-5; clip 1.0 VERBATIM; then THE HOOK (the arm's
    only intervention) before opt.step(). Resumable per burst; the
    ladder probe (p_syn on the CPU twin) runs mid-burst; stop_band (the
    FREE arm's calibration): stop at the first ladder point inside."""
    dev = torch.device("cuda")
    _arm_device_setup()
    state = {"step": 0, "ledger": {}, "ladder": {}}
    if resume_ck.exists():
        state = torch.load(resume_ck, map_location=CPU, weights_only=False)
        log(f"  [INST-{tag}] RESUMED from {resume_ck.name} at step "
            f"{state['step']}/{n_steps}")
        if stop_band is not None and any(
                stop_band[0] <= r["p"] <= stop_band[1]
                for s, r in state["ladder"].items()
                if int(s) < int(state["step"])):
            raise RuntimeError(
                f"INST-{tag}: resume overshot an in-band ladder point "
                f"(a crash between the probe and the save); delete "
                f"{resume_ck.name} and restart the arm")
    if int(state.get("step", 0)) >= n_steps:
        log(f"  [INST-{tag}] resume ckpt already COMPLETE at "
            f"s{state['step']}")
        return {"sd": state["model"], "ledger": state["ledger"],
                "ladder": state["ladder"], "steps_ran": n_steps,
                "resumed_final": True}
    net = opt = evl = gen = None
    params = None
    step = int(state["step"])
    burst_id = step + 1
    t_burst = None
    n_burst = 0
    stopped_early = False
    while step < n_steps:
        if t_burst is None:
            wait_gpu_free(f"INST{tag}-burst{burst_id}")
            t_burst = time.time()
            n_burst = 0
            log(f"[INST-{tag}] burst {burst_id} opens at s{step + 1}")
        if net is None:
            net = copy.deepcopy(net0).to(dev)
            net.train()
            opt = torch.optim.AdamW(net.parameters(), lr=INST_LR,
                                    betas=(0.9, 0.95), weight_decay=0.1)
            gen = torch.Generator().manual_seed(INST_CORP_SEED)
            if resume_ck.exists():
                net.load_state_dict(state["model"])
                net.to(dev)
                net.train()
                opt.load_state_dict(state["opt"])
                e2.opt_state_dev_fix(opt, dev)
                gen.set_state(state["gen_state"])
                step = int(state["step"])
            evl = copy.deepcopy(net0).to(CPU)
            params = list(net.parameters())
        step += 1
        n_burst += 1
        # ---- the batch: 4 fact windows (masked CE) + 4 corpus windows
        offs = corp.offs[step - 1]
        cx = torch.stack([corp.ids[o: o + INST_CTX] for o in offs]).to(dev)
        cy = torch.stack([corp.ids[o + 1: o + 1 + INST_CTX]
                          for o in offs]).to(dev)
        fx, fy = fact_x.to(dev), fact_y.to(dev)
        lg1 = net(input_ids=fx).logits
        nll1 = F.cross_entropy(lg1.reshape(-1, lg1.shape[-1]),
                               fy.reshape(-1), reduction="none"
                               ).view(fx.shape[0], fx.shape[1])
        fm = torch.zeros_like(nll1, dtype=torch.bool)
        fm[:, -1] = True                      # the answer position only
        lg2 = net(input_ids=cx).logits
        nll2 = F.cross_entropy(lg2.reshape(-1, lg2.shape[-1]),
                               cy.reshape(-1), reduction="none"
                               ).view(cx.shape[0], cx.shape[1])
        loss = (nll1[fm].sum() + nll2.sum()) / (fm.sum() + nll2.numel())
        opt.zero_grad(set_to_none=True)
        loss.backward()
        # ---- pre-clip norm (the ordering disclosure's co-record)
        gn_raw = 0.0
        with torch.no_grad():
            for p in params:
                g = p.grad.detach().reshape(-1)
                gn_raw += float(_dot64(g, g).item())
        gn_raw = math.sqrt(gn_raw)
        torch.nn.utils.clip_grad_norm_(net.parameters(), 1.0)
        # ---- THE HOOK (the cell's only intervention; e237's order)
        with torch.no_grad():
            d1 = torch.zeros((), dtype=torch.float64, device=dev)
            d2 = torch.zeros((), dtype=torch.float64, device=dev)
            gn2 = torch.zeros((), dtype=torch.float64, device=dev)
            for p, s1, s2 in zip(params, u1g, u2g):
                g = p.grad.detach().reshape(-1)
                d1 += _dot64(g, s1)
                d2 += _dot64(g, s2)
                gn2 += _dot64(g, g)
            c1 = float(d1.item())
            c2 = float(d2.item())
            gn = math.sqrt(float(gn2.item()))
        ru_pre = math.sqrt(c1 * c1 + c2 * c2) / gn if gn > 0 else 0.0
        gp_norm = gn
        gn_ap = gn
        ru_ap = ru_pre
        scale = 1.0
        fallback_u1 = False
        if tag != "FREE":
            with torch.no_grad():
                # pass 1: remove the RU component (both arms)
                for p, s1, s2 in zip(params, u1g, u2g):
                    p.grad.add_(((-c1) * s1 + (-c2) * s2).reshape(p.shape))
                gp2 = torch.zeros((), dtype=torch.float64, device=dev)
                for p in params:
                    g = p.grad.detach().reshape(-1)
                    gp2 += _dot64(g, g)
                gp_norm = math.sqrt(float(gp2.item()))
                if gp_norm <= 0:
                    raise RuntimeError(f"INST-{tag}: zero perpendicular "
                                       f"gradient at s{step}")
                if tag == "ORTHO":
                    scale = gn / gp_norm
                    for p in params:
                        p.grad.mul_(scale)
                else:                          # COUNTERFEIT
                    cnorm = math.sqrt(c1 * c1 + c2 * c2)
                    fallback_u1 = cnorm < 1e-8 * gn
                    scale = math.sqrt(1.0 - RHO * RHO) * gn / gp_norm
                    rho_g = RHO * gn
                    if fallback_u1:
                        w1c, w2c = rho_g, 0.0
                    else:
                        w1c = rho_g * c1 / cnorm
                        w2c = rho_g * c2 / cnorm
                    for p, s1, s2 in zip(params, u1g, u2g):
                        p.grad.mul_(scale).add_(
                            (w1c * s1 + w2c * s2).reshape(p.shape))
                # the dose + share verification (measured, never nominal)
                ga = torch.zeros((), dtype=torch.float64, device=dev)
                a1 = torch.zeros((), dtype=torch.float64, device=dev)
                a2 = torch.zeros((), dtype=torch.float64, device=dev)
                for p, s1, s2 in zip(params, u1g, u2g):
                    g = p.grad.detach().reshape(-1)
                    ga += _dot64(g, g)
                    a1 += _dot64(g, s1)
                    a2 += _dot64(g, s2)
                gn_ap = math.sqrt(float(ga.item()))
                ru_ap = math.sqrt(float(a1.item()) ** 2
                                  + float(a2.item()) ** 2) / gn_ap
        opt.step()          # both moments + the update see the hook's g'
        if step % 10 == 0 or step == 1 or step == n_steps or SMOKE:
            state["ledger"][step] = {
                "ce": float(loss.item()), "gnorm_preclip": gn_raw,
                "gnorm": gn, "c1": c1, "c2": c2,
                "ru_share_pre": ru_pre, "gpnorm": gn_ap,
                "ru_share_applied": ru_ap, "scale_perp": scale,
                "fallback_u1": fallback_u1,
                "dose_rel_dev": abs(gn_ap - gn) / gn if gn > 0 else 0.0,
                "clip_bound": bool(gn_raw > 1.0)}
            r = state["ledger"][step]
            log(f"  [INST-{tag}] s{step:4d}/{n_steps} CE "
                f"{r['ce']:.4f} |g| {gn:.4f} (preclip {gn_raw:.3f}"
                f"{' CLIP' if r['clip_bound'] else ''}) RUpre "
                f"{ru_pre*100:.3f}% RUap {ru_ap*100:.3f}% |g'| "
                f"{gn_ap:.4f} (dev {r['dose_rel_dev']:.1e})")
        # ---- the ladder probe (mid-burst, CPU twin, the synthetic only)
        if step in ladder:
            sd = {k: v.detach().to("cpu", torch.float32).clone()
                  for k, v in net.state_dict().items()}
            evl.load_state_dict(sd)
            row = probe_rows(evl, [syn_row])[0]
            state["ladder"][step] = row
            log(f"  [INST-{tag}] LADDER s{step}: p_syn {row['p']:.4f} "
                f"top1 {row['top1']!r}")
            if stop_band is not None and stop_band[0] <= row["p"] \
                    <= stop_band[1]:
                log(f"  [INST-{tag}] STOP-ON-LAND at s{step} "
                    f"(p {row['p']:.4f} in the band) — N frozen")
                stopped_early = True
        # ---- burst bookkeeping / thermal guard (per-step polls)
        temp_ok = burst_temp_check(f"INST{tag}-b{burst_id}")
        burst_over = (n_burst >= BURST_MAX_STEPS
                      or time.time() - t_burst >= BURST_MAX_S
                      or step >= n_steps or stopped_early or not temp_ok)
        if not burst_over:
            continue
        t_end = time.time()
        log(f"  [INST-{tag}] burst {burst_id} done: {n_burst} steps in "
            f"{t_end - t_burst:.1f}s, now at s{step}")
        sd = {k: v.detach().to("cpu", torch.float32).clone()
              for k, v in net.state_dict().items()}
        torch.save({"model": sd,
                    "opt": e2._opt_state_to_cpu(opt.state_dict()),
                    "gen_state": gen.get_state(), "step": step,
                    "ledger": state["ledger"], "ladder": state["ladder"],
                    "meta": {"experiment": NAME, "arm": tag,
                             "step": step}},
                   resume_ck)
        if stopped_early:
            break
        if step >= n_steps:
            break
        burst_cooldown(tag, t_end)
        burst_id = step + 1
        t_burst = None
    net.eval()
    sd = {k: v.detach().to("cpu", torch.float32).clone()
          for k, v in net.state_dict().items()}
    return {"sd": sd, "ledger": state["ledger"], "ladder": state["ladder"],
            "steps_ran": step, "stopped_early": stopped_early}


def run_wash(tag: str, root_mod, train_ids, offs, light_rows, full_rows,
             bank_xy, resume_ck: Path) -> dict:
    """The w1 wash VERBATIM (e237's run_arm minus the hook): AdamW
    (0.9,0.95) wd 0.1 const lr 5e-5, clip 1.0, batch 8 x ctx 512,
    full-token CE, the certified seed-18202 window draws, 80 steps from
    the arm's OWN root; GPU fp32 in <=175 s / <=40-step bursts; the
    light battery probed on the CPU twin at every ckpt; the full
    battery + bank ppl at +80; resumable."""
    dev = torch.device("cuda")
    _arm_device_setup()
    n_steps = WASH_STEPS
    ckpt_set = set(WASH_CK)
    state = {"step": 0, "reads": {}, "ledger": {}}
    if resume_ck.exists():
        state = torch.load(resume_ck, map_location=CPU, weights_only=False)
        log(f"  [WASH-{tag}] RESUMED from {resume_ck.name} at step "
            f"{state['step']}/{n_steps}")
    if int(state.get("step", 0)) >= n_steps:
        return {"sd": state["model"], "reads": state["reads"],
                "ledger": state["ledger"], "steps_ran": n_steps,
                "resumed_final": True}
    net = opt = evl = None
    step = int(state["step"])
    burst_id = step + 1
    t_burst = None
    n_burst = 0
    while step < n_steps:
        if t_burst is None:
            wait_gpu_free(f"WASH{tag}-burst{burst_id}")
            t_burst = time.time()
            n_burst = 0
            log(f"[WASH-{tag}] burst {burst_id} opens at s{step + 1}")
        if net is None:
            net = copy.deepcopy(root_mod).to(dev)
            net.train()
            opt = torch.optim.AdamW(net.parameters(), lr=e1.LR,
                                    betas=(0.9, 0.95), weight_decay=0.1)
            if resume_ck.exists() and step > 0:
                net.load_state_dict(state["model"])
                net.to(dev)
                net.train()
                opt.load_state_dict(state["opt"])
                e2.opt_state_dev_fix(opt, dev)
            evl = copy.deepcopy(root_mod).to(CPU)
        step += 1
        n_burst += 1
        off = offs[step - 1]
        x = torch.stack([train_ids[o: o + e1.SEQ] for o in off]).to(dev)
        y = torch.stack([train_ids[o + 1: o + 1 + e1.SEQ]
                         for o in off]).to(dev)
        logits = net(input_ids=x).logits
        loss = F.cross_entropy(logits.reshape(-1, logits.shape[-1]),
                               y.reshape(-1))
        opt.zero_grad(set_to_none=True)
        loss.backward()
        torch.nn.utils.clip_grad_norm_(net.parameters(), 1.0)
        opt.step()
        state["ledger"][step] = {"ce": float(loss.item())}
        if step % 10 == 0 or step == 1 or SMOKE:
            log(f"  [WASH-{tag}] s{step:3d}/{n_steps} CE "
                f"{float(loss.item()):.4f}")
        temp_ok = burst_temp_check(f"WASH{tag}-b{burst_id}")
        hit_ckpt = step in ckpt_set
        burst_over = (n_burst >= BURST_MAX_STEPS
                      or time.time() - t_burst >= BURST_MAX_S
                      or hit_ckpt or step >= n_steps or not temp_ok)
        if not burst_over:
            continue
        t_end = time.time()
        log(f"  [WASH-{tag}] burst {burst_id} done: {n_burst} steps in "
            f"{t_end - t_burst:.1f}s, now at s{step}")
        sd = {k: v.detach().to("cpu", torch.float32).clone()
              for k, v in net.state_dict().items()}
        torch.save({"model": sd,
                    "opt": e2._opt_state_to_cpu(opt.state_dict()),
                    "step": step, "reads": state["reads"],
                    "ledger": state["ledger"],
                    "meta": {"experiment": NAME, "arm": tag,
                             "step": step}},
                   resume_ck)
        if hit_ckpt:
            torch.save({"model": sd,
                        "meta": {"experiment": NAME, "arm": tag,
                                 "step": step}},
                       CK_DIR / f"{NAME}_{tag}_w{step}.pt")
            evl.load_state_dict(sd)
            state["reads"][step] = {
                "light": probe_rows(evl, light_rows),
                "full": (probe_rows(evl, full_rows)
                         if step == WASH_STEPS else None),
                "ppl": (e1.ppl_eval(evl, *bank_xy)
                        if step == WASH_STEPS else None)}
            lr_ = state["reads"][step]["light"]
            syn = next(r for r in lr_ if r["fact"] == SYN_FACT)
            log(f"  [WASH-{tag}] READ s{step}: p_syn {syn['p']:.4f} "
                f"top1 {syn['top1']!r} | " + " ".join(
                    f"{r['fact'].split('->')[-1]}:{r['p']:.2f}"
                    for r in lr_ if r["fact"] != SYN_FACT))
        if step >= n_steps:
            break
        burst_cooldown(tag, t_end)
        burst_id = step + 1
        t_burst = None
    net.eval()
    sd = {k: v.detach().to("cpu", torch.float32).clone()
          for k, v in net.state_dict().items()}
    return {"sd": sd, "reads": state["reads"], "ledger": state["ledger"],
            "steps_ran": step}


