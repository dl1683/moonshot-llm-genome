# P6 — THE FLIP ANALYSIS (classification + brackets)
# ======================================================================
def classify_cell(pre: list[float], post: list[float],
                  band_cols: list[list[float]]) -> dict:
    """x44's frozen per-context classifier VERBATIM (both forms + the
    bracket), with the band := max over the five never-written columns.

    PRIMARY (band) form — x38's convention per context, WITH x38's
    living-read currency rule: PRE <= 0.05 -> ratio currency (an empty
    slot cannot collapse); PRE > 0.05 -> move currency (|dZ| > 5x the
    per-context never-written band).
    """
    n = len(pre)
    cls_band, cls_ratio = [], []
    band_floor_fired = 0
    sat_up = 0
    noise_lifts = 0
    for i in range(n):
        dT = abs(post[i] - pre[i])
        band = max(abs(c[i]) for c in band_cols)
        if band < BAND_FLOOR:
            band = BAND_FLOOR
            band_floor_fired += 1
        if pre[i] <= LIVING_BAR:
            # x38's ratio currency: a dead/empty context can only LIFT
            cls_band.append("LIFT" if post[i] > pre[i] else "AMBIG")
            if post[i] > pre[i] and pre[i] < NOISE_ZONE:
                noise_lifts += 1
        elif dT > BAND_X * band:
            cls_band.append("COLLAPSE")
            if post[i] > pre[i]:
                sat_up += 1
        elif post[i] > pre[i]:
            cls_band.append("LIFT")
        else:
            cls_band.append("AMBIG")
        if post[i] <= COLLAPSE_RATIO * pre[i]:
            cls_ratio.append("COLLAPSE")
        elif post[i] > pre[i]:
            cls_ratio.append("LIFT")
        else:
            cls_ratio.append("AMBIG")

    def bracket(cls):
        lift_pre = [pre[i] for i in range(n) if cls[i] == "LIFT"]
        coll_pre = [pre[i] for i in range(n) if cls[i] == "COLLAPSE"]
        l_max = max(lift_pre) if lift_pre else None
        c_min = min(coll_pre) if coll_pre else None
        two_sided = l_max is not None and c_min is not None
        consistent = bool(two_sided and l_max < c_min)
        violations = 0
        if two_sided:
            violations = sum(1 for i in range(n)
                             if (cls[i] == "LIFT" and pre[i] >= c_min)
                             or (cls[i] == "COLLAPSE"
                                 and pre[i] <= l_max))
        r_hat = (math.sqrt(l_max * c_min)
                 if consistent else None)
        return {"n_lift": len(lift_pre), "n_collapse": len(coll_pre),
                "n_ambig": n - len(lift_pre) - len(coll_pre),
                "L_max": l_max, "C_min": c_min,
                "two_sided": bool(two_sided),
                "consistent": consistent, "violations": violations,
                "R_hat": r_hat}

    return {"cls_band": cls_band, "cls_ratio": cls_ratio,
            "bracket_band": bracket(cls_band),
            "bracket_ratio": bracket(cls_ratio),
            "band_floor_fired": band_floor_fired, "sat_up": sat_up,
            "noise_lifts": noise_lifts}


def phase_flip(st: dict, rd: dict) -> dict:
    log("P6 — THE FLIP ANALYSIS (classification + brackets)")
    cells = {}
    for key in sorted(st["ladder"]):
        cells[key] = {}
        for bn in GEOS:
            pre = rd["reads"][key]["pre"][bn]["Z"]
            post = rd["reads"][key]["post"][bn]["Z"]
            band_cols = []
            for col in [nm[0] for nm in BAND_NAMES]:
                band_cols.append(
                    [postc - prec for postc, prec in
                     zip(rd["reads"][key]["post"][bn][col],
                         rd["reads"][key]["pre"][bn][col])])
            cells[key][bn] = classify_cell(pre, post, band_cols)
            cells[key][bn]["pre"] = pre           # the cell's data table
            cells[key][bn]["post"] = post
            cells[key][bn]["band"] = [
                max((abs(c[i]) for c in band_cols),
                    default=BAND_FLOOR) for i in range(len(pre))]
            cells[key][bn]["dTrider"] = [
                postc - prec for postc, prec in
                zip(rd["reads"][key]["post"][bn]["T"],
                    rd["reads"][key]["pre"][bn]["T"])]
            bb = cells[key][bn]["bracket_band"]
            log(f"  [{key}:{bn}] band {bb['n_lift']}L/"
                f"{bb['n_collapse']}C/{bb['n_ambig']}A; bracket "
                + (f"({bb['L_max']:.4g}, {bb['C_min']:.4g}] "
                   f"R_hat {bb['R_hat']:.4g}" if bb["consistent"]
                   else ("one-sided" if bb["two_sided"] else "no bracket"))
                + f" (viol {bb['violations']})")

    # G_FLIPCLASS: the machinery's internal consistency
    ok = True
    for key in cells:
        for bn in cells[key]:
            bb = cells[key][bn]["bracket_band"]
            br = cells[key][bn]["bracket_ratio"]
            for b in (bb, br):
                if b["n_lift"] + b["n_collapse"] + b["n_ambig"] != 60:
                    ok = False
                if b["two_sided"] and not b["consistent"]:
                    if b["violations"] == 0:
                        ok = False      # inconsistent without violations
                if b["consistent"] and b["violations"] != 0:
                    ok = False
    g_fc = {"claim": "counts sum to 60 per cell; brackets well-formed "
                     "(consistent iff zero violations)",
            "pass": bool(ok)}
