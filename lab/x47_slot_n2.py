def main() -> None:
    log(f"X47 — THE SLOT-PROPERTY n=2 (smoke={SMOKE}) -> {RD}")
    metrics["birth_commit"] = git_head()
    write_partial("startup (bars + P-x47a registered, committed at birth)")
    set_seed(GLOBAL_SEED)          # global init only; no fresh draws exist

    gr = phase_gates()                    # md5 + quotes + references
    hp = phase_harness()                  # phase_P0 + gp12 + bank identity
    car = phase_carrier(hp, gr)           # the certified displacement
    st = phase_states(hp, car, gr)        # the ladder + the re-run
    rd = phase_reads(hp, car, st)         # the per-context reads
    flip = phase_flip(st, rd)             # the classification + brackets
    adj = adjudicate(flip, gr, st, rd)    # the frozen composite

    metrics["reads_summary"] = {
        key: {bn: {"pre_mean": rd["reads"][key]["pre"][bn]["Z_mean"],
                   "pre_alive": rd["reads"][key]["pre"][bn]
                   ["Z_alive_frac"],
                   "post_mean": rd["reads"][key]["post"][bn]["Z_mean"],
                   "post_alive": rd["reads"][key]["post"][bn]
                   ["Z_alive_frac"]}
              for bn in GEOS} for key in sorted(st["ladder"])}
    metrics["ce_r"] = {key: {"bare": rd["reads"][key]["ce_r_bare"],
                             "comp": rd["reads"][key]["ce_r_comp"]}
                       for key in sorted(st["ladder"])}
    metrics["flip_cells"] = flip["cells"]
    metrics["adjudication"] = adj
    metrics["rung_level"] = adj["rung_level"]

    if SMOKE:
        metrics["status"] = ("SMOKED — full gate path + all reads + the "
                             "classification exercised; NOTHING adjudicated")
        write_partial("SMOKE COMPLETE — nothing adjudicated")
        log("SMOKE COMPLETE (nothing adjudicated)")
        raise SystemExit(0)

    make_png(flip, adj, st, rd, gr)
    gates_n = (sum(1 for g in metrics["gates"].values() if g.get("pass")),
               len(metrics["gates"]))
    write_report(flip, adj, st, rd, gr, gates_n)
    metrics["verdict"] = {"word": adj["verdict"], "clause": adj["clause"],
                          "P_x47a_hit": adj["P_x47a"]["hit"]}
    metrics["git_head_final"] = git_head()
    metrics["date_completed"] = common.now_iso()
    metrics["outputs"] = [str((RD / "x47_slot_n2.png").relative_to(REPO)),
                          str((RD / "REPORT.md").relative_to(REPO)),
                          str((RD / "metrics.json").relative_to(REPO))]
    metrics["status"] = "COMPLETE"
    save_json(RD / "metrics.json", metrics)
    log(f"X47 run lands — verdict {adj['verdict']} "
        f"(P-x47a {'HIT' if adj['P_x47a']['hit'] else 'MISSED'}; "
        f"ratio " + (f"{adj['ratio']:.3f}" if adj['ratio'] is not None
                     else "n/a") + "); gates "
        f"{gates_n[0]}/{gates_n[1]} PASS")


if __name__ == "__main__":
    main()
