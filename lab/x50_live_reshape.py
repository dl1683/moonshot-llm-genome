    sub_sd = load_model_sd(CKPT_DIR / "g1c_install_resume.pt")
    leg_start64 = flat_params_cpu(G1.evl_load(sub_sd)).double().numpy()
    row = instrument(p0, sub_sd, "live_s0", name_id, e001_flat64,
                     leg_start64=leg_start64)
    row.update({"step": 0, "pos": 400, "provenance": "committed-anchor",
                "net0_class": "BASE-formed (the install end)"})
    live["rows"]["live_s0"] = row
    log(f"  [live_s0 ANCHOR] read {row['read']:.6f} | r(g-12|g0) "
        f"{row['corrs']['g-12|g0']} r(g0|g+12) {row['corrs']['g0|g+12']} "
        f"| |W| {row['write_norm']:.2f} inroom {row['in_room']:.4f}")

    # ---- the replay (x45's cons-branch arithmetic VERBATIM) -----------
    resume_ck = RD / "live_cons_resume.pt"
    state = {"step": 0, "traj": [], "draws": []}
    if resume_ck.exists():
        state = torch.load(resume_ck, map_location="cpu", weights_only=False)
        live["rows"].update({k: v for k, v in
                             state.get("instrument_rows", {}).items()
                             if k != "live_s0"})
        log(f"  [live] RESUMED at step {state['step']}/{CONS_STEPS} "
            f"({len(live['rows'])} rows restored)")

    net = G1.evl_load(sub_sd).to(dev)
    net.train()
    opt = torch.optim.AdamW(net.parameters(), lr=G1.FT_LR,
                            betas=(0.9, 0.95), weight_decay=0.1)
    gen = torch.Generator().manual_seed(CONS_SEED)
    if resume_ck.exists():
        net.load_state_dict(state["model"])
        net.to(dev)
        net.train()
        opt.load_state_dict(state["opt"])
        gen.set_state(state["gen_state"])

    pool_x, pool_mask = p0["pool_z_x"], p0["pool_z_mask"]
    n_pool = pool_x.shape[0]
    cons_anchor = p0["cons_anchor"]
    train_ids = p0["train_ids"]

    def rung_row(step_: int) -> None:
        sd_cpu = {k: v.detach().cpu().clone()
                  for k, v in net.state_dict().items()}
        sub_tag = f"live_s{step_}"
        row = instrument(p0, sd_cpu, sub_tag, name_id, e001_flat64,
                         leg_start64=leg_start64)
        row.update({"step": step_, "pos": 400 + step_,
                    "provenance": "replay",
                    "net0_class": "ROOT-forming",
                    "grain": ("fine" if step_ in FINE_RUNGS
                              and step_ not in DENSE_RUNGS else "dense"),
                    "committed_rung": bool(step_ in COMMITTED_RUNGS)})
        live["rows"][sub_tag] = row
        state["traj"].append({"step": step_, "read": row["read"]})
        log(f"  [live] s{step_:4d} READ {row['read']:.6f} | r1 "
            f"{row['corrs']['g-12|g0']} r2 {row['corrs']['g0|g+12']} "
            f"| alive g0 {row['alive']['g0']:.3f} | |W| "
            f"{row['write_norm']:.2f} inroom {row['in_room']:.4f} "
            f"| CE_R {row['ce_r']:.4f}")

    def save_resume() -> None:
        torch.save({"model": {k: v.detach().cpu().clone()
                              for k, v in net.state_dict().items()},
                    "opt": opt.state_dict(), "gen_state": gen.get_state(),
                    "step": state["step"], "traj": state["traj"],
                    "draws": state["draws"],
                    "instrument_rows": live["rows"]}, resume_ck)

    step = state["step"]
    t_slice = time.time()
    n_slices = 0
    while step < CONS_STEPS:
        step += 1
        ix = torch.randint(n_pool, (16,), generator=gen)
        aj = torch.randint(cons_anchor.shape[0], (8,), generator=gen)
        rj = torch.randint(len(train_ids) - G1.BLOCK - 1, (8,),
                           generator=gen)
        state["draws"].append({"step": step, "ix": ix.tolist(),
                               "aj": aj.tolist(), "rj": rj.tolist()})
        nw = pool_x[ix].to(dev)
        anc = torch.cat([cons_anchor[aj],
                         torch.stack([train_ids[s: s + G1.BLOCK]
                                      for s in rj])], 0).to(dev)
        x = torch.cat([nw[:, :-1], anc[:, :-1]], 0)
        y = torch.cat([nw[:, 1:], anc[:, 1:]], 0)
        m = torch.zeros(32, x.shape[1], dtype=torch.bool, device=dev)
        m[:16] = pool_mask[ix].to(dev)
        logits, _ = net(x)
        nll = F.cross_entropy(logits.reshape(-1, logits.shape[-1]),
                              y.reshape(-1), reduction="none"
                              ).view(x.shape[0], x.shape[1])
        nm = nll[:16][m[:16]]
        cm = nll[16:]
        loss = (nm.sum() + cm.sum()) / (nm.numel() + cm.numel())
        opt.zero_grad(set_to_none=True)
        loss.backward()
        torch.nn.utils.clip_grad_norm_(net.parameters(), 1.0)
        opt.step()
        state["step"] = step
        if step in REPLAY_RUNGS:
            rung_row(step)
        if (time.time() - t_slice) > TRAIN_CAP_CPU:
            save_resume()
            n_slices += 1
            log(f"  [live] slice cap ({TRAIN_CAP_CPU:.0f}s) at s{step} — "
                f"resume saved, continuing (CPU park convention)")
            t_slice = time.time()
    save_resume()
    live["draws"] = state["draws"]
    log(f"  [live] leg finished: {CONS_STEPS} steps, {n_slices} slice "
        f"caps, {len(live['rows'])} instrument rows")

    # ---- the s300 END anchor row (the committed root, read directly) --
    root_sd = load_model_sd(CKPT_DIR / "g1c_root.pt")
    row = instrument(p0, root_sd, "live_s300_end", name_id, e001_flat64,
                     leg_start64=leg_start64)
    row.update({"step": 300, "pos": 700, "provenance": "committed-anchor",
                "net0_class": "ROOT"})
    live["rows"]["live_s300_end"] = row
    log(f"  [live_s300_end ANCHOR] read {row['read']:.6f} | r1 "
        f"{row['corrs']['g-12|g0']} r2 {row['corrs']['g0|g+12']} | |W| "
        f"{row['write_norm']:.2f} inroom {row['in_room']:.4f}")
    del net, opt
    metrics["live"] = {"rows": live["rows"]}
    write_partial("P1 the live replay done")
    return live


