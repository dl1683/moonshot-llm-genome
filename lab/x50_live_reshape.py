def phase_P3(p0: dict, live: dict) -> dict:
    log("P3 — THE EMERGENCE WINDOW + THE SHAPE + THE COMPACTNESS RIDER")

    rows = [live["rows"][f"live_s{s}"] for s in sorted(REPLAY_RUNGS)]
    curve = [{
        "step": r["step"],
        "read": r["read"],
        "r1": r["corrs"]["g-12|g0"], "r2": r["corrs"]["g0|g+12"],
        "r3": r["corrs"]["g-12|g+12"],
        "C": (min(r["corrs"]["g-12|g0"], r["corrs"]["g0|g+12"])
              if r["corrs"]["g-12|g0"] is not None
              and r["corrs"]["g0|g+12"] is not None else None),
        "raw_collapse": bool(r["corrs"]["g-12|g0"] is not None
                             and r["corrs"]["g-12|g0"] <= RAW_BAR),
        "write_norm": r["write_norm"], "in_room": r["in_room"],
        "w_per_read": (r["write_norm"] / r["read"]
                       if r["read"] > 0 else None),
    } for r in rows]

    # ---- the before-state + the after-state (the frozen rule) ---------
    seq = [c for c in curve if c["C"] is not None]
    coherent_runs, cur = [], []
    for c in seq:
        if c["C"] >= COH_BAR:
            cur.append(c)
        else:
            if len(cur) >= MIN_COH_RUNGS:
                coherent_runs.append(cur)
            cur = []
    if len(cur) >= MIN_COH_RUNGS:
        coherent_runs.append(cur)

    before = None
    after = None
    for run in coherent_runs:
        last_coh_step = run[-1]["step"]
        # the first qualifying after-start following this run
        rest = [c for c in seq if c["step"] > last_coh_step]
        for c in rest:
            w0, w1 = c["step"], min(c["step"] + AFTER_SPAN, CONS_STEPS)
            win = [q for q in seq if w0 <= q["step"] <= w1]
            if len(win) >= 2 and all(q["C"] <= DECO_LEVEL for q in win):
                before, after = run, c
                break
        if after is not None:
            break

    emergence = {
        "coh_bar": COH_BAR, "deco_level": DECO_LEVEL,
        "n_dense_rungs": len(seq),
        "coherent_runs": ([[c["step"] for c in run]
                           for run in coherent_runs] or None),
        "before_state": ([c["step"] for c in before] if before else None),
        "after_state_start": (after["step"] if after else None),
    }

    if before is not None and after is not None:
        s_lo = before[-1]["step"]
        s_hi = after["step"]
        width = s_hi - s_lo
        inside = [c for c in seq if s_lo <= c["step"] <= s_hi]
        deltas = [inside[i + 1]["C"] - inside[i]["C"]
                  for i in range(len(inside) - 1)]
        frac_neg = (sum(1 for d in deltas if d < 0) / len(deltas)
                    if deltas else 0.0)
        if width <= STEP_WIDTH:
            shape = "STEP"
        elif width <= RAMP_WIDTH and frac_neg >= RAMP_MONO:
            shape = "RAMP"
        else:
            shape = "OSCILLATION"
        emergence.update({
            "window": [s_lo, s_hi], "width_steps": width,
            "C_inside": [(c["step"], round(c["C"], 4)) for c in inside],
            "frac_negative_deltas": round(frac_neg, 4),
            "shape": shape,
        })
        verdict = "LIVE-DECORRELATION"
        clause = (f"the emergence window is [{s_lo}, {s_hi}] "
                  f"(width {width} steps, shape {shape} at the "
                  f"{min(5, width)}-step grain): a coherent before-state "
                  f"(C >= {COH_BAR} at "
                  + ", ".join(str(c['step']) for c in before)
                  + f") gives way to a decorrelated after-state (C <= "
                  f"{DECO_LEVEL} sustained from s{s_hi}) — the "
                  "decorrelation is WRITTEN mid-phase, inside the "
                  "observed window; warmth becomes a manipulable "
                  "protocol knob; x43's ceiling re-reads as never having "
                  "watched the right phase")
    else:
        verdict = "COHERENT-THROUGHOUT"
        if not coherent_runs:
            sub = "NO-BEFORE (inherited/absent)"
            clause = (f"no >= {MIN_COH_RUNGS}-consecutive-rung coherent "
                      f"state (C >= {COH_BAR}) anywhere in the dense "
                      "curve — the coherent peak the committed grid "
                      "suggested does not survive the dense grain; the "
                      "level difference was INHERITED or the walk never "
                      "holds the coherent regime on this ruler")
        else:
            sub = "NO-AFTER (coherent past the committed grid's resolution)"
            clause = (f"{len(coherent_runs)} coherent run(s) but no "
                      f"qualifying after-state (C <= {DECO_LEVEL} "
                      f"sustained over a {AFTER_SPAN}-step window) — the "
                      "curves stay coherent until the committed grid's "
                      "resolution; the level forms coarser than the grain "
                      "(disclosed: the grain is 5 steps, 2 in [112, 138])")
        emergence["sub_class"] = sub
        emergence["clause"] = clause

    # the s125 tick window at fine grain (co-report; the census line)
    fine = [c for c in curve if 112 <= c["step"] <= 138]
    emergence["s125_fine_window"] = [
        {"step": c["step"], "r1": c["r1"], "r2": c["r2"], "C": c["C"],
         "raw_collapse": c["raw_collapse"]} for c in fine]
    raw_hits = [c["step"] for c in curve if c["raw_collapse"]]
    emergence["raw_collapse_hits"] = raw_hits

    # ---- the compactness rider (P-T332a's live form) ------------------
    rider = {"series": {}}
    cvals = [c["C"] for c in seq]

    def corr_series(key):
        xs, ys = [], []
        for c in seq:
            v = c[key]
            if v is not None:
                xs.append(c["C"])
                ys.append(v)
        if len(xs) < 3:
            return {"n": len(xs), "flat": True, "pearson": None,
                    "spearman": None,
                    "note": "insufficient samples"}
        sx, sy = float(np.std(xs)), float(np.std(ys))
        if sx < FLAT_STD or sy < FLAT_STD:
            return {"n": len(xs), "flat": True, "pearson": None,
                    "spearman": None, "std": float(min(sx, sy)),
                    "note": (f"FLAT (std {min(sx, sy):.2e} < {FLAT_STD}) "
                             "— cannot carry tracking")}
        r_p = float(np.corrcoef(xs, ys)[0, 1])
        rk = lambda v: list(np.argsort(np.argsort(v)))  # noqa: E731
        r_s = float(np.corrcoef(rk(xs), rk(ys))[0, 1])
        return {"n": len(xs), "flat": False, "pearson": r_p,
                "spearman": r_s, "tracks": bool(abs(r_p) >= RIDER_RBAR)}

    for key, label in (("write_norm", "|W|"),
                       ("w_per_read", "|W|/read (|W|-per-read)"),
                       ("in_room", "in_room")):
        rider["series"][label] = corr_series(key)
    nonflat = [k for k, v in rider["series"].items() if not v["flat"]]
    n_track = sum(1 for k in nonflat
                  if rider["series"][k].get("tracks"))
    rider["rule"] = (f"TRACKS iff >= half of the non-FLAT series have "
                     f"|Pearson r| >= {RIDER_RBAR} with C(s)")
    if nonflat:
        rider["verdict"] = ("COMPACTNESS-TRACKS"
                            if 2 * n_track >= len(nonflat)
                            else "COMPACTNESS-INDEPENDENT")
    else:
        rider["verdict"] = "VACUOUS (every series flat)"
    rider["n_track"] = n_track
    rider["n_nonflat"] = len(nonflat)

    # ---- the composite (frozen; TEXTURE on hard-gate failure) ---------
    hard_ok = all(bool(g.get("pass")) for g in metrics["gates"].values())
    if not hard_ok:
        verdict = "TEXTURE"
        clause = ("hard-gate failure: "
                  + ", ".join(k for k, g in metrics["gates"].items()
                              if not g.get("pass"))
                  + " — nothing adjudicated; tables verbatim")
        rider["verdict"] = "VACUOUS (texture)"
    if SMOKE:
        verdict, clause = "SMOKE", "nothing adjudicated (smoke stamp)"
        rider["verdict"] = "SMOKE"

    adj = {
        "bars_verbatim": REGISTERED["bars_verbatim"],
        "parity": REGISTERED["parity_block_verbatim"],
        "grain": {"dense": 5, "fine_window": [112, 138, 2],
                  "start_rungs": [1, 2],
                  "disclosure": "events finer than the grain are "
                                "invisible; the committed 25-step grid is "
                                "a subset of the dense rungs"},
        "emergence": emergence,
        "rider": rider,
        "P-x50a": {"guess": REGISTERED["P-x50a"]["my_guess"],
                   "hit": bool(verdict == "LIVE-DECORRELATION"),
                   "scored": REGISTERED["P-x50a"]["scored"],
                   "rider_guess": "COMPACTNESS-INDEPENDENT",
                   "rider_hit": bool(
                       rider["verdict"] == "COMPACTNESS-INDEPENDENT")},
        "verdict": verdict, "clause": clause,
        "composite_order": ("TEXTURE (hard gates) -> LIVE-DECORRELATION "
                            "(before + after states) -> COHERENT-THROUGHOUT "
                            "(no before: inherited clause; no after: the "
                            "coherent clause)"),
    }
    metrics["adjudication"] = adj
    metrics["live"]["curve"] = curve
    write_partial("P3 the emergence + rider adjudication done")
    log(f"P3: verdict {verdict}; rider {rider['verdict']}; emergence "
        f"window {emergence.get('window')}")
    return adj


