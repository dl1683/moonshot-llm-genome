def seq_restore_phase(tag: str, start_sd: dict, rooms,
                      organism_flat_np: np.ndarray, base_flat_np: np.ndarray,
                      budget_r: float, lr_m_max4: float, facts_x: list,
                      facts_mask: list, baselines: dict, g0_ids_f: dict,
                      gm12_ids_f: dict, r_eval_xy, zid, resume_ck: Path,
                      dev: torch.device) -> dict:
    """THE RESTORE PASS — maintenance ONLY, exactly RESTORE_ROUNDS
    rounds; NO corpus steps, NO anti events. Each round: the four
    sibling controllers (fact order 1->2->4->5) fire back-to-back —
    each ONE name-only CE descent step on its own 12-window pool
    (ix(16) draws from the shared controller generator), clip 1.0,
    UNPROJECTED, through its OWN opt_Fi (fresh at the boundary), gated
    on its OWN battery against its OWN committed baseline, capped at
    B_R's equal share of the remaining restore events. The five-fact
    panel after EVERY round (the resurrection microscope). Thermal: a
    poll after EVERY optimizer event."""
    name_bs = G1.NAME_BS
    N = int(organism_flat_np.size)
    total_events = len(CTL_IDX) * RESTORE_ROUNDS
    state = {"round": 0, "traj": [], "panel_ledger": [], "ctl_ledgers":
             [[] for _ in CTL_IDX],
             "budget_ledger": [],
             "bufsep": {"ctl_checks": 0, "ctl_violations": 0,
                        "optF_steps": [0 for _ in CTL_IDX]},
             "maint_cums": [torch.zeros(N, dtype=torch.float64)
                            for _ in CTL_IDX],
             "S_restore": 0.0, "n_ctl_capped": [0 for _ in CTL_IDX],
             "events_done": 0,
             "f3_first_return_round": None,
             "f3_dead_at_round_start": None,
             "n_resurrections": 0, "n_kills": 0}
    if resume_ck.exists():
        state = torch.load(resume_ck, map_location="cpu", weights_only=False)
        log(f"  [{tag}] RESUMED from {resume_ck.name} at round "
            f"{state['round']}/{RESTORE_ROUNDS}")
    if int(state.get("round", 0)) >= RESTORE_ROUNDS:
        log(f"  [{tag}] resume ckpt already COMPLETE at round "
            f"{state['round']}")
        out = _p2_final(state, RESTORE_ROUNDS)
        out["restore_cums_np"] = [c.double().numpy()
                                  for c in state["maint_cums"]]
        _net = G1.evl_load(start_sd)
        _opts = []
        for ci in range(len(CTL_IDX)):
            _o = torch.optim.SGD(_net.parameters(), lr=lr_m_max4)
            _o.load_state_dict(state["optFs"][ci])
            _opts.append(_o)
        out["bufF_finals_flat"] = [opt_buffer_flat(o, list(_net.parameters()))
                                   for o in _opts]
        del _net, _opts
        return out
    net = mgen = evl = None
    opt_Fs: list = []
    n_chunks, chunk_table = 0, []
    rnd = state["round"]
    t_burst, n_burst = None, 0
    chunk_temps: list[float] = []
    maint_cums = [c.to(dev) for c in state["maint_cums"]]
    S_restore = float(state["S_restore"])
    events_done = int(state["events_done"])

    def _panel_read() -> dict:
        sd_cpu = {k: v.detach().cpu().clone()
                  for k, v in net.state_dict().items()}
        evl.load_state_dict(sd_cpu)
        evl.eval()
        return {fi: G1.battery_cell(evl, ids, zid)["mean_pz"]
                for fi, ids in g0_ids_f.items()}

    while rnd < RESTORE_ROUNDS:
        if t_burst is None:
            t_burst, n_burst = E261._open_burst(
                f"{tag}:restore:chunk{n_chunks + 1}")
        n_chunks += 1
        chunk_temps = []
        if net is None:
            net = G1.evl_load(start_sd).to(dev)
            net.train()
            opt_Fs = [torch.optim.SGD(net.parameters(), lr=lr_m_max4,
                                      momentum=SGD_MOMENTUM,
                                      weight_decay=SGD_WD)
                      for _ in CTL_IDX]
            mgen = torch.Generator().manual_seed(MAINT_GEN_SEED_B)
            if resume_ck.exists():
                net.load_state_dict(state["model"])
                net.to(dev)
                net.train()
                for ci, o in enumerate(opt_Fs):
                    o.load_state_dict(state["optFs"][ci])
                mgen.set_state(state["mgen_state"])
                rnd = state["round"]
                S_restore = float(state["S_restore"])
                events_done = int(state["events_done"])
            evl = G1.evl_load(start_sd)
        devices_row = {"chunk": n_chunks, "device": str(dev),
                       "t_start": round(time.time() - T0, 1)}
        chunk_capped = False
        params_live = list(net.parameters())
        for rnd in range(rnd + 1, RESTORE_ROUNDS + 1):
            for ci, fi in enumerate(CTL_IDX):
                ctl_fact = f"FACT{fi + 1}"
                base_i = baselines[ctl_fact]
                ix_m = torch.randint(facts_x[fi].shape[0], (name_bs,),
                                     generator=mgen)
                nw_m = facts_x[fi][ix_m]
                x_m = nw_m[:, :-1].to(dev)
                y_m = nw_m[:, 1:].to(dev)
                m_m = facts_mask[fi][ix_m].to(dev)
                logits_m, _ = net(x_m)
                nll_m = F.cross_entropy(
                    logits_m.reshape(-1, logits_m.shape[-1]),
                    y_m.reshape(-1), reduction="none"
                ).view(x_m.shape[0], x_m.shape[1])
                nm_m = nll_m[m_m]                    # the 112 name tokens
                loss_m = nm_m.mean()                 # DESCENT (the anchor)
                net.zero_grad(set_to_none=True)
                loss_m.backward()
                torch.nn.utils.clip_grad_norm_(net.parameters(), 1.0)
                gn_m = float(torch.cat(
                    [p.grad.detach().reshape(-1) for p in net.parameters()
                     if p.grad is not None]).norm().item())
                # the deficit gate on fact i's OWN battery
                sd_gate = {k: v.detach().cpu().clone()
                           for k, v in net.state_dict().items()}
                evl.load_state_dict(sd_gate)
                evl.eval()
                read_gate_m = G1.battery_cell(evl, g0_ids_f[ctl_fact],
                                              zid)["mean_pz"]
                deficit_t = min(1.0, max(
                    0.0, base_i - read_gate_m) / base_i)
                lr_target_m = lr_m_max4 * deficit_t
                assert lr_target_m <= lr_m_max4 * (1.0 + 1e-12), \
                    (f"controller law broken: {lr_target_m} > "
                     f"{lr_m_max4}")
                if deficit_t <= 0.0:
                    assert lr_target_m == 0.0
                bm_sq = pending_buffer_sqnorm(opt_Fs[ci], params_live,
                                              SGD_MOMENTUM)
                bm_norm = math.sqrt(max(bm_sq, 0.0))
                rem_ev = max(total_events - events_done, 1)
                remaining_r = max(budget_r - S_restore, 0.0)
                share_m = remaining_r / rem_ev
                cap_m = share_m / max(bm_norm, 1e-12)
                lr_m = min(lr_target_m, cap_m)
                assert lr_m <= lr_m_max4 * (1.0 + 1e-9), \
                    f"applied lr_m {lr_m} exceeds lr_m_max4 {lr_m_max4}"
                capped_m = bool(cap_m < lr_target_m)
                binder_m = "cap" if capped_m else "controller"
                if capped_m:
                    state["n_ctl_capped"][ci] += 1
                for g_ in opt_Fs[ci].param_groups:
                    g_["lr"] = lr_m
                others = [o for j, o in enumerate(opt_Fs) if j != ci]
                sn_others = [snap_buffers(o, params_live) for o in others]
                theta_b = torch.cat([p.detach().reshape(-1)
                                     for p in net.parameters()])
                opt_Fs[ci].step()
                with torch.no_grad():
                    d_m = torch.cat([p.detach().reshape(-1)
                                     for p in net.parameters()]) - theta_b
                    maint_cums[ci] += d_m
                realized_m = float(d_m.norm().item())
                S_restore += realized_m
                events_done += 1
                state["bufsep"]["ctl_checks"] += 1
                state["bufsep"]["optF_steps"][ci] += 1
                bad = False
                for o, sn in zip(others, sn_others):
                    if not buffers_bitwise_equal(
                            sn, snap_buffers(o, params_live)):
                        bad = True
                if bad:
                    state["bufsep"]["ctl_violations"] += 1
                    raise RuntimeError(
                        f"[{tag}] G_BUFSEP ISOLATION VIOLATION at round "
                        f"{rnd}'s {ctl_fact} event: it touched another "
                        "controller's state — HALT")
                state["ctl_ledgers"][ci].append({
                    "round": rnd, "fact": ctl_fact,
                    "name_ce": float(loss_m.item()),
                    "gn_clipped": gn_m,
                    "read_at_gate": read_gate_m, "deficit_t": deficit_t,
                    "lr_m_max4": lr_m_max4, "lr_target": lr_target_m,
                    "cap_m": cap_m, "lr_maint": lr_m, "capped": capped_m,
                    "binder": binder_m, "b_m_norm": bm_norm,
                    "realized_step_norm": realized_m,
                    "S_restore": S_restore,
                    "elapsed_s": round(time.time() - T0, 1)})
                n_burst += 1
                ok_t, temp = E261.burst_temp_check(
                    f"{tag}:ctl:c{n_chunks}.x")
                chunk_temps.append(temp)
            # ---- the round's panel (the resurrection microscope) ------
            panel = _panel_read()
            f3_now = panel[TARGET_FACT]
            prev_row = (state["panel_ledger"][-1]["panel_g0"]
                        if state["panel_ledger"] else None)
            f3_prev = prev_row[TARGET_FACT] if prev_row else None
            if state["f3_first_return_round"] is None \
                    and f3_now >= ERASE_BAR:
                state["f3_first_return_round"] = rnd
            # the kill/resurrection census across the restore
            if f3_prev is not None:
                if f3_prev < ERASE_BAR and f3_now >= ERASE_BAR:
                    state["n_resurrections"] += 1
                elif f3_prev >= ERASE_BAR and f3_now < ERASE_BAR:
                    state["n_kills"] += 1
            state["panel_ledger"].append({
                "round": rnd, "panel_g0": panel,
                "S_restore": S_restore,
                "elapsed_s": round(time.time() - T0, 1)})
            ratios = {fi_: panel[fi_] / baselines[fi_] for fi_ in panel}
            if rnd in RESTORE_MILESTONES or rnd == RESTORE_ROUNDS or SMOKE:
                sd_cpu = {k: v.detach().cpu().clone()
                          for k, v in net.state_dict().items()}
                evl.load_state_dict(sd_cpu)
                evl.eval()
                panel12 = {fi_: G1.battery_cell(evl, ids, zid)["mean_pz"]
                           for fi_, ids in gm12_ids_f.items()}
                ce_r = G1.ce_fixed_cpu(evl, *r_eval_xy)
                theta_t = flat_params_cpu(net).double().numpy() \
                    .astype(np.float64)
                dn = float(np.linalg.norm(theta_t - organism_flat_np))
                cum_all = np.sum([c.double().cpu().numpy()
                                  for c in maint_cums], axis=0)
                state["budget_ledger"].append({
                    "round": rnd, "S_restore": S_restore,
                    "S_restore_usage_frac": S_restore / budget_r,
                    "events_done": events_done})
                state["traj"].append({
                    "round": rnd, "panel_g0": panel,
                    "panel_gm12": panel12,
                    "ratios_vs_baseline": ratios,
                    "ce_r": ce_r, "drift_norm": dn,
                    "restore_cum_norm": float(np.linalg.norm(cum_all)),
                    "S_restore": S_restore,
                    "elapsed_s": round(time.time() - T0, 1)})
                log(f"  [{tag}] ROUND {rnd:3d}: panel "
                    + " ".join(f"{k} {v:.6f}(x{ratios[k]:.3f})"
                               for k, v in panel.items())
                    + f" | CE_R {ce_r:.4f} |d_org| {dn:.3f} | S_restore "
                    f"{S_restore:.4f}/{budget_r:.4f} "
                    f"({S_restore / budget_r:.1%} of B_R)")
            else:
                log(f"  [{tag}] ROUND {rnd:3d}: panel "
                    + " ".join(f"{k} {v:.4f}" for k, v in panel.items())
                    + f" | S_restore {S_restore:.4f}")
            if not ok_t:
                E261._end_burst_early(tag, n_burst, t_burst)
                chunk_capped = True
                break
            if (time.time() - t_burst) > E261.BURST_MAX_S:
                log(f"  [{tag}] chunk {n_chunks}: burst cap "
                    f"{E261.BURST_MAX_S:.0f}s at round {rnd} — resume "
                    f"ckpt saved")
                chunk_capped = True
                break
        chunk_table.append({**devices_row,
                            "seconds": round(time.time() - t_burst, 1),
                            "rounds_done": rnd, "capped": chunk_capped,
                            "max_temp_c": max(chunk_temps, default=None)})
        torch.save({"model": {k: v.detach().cpu()
                              for k, v in net.state_dict().items()},
                    "optFs": [o.state_dict() for o in opt_Fs],
                    "mgen_state": mgen.get_state(),
                    "round": rnd, "traj": state["traj"],
                    "panel_ledger": state["panel_ledger"],
                    "ctl_ledgers": state["ctl_ledgers"],
                    "budget_ledger": state["budget_ledger"],
                    "bufsep": state["bufsep"],
                    "maint_cums": [c.cpu() for c in maint_cums],
                    "S_restore": S_restore,
                    "n_ctl_capped": state["n_ctl_capped"],
                    "events_done": events_done,
                    "f3_first_return_round": state["f3_first_return_round"],
                    "n_resurrections": state["n_resurrections"],
                    "n_kills": state["n_kills"],
                    "n_chunks": n_chunks, "chunk_table": chunk_table},
                   resume_ck)
        if rnd >= RESTORE_ROUNDS:
            break
        if n_chunks >= 20:
            raise RuntimeError(f"{tag}: cap-loop guard at chunk {n_chunks}")
        E261.burst_cooldown(tag)
        t_burst = None
    net.eval()
    sd_cpu = {k: v.detach().cpu().clone() for k, v in net.state_dict().items()}
    out = _p2_final(state, RESTORE_ROUNDS)
    out["sd"] = sd_cpu
    out["restore_cums_np"] = [c.double().cpu().numpy() for c in maint_cums]
    out["bufF_finals_flat"] = [opt_buffer_flat(o, list(net.parameters()))
                               for o in opt_Fs]
    out["n_chunks"] = n_chunks
    return out


