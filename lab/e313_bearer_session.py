def stream_live(corpus_ledger: dict) -> dict:
    rows = sorted((int(k), v["ce"]) for k, v in corpus_ledger.items())
    early = [c for t, c in rows if 1 <= t <= 100]
    late = [c for t, c in rows if 300 < t <= 400]
    if not early or not late:
        return {"live": None, "note": "no CE rows (smoke cadence)"}
    e_med, l_med = med(early), med(late)
    improving = bool(l_med < e_med)
    stable = bool(l_med <= STREAM_STABLE_TOL * e_med)
    return {"ce_early_median": e_med, "ce_late_median": l_med,
            "improving": improving, "stable_1p05": stable,
            "live": bool(improving or stable)}


