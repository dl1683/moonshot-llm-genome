def brush_svd_read(dw: np.ndarray) -> dict:
    """e307's svd_read VERBATIM in form: per-2D-matrix SVD fp64; T3/T10/
    cross90/cross99 over the 2D energy; 1D energies excluded from the
    spectrum (co-reported)."""
    spect = []
    off = 0
    per_energy = {}
    for k, sh in _KEYS_SHAPES:
        n = int(np.prod(sh))
        seg = dw[off:off + n]
        off += n
        if len(sh) == 1:
            per_energy[k] = float((seg * seg).sum())
            continue
        s = torch.linalg.svdvals(torch.from_numpy(
            seg.reshape(sh).copy())).numpy()
        en = (s * s).astype(np.float64)
        spect.append(en)
        per_energy[k] = float(en.sum())
    glob = np.sort(np.concatenate(spect))[::-1]
    e2d = float(glob.sum())
    cum = np.cumsum(glob)
    tot_e = sum(per_energy.values())
    if e2d <= 0.0 or tot_e <= 0.0:
        return {"T3": None, "T10": None, "cross90": None, "cross99": None,
                "e_2d": e2d, "e_1d_share": None}
    return {"T3": float(glob[:3].sum() / e2d),
            "T10": float(glob[:10].sum() / e2d),
            "cross90": int(np.searchsorted(cum, 0.90 * e2d) + 1),
            "cross99": int(np.searchsorted(cum, 0.99 * e2d) + 1),
            "e_2d": e2d, "e_1d_share": float(1.0 - e2d / tot_e)}


def brush_repeat_read(maint_cum_np: np.ndarray, r_norms: list,
                      b_norms: list, gn_norms: list) -> dict:
    """e307's R1 + R2 EXACT algebra on this session's own ledgers:
    R1 = (||cum||^2 - sum r_i^2) / ((sum r_i)^2 - sum r_i^2); rho_t =
    (b_t^2 - 0.81 b_{t-1}^2 - gn_t^2)/(1.8 b_{t-1} gn_t); the
    consecutive-step cosine (0.9 b_{t-1} + rho_t gn_t)/b_t."""
    cum2 = float(maint_cum_np @ maint_cum_np)
    sr = float(sum(r_norms))
    sr2 = float(sum(x * x for x in r_norms))
    denom = sr * sr - sr2
    r1 = (cum2 - sr2) / denom if denom > 0 else None
    rhos, consec = [], []
    for t in range(1, len(b_norms)):
        b_prev, b_t, gn_t = b_norms[t - 1], b_norms[t], gn_norms[t]
        den = 1.8 * b_prev * gn_t
        if den <= 0:
            continue
        rho = (b_t * b_t - 0.81 * b_prev * b_prev - gn_t * gn_t) / den
        rho = max(-1.0, min(1.0, rho))
        rhos.append(rho)
        if b_t > 0:
            consec.append((0.9 * b_prev + rho * gn_t) / b_t)
    return {"R1_wmean_cross_event_cos": r1,
            "rho_series": [float(x) for x in rhos],
            "rho_mean": (float(np.mean(rhos)) if rhos else None),
            "consec_step_cos": [float(x) for x in consec],
            "consec_cos_mean": (float(np.mean(consec)) if consec else None)}


