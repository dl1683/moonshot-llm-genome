def main() -> None:
    log(f"E340 — THE UNSHELLED HIGH-READ COMMIT (smoke={SMOKE}) -> {RD}")
    metrics["birth_commit"] = BIRTH_COMMIT_PINNED
    write_partial("startup (bars registered, committed at birth)")
    set_seed(34001)              # global init only; every RNG is its own

    # ---- the harness's own phases (VERBATIM, into this cell's context) ---
    p0 = E38.phase_P0()
    p1 = phase_P1_340(p0)
    p2 = E38.phase_P2(p1["theta0"])
    p3 = E38.phase_P3()
    p3b = phase_P3b()

    # ---- the arms (sequential; cooldown between; GPU single-lane) -------
    comm = E38.wash_arm("COMMIT", p2["net0"], RD / "wash_committed_resume.pt",
                        p0, armed=True)
    if torch.cuda.is_available():
        E38.E261.burst_cooldown("between-arms")
    twin = E38.wash_arm("TWIN", p2["twin0"], RD / "wash_twin_resume.pt",
                        p0, armed=False)

    comm_s = E38.arm_summary(comm["traj"], p3["band"], p3["sand"])
    twin_s = E38.arm_summary(twin["traj"], p3["band"], p3["sand"])
    p5 = E38.phase_P5(comm, twin, {"net0": p2["net0"]})
    adj = adjudicate_340(comm_s, twin_s, p3["band"])

    metrics["arms"] = {
        "committed": {k: v for k, v in comm_s.items()},
        "twin": {k: v for k, v in twin_s.items()},
        "resumed_final": {"committed": comm["resumed_final"],
                          "twin": twin["resumed_final"]},
    }
    metrics["adjudication"] = adj
    metrics["thermal"] = {
        "max_temp": (max((r["temp"] for r in thermal_log), default=None)),
        "polls": len(thermal_log),
        "device_events": device_events + E38.device_events,
    }
    metrics["status"] = ("DONE (smoke; nothing adjudicated)" if SMOKE
                         else f"DONE: {adj['verdict']}")
    metrics["git_head_final"] = git_head()
    metrics["completed_utc"] = utcnow()
    save_json(RD / "metrics.json", metrics)

    make_png_340(adj, comm_s, twin_s, p3["band"], p3b)
    write_report_340(adj, comm_s, twin_s, p3["band"], p3["sand"],
                     p3["ball_ref"], p5, p3b)
    log(f"E340 VERDICT: {adj['verdict']}")


if __name__ == "__main__":
    main()
