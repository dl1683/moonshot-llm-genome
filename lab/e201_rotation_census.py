# ------------------------------------------------------------------ plots

def plot_census(path, pairs, ug, verdict, alt_bar):
    """The census table visualized: (A) the consecutive-front mutual
    cosines across organisms (alive cells colored, post-death flagged);
    (B) the ROOT-point ug overlaps per front per organism."""
    fig = plt.figure(figsize=(15.5, 8.6))
    gs = fig.add_gridspec(2, 2, height_ratios=[1.35, 1.0], hspace=0.34,
                          wspace=0.22)

    # ---- panel A: the mutual-correlation table --------------------------
    axA = fig.add_subplot(gs[0, :])
    orgs = ["org1", "MIRABEL", "org2-half", "org2-dead-full"]
    labels = ["org1\n(e131, 2.74M 6L)", "MIRABEL\n(e193b, 2.74M 6L)",
              "org2-half\n(e157_f2, 873k 4L)",
              "org2-dead-full\n(context)"]
    pair_cols = ["(u0,u1)", "(u1,u2)", "(u2,u3)", "(u3,u4)", "(u4,u5)"]
    grid = np.full((len(orgs), len(pair_cols)), np.nan)
    alive = np.zeros_like(grid, dtype=bool)
    for p in pairs:
        r = orgs.index(p["organism"])
        c = p["pair"][0]
        grid[r, c] = p["cos"]
        alive[r, c] = bool(p["alive_pair"])
    cmap = LinearSegmentedColormap.from_list(
        "bwr_soft", [(0.0, "#08306b"), (0.5, "#f7f7f7"), (1.0, "#a50f15")])
    vmax = 0.42
    axA.imshow(np.clip(grid, -vmax, vmax), cmap=cmap, vmin=-vmax, vmax=vmax,
               aspect="auto")
    for r in range(len(orgs)):
        for c in range(len(pair_cols)):
            v = grid[r, c]
            if np.isnan(v):
                axA.text(c, r, "—", ha="center", va="center",
                         color="#999999", fontsize=10)
                continue
            star = "" if alive[r, c] else "\u2020"
            axA.text(c, r, f"{v:+.3f}{star}", ha="center", va="center",
                     fontsize=11.5, fontweight="bold" if alive[r, c]
                     else "normal",
                     color="#111111")
            axA.add_patch(plt.Rectangle(
                (c - 0.5, r - 0.5), 1, 1, fill=False,
                edgecolor="#222222" if alive[r, c] else "#bbbbbb",
                linewidth=2.0 if alive[r, c] else 0.8,
                linestyle="-" if alive[r, c] else ":"))
    axA.set_xticks(range(len(pair_cols)), pair_cols, fontsize=10)
    axA.set_yticks(range(len(orgs)), labels, fontsize=9)
    axA.set_xticks(np.arange(-.5, len(pair_cols), 1), minor=True)
    axA.set_yticks(np.arange(-.5, len(orgs), 1), minor=True)
    axA.grid(which="minor", color="#dddddd", linewidth=0.6)
    axA.tick_params(which="minor", length=0)
    axA.set_title("E201 — THE FRONT-ROTATION CENSUS: consecutive-front "
                  f"mutual cosines  cos(u_t, u_{{t+1}})   [bar: "
                  f"alive pairs < {alt_bar:.2f}]\n\u2020 = post-death "
                  "context (never adjudicated);  org2-dead-full row = "
                  "dead-state reads, context only",
                  fontsize=11.5)
    sm = plt.cm.ScalarMappable(cmap=cmap,
                               norm=plt.Normalize(vmin=-vmax, vmax=vmax))
    cb = fig.colorbar(sm, ax=axA, orientation="vertical", shrink=0.85,
                      pad=0.01)
    cb.set_label("cos(u_t, u_{t+1})  (fp64)", fontsize=9)

    # ---- panel B: the ROOT-point ug overlaps ------------------------------
    axB = fig.add_subplot(gs[1, 0])
    series = [
        ("org1", ug["org1"], "#1f77b4"),
        ("MIRABEL", ug["MIRABEL"], "#2ca02c"),
        ("org2-half", ug["org2-half"], "#ff7f0e"),
    ]
    w = 0.26
    xs = np.arange(5)
    for i, (name, d, col) in enumerate(series):
        vals = [d.get(f"u{t}") for t in range(5)]
        xpos = xs + (i - 1) * w
        for x, v, t in zip(xpos, vals, range(5)):
            if v is None:
                continue
            post = (name == "org1" and t >= 2) or \
                   (name == "MIRABEL" and t >= 3)
            axB.bar(x, v, width=w * 0.92, color=col,
                    alpha=0.45 if post else 1.0,
                    hatch="//" if post else None,
                    edgecolor="#333333", linewidth=0.5)
        axB.bar([], [], color=col, label=name)
    iso = 1.0 / (2739072 ** 0.5)
    axB.axhline(0.0, color="#333333", linewidth=0.9)
    axB.axhline(iso, color="#999999", linewidth=0.8, linestyle="--")
    axB.text(4.45, iso, f" iso floor (2.74M) {iso:.1e}", fontsize=7.5,
             va="bottom", ha="right", color="#777777")
    axB.set_xticks(xs, [f"u{t}" for t in range(5)], fontsize=9)
    axB.set_ylim(-0.45, 0.72)
    axB.legend(fontsize=9, loc="upper right")
    axB.set_title("each front vs its OWN root fact-gradient u_g\n"
                  "(ROOT-point theta_0 read — the dual-estimator lesson: "
                  "point stated; hatched = post-death)",
                  fontsize=10)
    axB.set_ylabel("cos(u_t, u_g)  (fp64)", fontsize=9)

    # ---- panel C: the verdict box -----------------------------------------
    axC = fig.add_subplot(gs[1, 1])
    axC.axis("off")
    alive_rows = [(p["organism"], p["pair"], p["cos"])
                  for p in pairs if p["alive_pair"]
                  and p["organism"] in ("org1", "MIRABEL")]
    half_rows = [(p["pair"], p["cos"]) for p in pairs
                 if p["alive_pair"] and p["organism"] == "org2-half"]
    lines = ["VERDICT: " + verdict, ""]
    for org, pr, v in alive_rows:
        lines.append(f"{org:9s} (u{pr[0]},u{pr[1]}):  {v:+.4f}  "
                     f"{'< ' + f'{alt_bar:.2f}' if v < alt_bar else '>= -0.10'}"
                     f"  [ADJUDICATES]")
    lines.append("")
    lines.append("half-step anchor (context): "
                 + "  ".join(f"{a}->{b} {c:+.3f}" for (a, b), c in half_rows))
    lines.append("")
    lines.append("post-death context: org1 (u1,u2) "
                 f"{[p['cos'] for p in pairs if p['organism']=='org1' and p['pair']==[1,2]][0]:+.4f}"
                 " (committed)")
    m23 = [p["cos"] for p in pairs if p["organism"] == "MIRABEL"
           and p["pair"] == [2, 3]]
    if m23:
        lines.append(f"                 MIRABEL (u2,u3) {m23[0]:+.4f} "
                     "(fresh u3, this cell)")
    lines.append("")
    lines.append("the rotation-alternates account is tested at n=3;")
    lines.append("nothing guaranteed — the openness is the point.")
    axC.text(0.02, 0.97, "\n".join(lines), fontsize=9.6, va="top",
             family="monospace",
             bbox=dict(boxstyle="round,pad=0.6", facecolor="#f5f5f5",
                       edgecolor="#444444"))

    fig.suptitle(f"E201 — the front-rotation census  |  verdict: "
                 f"{verdict}", fontsize=13, y=0.995)
    fig.savefig(path, dpi=150, bbox_inches="tight")
    plt.close(fig)


