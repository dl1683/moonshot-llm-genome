def run_arm(p0: dict, arm: dict, start_path: Path) -> dict:
    tag = arm["tag"]
    host_id = p0[arm["host"]]
    guest_id = p0[arm["guest"]]
    resume_ck = RD / f"arm_resume_{tag}.pt"

    state = {"step": 0, "traj": [], "captured": {}, "draws": []}
    if resume_ck.exists():
        state = torch.load(resume_ck, map_location="cpu",
                           weights_only=False)
        log(f"  [{tag}] RESUMED at step {state['step']}/{CONS_STEPS} "
            f"({len(state['captured'])} captures restored)")

    if int(state.get("step", 0)) >= CONS_STEPS:
        log(f"  [{tag}] resume ckpt already finished at s{state['step']} "
            "— training skipped")
        return {"traj": state["traj"], "captured": state["captured"],
                "draws": state.get("draws", [])}

    net0 = G1.evl_load(load_model_sd(start_path))
    dev = GPU
    net = copy.deepcopy(net0).to(dev)
    net.train()
    opt = torch.optim.AdamW(net.parameters(), lr=FT_LR, betas=(0.9, 0.95),
                            weight_decay=0.1)
    gen = torch.Generator().manual_seed(CONS_SEED)
    if resume_ck.exists():
        net.load_state_dict(state["model"])
        net.to(dev)
        net.train()
        opt.load_state_dict(state["opt"])
        gen.set_state(state["gen_state"])

    evl = copy.deepcopy(net0).to(dev)     # the measurement twin
    draw = make_draw(p0, arm["slot_keys"])
    captured: dict = state["captured"]
    step = state["step"]
    traj: list = state["traj"]
    draws: list = state["draws"]
    max_temp_seen = 0.0

    def save_resume() -> None:
        torch.save({"model": {k: v.detach().cpu().clone()
                              for k, v in net.state_dict().items()},
                    "opt": opt.state_dict(), "gen_state": gen.get_state(),
                    "step": state["step"], "traj": state["traj"],
                    "captured": state["captured"],
                    "draws": state["draws"]}, resume_ck)

    burst_n = 0
    # THE POST-BREACH PHASE FLAG: arms tagged in POST_BREACH_ARMS run
    # every burst under the phase-2 guard (the deviation discloses the
    # two-phase envelope; finished arms keep their phase-1 records).
    phase2 = tag in POST_BREACH_ARMS
    b_cap = TRAIN_BURST_CAP_2 if phase2 else TRAIN_BURST_CAP
    cd_s = COOLDOWN_S_2 if phase2 else COOLDOWN_S
    t_abort = THERM_NEVER_PAST_2 if phase2 else THERM_NEVER_PAST
    t_launch = THERM_LAUNCH_MAX_2 if phase2 else THERM_LAUNCH_MAX
    poll_every = POLL_EVERY_2 if phase2 else POLL_EVERY
    while step < CONS_STEPS:
        # ---- the launch gate (double-polled) --------------------------
        while not gpu_launch_ok2(f"{tag}.b{burst_n}", t_launch):
            log(f"  [{tag}] launch HOLD (busy/hot) — waiting "
                f"{cd_s:.0f}s")
            time.sleep(cd_s)
        burst_n += 1
        t_burst = time.time()
        burst_rec = {"tag": f"{tag}.burst{burst_n}",
                     "t_start": utcnow(), "steps": [step, None],
                     "max_temp": None, "dur_s": None,
                     "end_reason": None, "cooldown_s": cd_s,
                     "envelope_phase": 2 if phase2 else 1}
        aborted = False
        while step < CONS_STEPS:
            step += 1
            x, y, m, dr = draw(gen, dev)
            draws.append({"step": step, "ix": dr[0], "aj": dr[1],
                          "rj": dr[2]})
            loss = train_step(net, opt, x, y, m)
            # ---- the per-step dual-channel read (on the twin) ---------
            sd_dev = {k: v.detach().clone() for k, v
                      in net.state_dict().items()}
            evl.load_state_dict(sd_dev)
            evl.eval()
            bh = G1.battery_cell(evl, p0["g0_ids"].to(dev), host_id)
            bg = G1.battery_cell(evl, p0["g0_ids"].to(dev), guest_id)
            traj.append({"step": step, "host": bh["mean_pz"],
                         "guest": bg["mean_pz"],
                         "ce_batch": loss})
            if step in CAPTURE_STEPS and step not in captured:
                captured[step] = {k: v.detach().cpu().clone()
                                  for k, v in net.state_dict().items()}
                log(f"  [{tag}] CAPTURED s{step} (host "
                    f"{bh['mean_pz']:.6f} | guest {bg['mean_pz']:.6f})")
            if step % 25 == 0 or step == 1:
                log(f"  [{tag}] s{step:4d} host {bh['mean_pz']:.6f} "
                    f"guest {bg['mean_pz']:.6f} CE {loss:.4f}")
            state["step"] = step
            state["traj"] = traj
            state["captured"] = captured
            state["draws"] = draws
            # ---- the in-burst thermal + burst-cap guards -------------
            if step % poll_every == 0:
                gs = common.gpu_status()
                max_temp_seen = max(max_temp_seen, gs["temp"])
                if gs["temp"] >= t_abort:
                    log(f"  [{tag}] THERMAL GUARD {gs['temp']:.1f}C — "
                        f"burst ended, resume saved")
                    burst_rec["end_reason"] = \
                        f"thermal {gs['temp']:.1f}C"
                    aborted = True
            if (time.time() - t_burst) > b_cap:
                burst_rec["end_reason"] = "burst cap"
                aborted = True
            if aborted:
                break
        burst_rec["steps"][1] = step
        burst_rec["dur_s"] = round(time.time() - t_burst, 1)
        gs_end = common.gpu_status()
        max_temp_seen = max(max_temp_seen, gs_end["temp"])
        burst_rec["max_temp"] = max_temp_seen
        burst_rec["post_poll"] = gs_end
        metrics["envelope"]["bursts"].append(burst_rec)
        save_resume()
        write_partial(f"P1b arm {tag} burst {burst_n} ended at s{step}")
        if step < CONS_STEPS:
            log(f"  [{tag}] burst {burst_n} ended "
                f"({burst_rec['end_reason']}) at s{step} — cooldown "
                f"{cd_s:.0f}s (temp {gs_end['temp']:.0f}C)")
            time.sleep(cd_s)
    save_resume()
    log(f"  [{tag}] replay finished: {CONS_STEPS} steps, "
        f"{len(captured)} captures, {burst_n} burst(s), max temp "
        f"{max_temp_seen:.1f}C")
    del net, opt, evl
    return {"traj": traj, "captured": captured, "draws": draws}


