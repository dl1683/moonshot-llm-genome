def apply_flat64(net, flat64: np.ndarray, offsets, shapes) -> None:
    """theta <- flat64 (fp64 arithmetic) cast fp32 into the params —
    e314/e311's applied-state convention, VERBATIM (x19/e325's port)."""
    f32 = flat64.astype(np.float32)
    with torch.no_grad():
        for p, (a, b), shp in zip(net.parameters(), offsets, shapes):
            p.copy_(torch.from_numpy(f32[a:b]).reshape(shp))


def inroom_frac(room: "E261.SRCT", v64: np.ndarray) -> float:
    vn = float(np.linalg.norm(v64))
    if vn == 0.0:
        return 0.0
    return float(np.linalg.norm(room.project(v64)) / vn)


def pending_buffer_sqnorm(opt, params, momentum: float) -> float:
    sq = torch.zeros((), device=next(iter(params)).device)
    st = opt.state
    for p in params:
        d = st.get(p)
        buf_prev = d.get("momentum_buffer") if isinstance(d, dict) else None
        if buf_prev is None:
            v = p.grad.detach()
        else:
            v = momentum * buf_prev + p.grad.detach()
        sq = sq + v.square().sum()
    return float(sq.item())


@torch.no_grad()
def last_logits(net, ids: torch.Tensor, bs: int = BS) -> np.ndarray:
    """x16's read convention VERBATIM: last-position logits, fp32
    forward, fp64 cast downstream (bs=30 = the committed batch)."""
    net.eval()
    outs = []
    for i in range(0, ids.shape[0], bs):
        lg, _ = net(ids[i:i + bs])
        outs.append(lg[:, -1, :].clone())
    return torch.cat(outs).numpy().astype(np.float64)


def softmax64(L: np.ndarray) -> np.ndarray:
    z = L - L.max(axis=1, keepdims=True)
    e = np.exp(z)
    return e / e.sum(axis=1, keepdims=True)


def z_excess(Lb: np.ndarray, Lt: np.ndarray, zid: int) -> dict:
    """x16's Z-bias excess instrument VERBATIM, per battery: per-context
    dlogit(Z) - mean dlogit over the vocab; plus the raw push on the
    name logit and the read means."""
    dlog_z = Lt[:, zid] - Lb[:, zid]
    dlog_mean = (Lt - Lb).mean(axis=1)
    dbias_z = dlog_z - dlog_mean
    pb, pt = softmax64(Lb), softmax64(Lt)
    return {
        "z_excess_mean": float(dbias_z.mean()),
        "z_excess_median": float(np.median(dbias_z)),
        "z_excess_frac_positive": float((dbias_z > 0).mean()),
        "dlog_z_mean": float(dlog_z.mean()),
        "pz_base_mean": float(pb[:, zid].mean()),
        "pz_trig_mean": float(pt[:, zid].mean()),
    }


