def make_draw(p0: dict, slot_keys: tuple):
    """e346's per-slot keyed cons draw, generalized ONLY in the pools dict
    (z/t canon + a/b fresh — a = QELVARO the host, b = NYSTORA the
    guest). The generator consumption is IDENTICAL for every keying
    (e346's doctrine)."""
    n_pool = p0["pool_z_x"].shape[0]
    cons_anchor = p0["cons_anchor"]
    train_ids = p0["train_ids"]
    pools_x = {"z": p0["pool_z_x"], "t": p0["pool_t_x"],
               "a": p0["pool_a_x"], "b": p0["pool_b_x"]}
    pools_m = {"z": p0["pool_z_mask"], "t": p0["pool_t_mask"],
               "a": p0["pool_a_mask"], "b": p0["pool_b_mask"]}

    def draw(gen, dev):
        ix = torch.randint(n_pool, (16,), generator=gen)
        aj = torch.randint(cons_anchor.shape[0], (8,), generator=gen)
        rj = torch.randint(len(train_ids) - G1.BLOCK - 1, (8,),
                           generator=gen)
        nw = torch.stack([pools_x[slot_keys[s]][ix[s]] for s in range(16)])
        nm = torch.stack([pools_m[slot_keys[s]][ix[s]] for s in range(16)])
        anc = torch.cat([cons_anchor[aj],
                         torch.stack([train_ids[s: s + G1.BLOCK]
                                      for s in rj])], 0)
        x = torch.cat([nw[:, :-1], anc[:, :-1]], 0).to(dev)
        y = torch.cat([nw[:, 1:], anc[:, 1:]], 0).to(dev)
        m = torch.zeros(32, x.shape[1], dtype=torch.bool, device=dev)
        m[:16] = nm.to(dev)
        return x, y, m, (ix.tolist(), aj.tolist(), rj.tolist())
    return draw


def train_step(net, opt, x, y, m):
    logits, _ = net(x)
    nll = F.cross_entropy(logits.reshape(-1, logits.shape[-1]),
                          y.reshape(-1), reduction="none"
                          ).view(x.shape[0], x.shape[1])
    nm = nll[:16][m[:16]]
    cm = nll[16:]
    loss = (nm.sum() + cm.sum()) / (nm.numel() + cm.numel())
    opt.zero_grad(set_to_none=True)
    loss.backward()
    torch.nn.utils.clip_grad_norm_(net.parameters(), 1.0)
    opt.step()
    return float(loss.item())


def install_leg(tag: str, start_sd: dict, steps: int, seed: int,
                p0: dict, inst_x, inst_mask, rungs: set,
                resume_ck: Path, end_ck: Path, host_id: int,
                dual_id: int | None, net0_class: str,
                e001_flat64: np.ndarray, keep_end: bool = True) -> dict:
    """x53/x60's replay_install_leg VERBATIM (the e043-Dmix install
    arithmetic: batch 16+16+32, house cosine, masked union CE) with
    instrumented rungs + the end-state save."""
    state = {"step": 0, "draws": [], "rows": {}}
    if resume_ck.exists():
        state = torch.load(resume_ck, map_location="cpu",
                           weights_only=False)
        log(f"  [{tag}] RESUMED at step {state['step']}/{steps} "
            f"({len(state['rows'])} rows restored)")
    if int(state.get("step", 0)) >= steps:
        # already complete: the end state is the resume ck's final model
        if end_ck.exists():
            end_sd = torch.load(end_ck, map_location="cpu",
                                weights_only=False)
        else:
            end_sd = {k: v.detach().cpu().clone()
                      for k, v in state["model"].items()}
        return {"rows": state["rows"], "draws": state["draws"],
                "steps_ran": steps, "end_sd": end_sd}

    net = G1.evl_load(start_sd).to(CPU)
    net.train()
    opt = torch.optim.AdamW(net.parameters(), lr=E43.LR, betas=(0.9, 0.95),
                            weight_decay=0.1)
    gen = torch.Generator().manual_seed(seed)
    if resume_ck.exists():
        net.load_state_dict(state["model"])
        net.train()
        opt.load_state_dict(state["opt"])
        gen.set_state(state["gen_state"])
    name_bs, corp_bs, mix_random = G1.NAME_BS, E43.CORP_BS, E43.MIX_RANDOM
    n_anc_full = p0["anchor_full"].shape[0]
    train_ids = p0["train_ids"]
    step = state["step"]
    rows: dict = state["rows"]
    draws: list = state["draws"]
    t_slice = time.time()
    n_caps = 0

    def rung_row(step_: int) -> None:
        sd_cpu = {k: v.detach().cpu().clone()
                  for k, v in net.state_dict().items()}
        row = instrument(p0, sd_cpu, f"{tag}_s{step_}", host_id,
                         e001_flat64, dual_id=dual_id)
        row.update({"step": step_, "provenance": "replay (CPU desk)",
                    "net0_class": net0_class, "leg": tag})
        rows[f"{tag}_s{step_}"] = row
        log(f"  [{tag}] s{step_:4d} READ {row['read']:.6f} | dual "
            f"{(row['dual']['means']['g0'] if row.get('dual')
                else float('nan')):.6f} | |W| "
            f"{row['write_norm']:.2f} inroom {row['in_room']:.3f} | CE_R "
            f"{row['ce_r']:.4f}")

    def save_resume() -> None:
        torch.save({"model": {k: v.detach().cpu().clone()
                              for k, v in net.state_dict().items()},
                    "opt": opt.state_dict(), "gen_state": gen.get_state(),
                    "step": step, "draws": draws, "rows": rows},
                   resume_ck)

    while step < steps:
        step += 1
        f = cosine_lr(step - 1, INST_TOTAL)       # the house schedule
        for g_ in opt.param_groups:
            g_["lr"] = E43.LR * f
        ix = torch.randint(inst_x.shape[0], (name_bs,), generator=gen)
        aj = torch.randint(n_anc_full, (corp_bs - mix_random,),
                           generator=gen)
        rj = torch.randint(len(train_ids) - G1.BLOCK - 1, (mix_random,),
                           generator=gen)
        draws.append({"step": step, "ix": ix.tolist(),
                      "aj": aj.tolist(), "rj": rj.tolist()})
        corp = torch.cat([p0["anchor_full"][aj],
                          torch.stack([train_ids[s: s + G1.BLOCK]
                                       for s in rj])], 0)
        nw = inst_x[ix]
        x = torch.cat([nw[:, :-1], corp[:, :-1]], 0)
        y = torch.cat([nw[:, 1:], corp[:, 1:]], 0)
        m = torch.zeros(name_bs + corp_bs, x.shape[1],
                        dtype=torch.bool)
        m[:name_bs] = inst_mask[ix]
        logits, _ = net(x)
        nll = F.cross_entropy(logits.reshape(-1, logits.shape[-1]),
                              y.reshape(-1), reduction="none"
                              ).view(x.shape[0], x.shape[1])
        nm = nll[:name_bs][m[:name_bs]]
        cm = nll[name_bs:]
        loss = (nm.sum() + cm.sum()) / (nm.numel() + cm.numel())
        opt.zero_grad(set_to_none=True)
        loss.backward()
        torch.nn.utils.clip_grad_norm_(net.parameters(), 1.0)
        opt.step()
        if step in rungs:
            rung_row(step)
        if (time.time() - t_slice) > TRAIN_CAP_CPU:
            save_resume()
            n_caps += 1
            metrics["envelope"].setdefault("slice_caps", []).append(
                {"tag": tag, "step": step, "t": utcnow()})
            log(f"  [{tag}] slice cap at s{step} — resume saved, "
                "continuing (CPU park convention)")
            t_slice = time.time()
    save_resume()
    sd_end = {k: v.detach().cpu().clone()
              for k, v in net.state_dict().items()}
    if keep_end:
        torch.save(sd_end, end_ck)
    log(f"  [{tag}] leg finished: {steps} steps, {n_caps} slice caps, "
        f"{len(rows)} instrument rows")
    del net, opt
    return {"rows": rows, "draws": draws, "steps_ran": step,
            "end_sd": sd_end}


def stream_leg(tag: str, start_sd: dict, steps: int, seed: int,
               p0: dict, slot_keys: tuple, rungs: set,
               resume_ck: Path, host_id: int, dual_id: int,
               net0_class: str, e001_flat64: np.ndarray) -> dict:
    """The per-slot keyed cons stream (e346's rig: batch 32 = 16 pool + 8
    anchors + 8 randoms; const lr 1e-3; masked union CE) with
    instrumented rungs, dual-channel."""
    state = {"step": 0, "draws": [], "rows": {}}
    if resume_ck.exists():
        state = torch.load(resume_ck, map_location="cpu",
                           weights_only=False)
        log(f"  [{tag}] RESUMED at step {state['step']}/{steps} "
            f"({len(state['rows'])} rows restored)")
    if int(state.get("step", 0)) >= steps:
        return {"rows": state["rows"], "draws": state["draws"],
                "steps_ran": steps}

    net = G1.evl_load(start_sd).to(CPU)
    net.train()
    opt = torch.optim.AdamW(net.parameters(), lr=FT_LR, betas=(0.9, 0.95),
                            weight_decay=0.1)
    gen = torch.Generator().manual_seed(seed)
    if resume_ck.exists():
        net.load_state_dict(state["model"])
        net.train()
        opt.load_state_dict(state["opt"])
        gen.set_state(state["gen_state"])
    draw = make_draw(p0, slot_keys)
    step = state["step"]
    rows: dict = state["rows"]
    draws: list = state["draws"]
    t_slice = time.time()
    n_caps = 0

    def rung_row(step_: int) -> None:
        sd_cpu = {k: v.detach().cpu().clone()
                  for k, v in net.state_dict().items()}
        row = instrument(p0, sd_cpu, f"{tag}_s{step_}", host_id,
                         e001_flat64, dual_id=dual_id)
        row.update({"step": step_, "provenance": "replay (CPU desk)",
                    "net0_class": net0_class, "leg": tag,
                    "slot_keys": "".join(slot_keys)})
        rows[f"{tag}_s{step_}"] = row
        log(f"  [{tag}] s{step_:4d} HOST {row['read']:.6f} GUEST "
            f"{row['dual']['means']['g0']:.6f} | |W| "
            f"{row['write_norm']:.2f} inroom {row['in_room']:.3f} | "
            f"r1 {row['corrs']['g-12|g0']}")

    def save_resume() -> None:
        torch.save({"model": {k: v.detach().cpu().clone()
                              for k, v in net.state_dict().items()},
                    "opt": opt.state_dict(), "gen_state": gen.get_state(),
                    "step": step, "draws": draws, "rows": rows},
                   resume_ck)

    while step < steps:
        step += 1
        x, y, m, dr = draw(gen, CPU)
        draws.append({"step": step, "ix": dr[0], "aj": dr[1],
                      "rj": dr[2]})
        train_step(net, opt, x, y, m)
        if step in rungs:
            rung_row(step)
        if (time.time() - t_slice) > TRAIN_CAP_CPU:
            save_resume()
            n_caps += 1
            metrics["envelope"].setdefault("slice_caps", []).append(
                {"tag": tag, "step": step, "t": utcnow()})
            log(f"  [{tag}] slice cap at s{step} — resume saved, "
                "continuing (CPU park convention)")
            t_slice = time.time()
    save_resume()
    log(f"  [{tag}] leg finished: {steps} steps, {n_caps} slice caps, "
        f"{len(rows)} instrument rows")
    del net, opt
    return {"rows": rows, "draws": draws, "steps_ran": step}


