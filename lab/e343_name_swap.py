def make_png(p4: dict, rows: dict, p0: dict) -> None:
    adj = p4["adj"]
    pairs = p4["pairs"]
    in_window = [p for p in pairs if p["in_window"]]
    walk = p0["committed_x45"]["walk_rungs"]
    fig = plt.figure(figsize=(16.5, 10.5))
    gs = fig.add_gridspec(2, 3)

    # ---- panel 1: the read trajectories -------------------------------
    ax1 = fig.add_subplot(gs[0, 0])
    zr = sorted(p4["zeph_rows"], key=lambda r: r["step"])
    ax1.plot([z["step"] for z in zr], [z["read"] for z in zr], "o-",
             color="tab:purple", label="the ZEPHYRA install path (mine)")
    ann = sorted(p4["ann_rows"], key=lambda r: r["step"])
    ax1.plot([a["step"] for a in ann], [a["read"] for a in ann], "s--",
             color="tab:red", alpha=0.8, label="the anneal (x45)")
    for p in pairs:
        sty = "-" if p["in_window"] else ":"
        alph = 0.45 if p["in_window"] else 0.15
        ax1.plot([p["zeph_step"], p["ann_step"]],
                 [p["zeph_read"], p["ann_read"]], sty, color="gray",
                 lw=0.8, alpha=alph)
    ax1.axhline(READ_BAR, color="black", ls="--", lw=1)
    ax1.set_xlabel("formation step (install 0-400; anneal 0-900)")
    ax1.set_ylabel("the read (battery mean p(NAME))")
    ax1.set_title("the two paths (matched pairs joined; dotted = "
                  "out-of-window)")
    ax1.legend(fontsize=7)
    ax1.grid(alpha=0.25)

    # ---- panel 2: the separation summary ------------------------------
    ax2 = fig.add_subplot(gs[0, 1])
    keys = list(PRIMARY + COREPORT)
    vals = [adj["separations"][k]["mean_abs_d"] or 0.0 for k in keys]
    cons = [adj["separations"][k]["sign_consistency"] or 0.0 for k in keys]
    colors = []
    for k in keys:
        s = adj["separations"][k]
        colors.append("tab:green" if s["separates_decorrelated"]
                      else ("tab:orange" if s["separates_any"] else
                            "tab:gray"))
    xs = range(len(keys))
    ax2.barh([i + 0.18 for i in xs], vals, height=0.36, color=colors)
    ax2.barh([i - 0.18 for i in xs],
             [FLOOR_CORR] * len(keys), height=0.36, color="black",
             alpha=0.35, label="floor 0.15")
    for i, k in enumerate(keys):
        s = adj["separations"][k]
        ax2.text(max(vals[i], FLOOR_CORR) + 0.01, i,
                 f"{s['dominant_sign']} {cons[i]:.2f}", va="center",
                 fontsize=7)
    ax2.set_yticks(list(xs), keys)
    ax2.invert_yaxis()
    ax2.set_xlabel("mean |zeph - anneal| over in-window pairs")
    ax2.set_title(f"the separation — verdict {adj['verdict']}\n"
                  "(green = DECORRELATED; orange = sign+ residue; "
                  "gray = none)")
    ax2.legend(fontsize=8)
    ax2.grid(alpha=0.25, axis="x")

    # ---- panels 3-5: the three arms' correlation profiles -------------
    walk_plot = [v for k, v in walk.items() if k != "base"]
    for pi, key in enumerate(("r_g-12|g0", "r_g0|g+12", "r_g-12|g+12")):
        ax = fig.add_subplot(gs[1, pi])
        ok = key in PRIMARY
        ax.set_title(key + (" (ADJUDICATING)" if ok
                            else " (co-report)"), fontsize=9)
        xs_z = [p["zeph_read"] for p in in_window
                if p[key]["d"] is not None]
        ys_z = [p[key]["zeph"] for p in in_window
                if p[key]["d"] is not None]
        xs_a = [p["ann_read"] for p in in_window
                if p[key]["d"] is not None]
        ys_a = [p[key]["anneal"] for p in in_window
                if p[key]["d"] is not None]
        ax.plot(xs_z, ys_z, "o", color="tab:purple", ms=9,
                label="ZEPHYRA install path")
        ax.plot(xs_a, ys_a, "s", color="tab:red", ms=6, alpha=0.9,
                label="anneal (x45)")
        ax.plot([w["read"] for w in walk_plot],
                [observable(w, key) for w in walk_plot], ".", ms=5,
                color="tab:blue", alpha=0.6, label="cons walk (x45)")
        allv = [v for v in ys_z + ys_a
                + [observable(w, key) for w in walk_plot]
                if v is not None]
        if allv:
            lo, hi = min(allv), max(allv)
            pad = (hi - lo) * 0.15 + 1e-3
            ax.plot([lo - pad, hi + pad], [lo - pad, hi + pad], "k--",
                    lw=0.8, alpha=0.4)
        if ok:
            s = adj["separations"][key]
            ax.text(0.03, 0.03,
                    f"sign {s['dominant_sign']} {s['sign_consistency']:.2f}"
                    f" |d| {s['mean_abs_d']:.3f}",
                    transform=ax.transAxes, fontsize=8,
                    verticalalignment="bottom")
        ax.set_xlabel("the read", fontsize=7)
        ax.set_ylabel(key, fontsize=7)
        ax.tick_params(labelsize=6)
        ax.grid(alpha=0.25)
        if pi == 0:
            ax.legend(fontsize=6)

    # ---- panel 6: the re-certification drifts -------------------------
    ax6 = fig.add_subplot(gs[0, 2])
    gz = metrics["gates"]["G_INSTRUMENT_Z"]
    labels, vals_d = [], []
    for k, r in gz["vs_x42_battery_reads"].items():
        labels.append(f"x42:{k}")
