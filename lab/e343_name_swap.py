    base_flat64 = flat_params_cpu(net0).double().numpy()

    if int(state.get("step", 0)) >= INST_STEPS:
        log(f"  [install] resume ckpt already finished at "
            f"s{state['step']} — training skipped")
        return {"traj": state["traj"], "first_draws":
                state["first_draws"], "captured": state["captured"],
                "base_flat64": base_flat64}

    net = copy.deepcopy(net0).to(CPU)
    net.train()
    opt = torch.optim.AdamW(net.parameters(), lr=lr, betas=(0.9, 0.95),
                            weight_decay=0.1)
    gen = torch.Generator().manual_seed(FRESH_GEN)
    if resume_ck.exists():
        net.load_state_dict(state["model"])
        net.to(CPU)
        net.train()
        opt.load_state_dict(state["opt"])
        gen.set_state(state["gen_state"])

    n_inst, n_anc = p0["inst_x"].shape[0], p0["anchor_full"].shape[0]
    train_ids = p0["train_ids"]
    captured: dict = state["captured"]
    first_draws: list = state["first_draws"]
    step = state["step"]
    traj: list = state["traj"]
    t_slice = time.time()

    def save_resume() -> None:
        torch.save({"model": {k: v.detach().cpu().clone()
                              for k, v in net.state_dict().items()},
                    "opt": opt.state_dict(), "gen_state": gen.get_state(),
                    "step": state["step"], "traj": state["traj"],
                    "first_draws": state["first_draws"],
                    "captured": state["captured"]}, resume_ck)

    while step < INST_STEPS:
        step += 1
        f = cosine_lr(step - 1, INST_TOTAL)          # house schedule
        for g_ in opt.param_groups:
            g_["lr"] = lr * f
        ix = torch.randint(n_inst, (name_bs,), generator=gen)
        aj = torch.randint(n_anc, (corp_bs - mix_random,), generator=gen)
        rj = torch.randint(len(train_ids) - G1.BLOCK - 1, (mix_random,),
                           generator=gen)
        if step <= 3:
            first_draws.append({
                "step": step,
                "ix": [int(v) for v in ix],
                "aj": [int(v) for v in aj],
                "rj_head": [int(v) for v in rj[:8]],
            })
        corp = torch.cat([p0["anchor_full"][aj],
                          torch.stack([train_ids[s: s + G1.BLOCK]
                                       for s in rj])], 0)
        nw = p0["inst_x"][ix]
        x = torch.cat([nw[:, :-1], corp[:, :-1]], 0)
        y = torch.cat([nw[:, 1:], corp[:, 1:]], 0)
        msk = torch.zeros(name_bs + corp_bs, x.shape[1],
                          dtype=torch.bool)
        msk[:name_bs] = p0["inst_mask"][ix]
        logits, _ = net(x)
        nll = F.cross_entropy(logits.reshape(-1, logits.shape[-1]),
                              y.reshape(-1), reduction="none"
                              ).view(x.shape[0], x.shape[1])
        nm = nll[:name_bs][msk[:name_bs]]
        cm = nll[name_bs:]
        loss = (nm.sum() + cm.sum()) / (nm.numel() + cm.numel())
        opt.zero_grad(set_to_none=True)
        loss.backward()
        torch.nn.utils.clip_grad_norm_(net.parameters(), 1.0)
        opt.step()
        # ---- the per-step read (x42's exact form, on the twin) --------
        sd_cpu = {k: v.detach().clone() for k, v in net.state_dict().items()}
        evl.load_state_dict(sd_cpu)
        evl.eval()
        bz = G1.battery_cell(evl, p0["g0_ids"], p0["zid"])
        traj.append({"step": step, "g0_pz": bz["mean_pz"],
                     "ce_batch": float(loss.item())})
        if step in CAPTURE_STEPS and step not in captured:
            captured[step] = sd_cpu
            log(f"  [install] CAPTURED s{step} (read "
                f"{bz['mean_pz']:.6f})")
        if step % 25 == 0 or step == 1:
            log(f"  [install] s{step:4d} g0 {bz['mean_pz']:.6f} "
                f"CE {float(loss.item()):.4f}")
        state["step"] = step
        state["traj"] = traj
        state["first_draws"] = first_draws
        state["captured"] = captured
        if (time.time() - t_slice) > TRAIN_CAP_CPU:
            save_resume()
            log(f"  [install] slice cap ({TRAIN_CAP_CPU:.0f}s) at s{step} "
                "— resume saved, continuing (CPU park convention)")
            t_slice = time.time()
    save_resume()
    log(f"  [install] replay finished: {INST_STEPS} steps, "
        f"{len(captured)} captures")
    del net, opt
    return {"traj": traj, "first_draws": first_draws,
            "captured": captured, "base_flat64": base_flat64}


