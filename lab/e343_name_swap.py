def main() -> None:
    log(f"E343 — THE NAME-SWAP CROSS (smoke={SMOKE}) -> {RD}")
    metrics["birth_commit"] = git_head()
    write_partial("startup (bars + P-e343a registered, committed at "
                  "birth)")
    set_seed(34300)             # global init only; every RNG is its own
    assert torch.get_num_threads() == 4

    p0 = phase_P0()
    replay = phase_P1(p0)
    rows = phase_P2(p0, replay)
    phase_P3(p0, replay, rows)
    p4 = phase_P4(p0, rows)

    gates_pass = all(bool(g.get("pass")) for g in metrics["gates"].values())
    if not gates_pass:
        p4["adj"]["verdict"] = "TEXTURE"
    metrics["status"] = (
        "SMOKE: nothing adjudicated" if SMOKE else
        f"ADJUDICATED: {p4['adj']['verdict']}")
    make_png(p4, rows, p0)
    metrics["git_head_final"] = git_head()
    metrics["date_finished"] = common.now_iso()
    save_json(RD / "metrics.json", metrics)
    write_report(p4, rows, p0)
    log(f"DONE — verdict {p4['adj']['verdict']} (gates "
        f"{sum(1 for g in metrics['gates'].values() if g.get('pass'))}/"
        f"{len(metrics['gates'])})")


if __name__ == "__main__":
    main()
