    for k, c in gz["vs_x45_committed_rows"].items():
        for bn in ("g-12", "g0", "g+12"):
            labels.append(f"x45:{k[-4:]}:{bn}")
            vals_d.append(max(c[f"mean:{bn}"]["abs_diff"], 1e-18))
    gt = metrics["gates"]["G_INSTRUMENT_T"]["drifts"]
    for kk, r in gt.items():
        labels.append(f"FRESH:{kk}")
        vals_d.append(max(r["abs_diff"], 1e-18))
    ax6.barh(range(len(labels)), vals_d, color="tab:gray")
    ax6.axvline(READ_TOL, color="tab:red", lw=1.5,
                label="tol 2e-6")
    ax6.set_xscale("log")
    ax6.set_yticks(range(len(labels)), labels, fontsize=5)
    ax6.invert_yaxis()
    ax6.set_xlabel("|d| (log)", fontsize=7)
    ax6.set_title("the instrument re-certification drifts "
                  "(ZEPHYRA side + the FRESH row)", fontsize=9)
    ax6.legend(fontsize=7)
    ax6.grid(alpha=0.25, axis="x")

    fig.suptitle("E343 THE NAME-SWAP CROSS — the ZEPHYRA install path vs "
                 "the anneal at matched reads (the cons walk co-plotted); "
                 f"verdict {adj['verdict']}", fontsize=11)
    fig.tight_layout(rect=(0, 0, 1, 0.96))
    out = RD / "e343_name_swap.png"
    fig.savefig(out, dpi=140)
    plt.close(fig)
    log(f"[png] {out.name} written")


