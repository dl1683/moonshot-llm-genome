PRIMARY = ("r_g-12|g0", "r_g0|g+12")
COREPORT = ("r_g-12|g+12", "alive_g0", "write_norm", "in_room")


def score_separation(ds: list) -> dict:
    """x45's frozen separation rule, scoped: dominant sign, consistency,
    mean|d|; separates_decorrelated requires dominant '-' + 0.75 + 0.15."""
    n = len(ds)
    if n == 0:
        return {"n": 0, "dominant_sign": None,
                "sign_consistency": 0.0, "mean_abs_d": 0.0,
                "separates_any": False, "separates_decorrelated": False}
    n_pos = sum(1 for d in ds if d > 0)
    n_neg = sum(1 for d in ds if d < 0)
    dominant = "+" if n_pos >= n_neg else "-"
    sign = max(n_pos, n_neg) / n
    mean_abs_d = sum(abs(d) for d in ds) / n
    sep_any = bool(sign >= SIGN_FRAC and mean_abs_d >= FLOOR_CORR)
    return {"n": n, "dominant_sign": dominant,
            "sign_consistency": round(sign, 4),
            "mean_abs_d": round(mean_abs_d, 6),
            "separates_any": sep_any,
            "separates_decorrelated": bool(sep_any and dominant == "-")}


def observable(row: dict, key: str):
    if key.startswith("alive_"):
        return row["alive"][key[len("alive_"):]]
    if key.startswith("r_"):
        return row["corrs"][key[2:]]
    return row.get(key)


def phase_P4(p0: dict, rows: dict) -> dict:
    log("P4 — THE MATCH (nearest-read pairing vs x45's anneal rows) + "
        "the separation + the adjudication")

    # ---- the arms (the ZEPHYRA path only; base + the TAVIREN subject
    # are floor/certification rows, never arm members) --------------------
    zeph_rows = [{"tag": v["tag"], "step": v["step"], "read": v["read"],
                  "row": v} for k, v in rows.items()
                  if k.startswith("zeph_")]
    ann_rows = [{"tag": v["tag"], "step": v["step"], "read": v["read"],
                 "row": v} for v in
                p0["committed_x45"]["anneal_panels"].values()]

    # ---- the nearest-read pairing (x45's frozen rule) ------------------
    pairs, out_of_window = [], []
    for zr in zeph_rows:
        best = min(ann_rows, key=lambda a: abs(a["read"] - zr["read"]))
        d_read = abs(best["read"] - zr["read"])
        pair = {"zeph_tag": zr["tag"], "zeph_step": zr["step"],
                "zeph_read": zr["read"],
                "zeph_provenance": zr["row"]["provenance"],
                "ann_tag": best["tag"], "ann_step": best["step"],
                "ann_read": best["read"],
                "ann_provenance": best["row"]["provenance"],
                "abs_d_read": d_read,
                "in_window": bool(d_read <= MATCH_WINDOW)}
        for key in PRIMARY + COREPORT:
            zv = observable(zr["row"], key)
            av = observable(best["row"], key)
            pair[key] = {"zeph": zv, "anneal": av,
                         "d": (None if zv is None or av is None
                               else zv - av)}
        (pairs if pair["in_window"] else out_of_window).append(pair)

    read_span = {
        "zeph_reads": [round(z["read"], 6) for z in zeph_rows],
        "ann_read_min": round(min(a["read"] for a in ann_rows), 6),
        "ann_read_max": round(max(a["read"] for a in ann_rows), 6),
        "window": MATCH_WINDOW,
        "note": ("the window disclosure: x45's committed anneal panel "
                 "series spans 0.286-0.803 on p(T); the ZEPHYRA path "
                 "spans ~1.5e-5 (s1) to ~0.754 (s200) on p(Z) — the low "
                 "rungs (s1, s8 ~0.022, s9 ~0.114) sit BELOW the anneal's "
                 "floor and are expected out-of-window"),
    }

    # ---- the separation scoring (the frozen rule) ---------------------
    in_window = [p for p in pairs if p["in_window"]]
    separations = {}
    for key in PRIMARY + COREPORT:
        ds = [p[key]["d"] for p in in_window if p[key]["d"] is not None]
        n_none = sum(1 for p in in_window if p[key]["d"] is None)
        separations[key] = dict(score_separation(ds),
                                n_none=n_none)
        s = separations[key]
        log(f"  [sep] {key:12s} n {s['n']:2d} sign {s['dominant_sign']} "
            f"{s['sign_consistency']:.2f} mean|d| {s['mean_abs_d']:.4f} "
            f"floor {FLOOR_CORR} -> "
            f"{'DECORRELATED' if s['separates_decorrelated'] else 'no'}")

    # the disclosed sub-scorings (never alone adjudicating)
    subsets = {}
    if not SMOKE:
        strict = [p for p in in_window
                  if p["zeph_step"] is not None and p["zeph_step"] <= 12]
        upper = [p for p in in_window
                 if p["zeph_step"] is not None and p["zeph_step"] >= 100]
        for name, sub in (("strict_interior_x42_rungs_le_s12", strict),
                          ("upper_segment_s100_plus", upper)):
            subsets[name] = {key: score_separation(
                [p[key]["d"] for p in sub if p[key]["d"] is not None])
                for key in PRIMARY}

    # the walk arm's committed separation (the reference fingerprint)
    walk_sep = {key: p0["committed_x45"]["separations"][key]
                for key in PRIMARY}

    # ---- the verdict (the frozen composite) ---------------------------
    hard_ok = all(bool(g.get("pass")) for g in metrics["gates"].values())
    if not hard_ok:
        verdict = "TEXTURE"
        clause = ("hard-gate failure: "
                  + ", ".join(k for k, g in metrics["gates"].items()
                              if not g.get("pass"))
                  + " — nothing adjudicated; tables verbatim")
    elif SMOKE:
        verdict, clause = "SMOKE", "nothing adjudicated (smoke stamp)"
    elif not in_window:
        verdict, clause = "TEXTURE", (
            "no in-window matched pairs — the match window admits "
            "nothing; the match table is the report")
    else:
        sep_dec = [k for k in PRIMARY
                   if separations[k]["separates_decorrelated"]]
        coherent_above = [k for k in PRIMARY
                          if separations[k]["separates_any"]
                          and separations[k]["dominant_sign"] == "+"]
        if sep_dec:
            verdict = "FINGERPRINT-HOLDS"
            clause = ("at matched reads the ZEPHYRA install path ALSO "
                      "shows the decorrelated families below the anneal: "
                      + ", ".join(
                          f"{k} (sign -, consistency "
                          f"{separations[k]['sign_consistency']:.2f}, "
                          f"mean|d| {separations[k]['mean_abs_d']:.4f} >= "
                          f"floor {FLOOR_CORR})"
                          for k in sep_dec)
                      + f" over {len(in_window)} in-window pairs — THE "
                        "SIGNATURE IS THE PATH'S: formation through the "
                        "install curriculum builds independent response "
                        "families regardless of name; the target list is "
                        "real; the era's hunt continues on solid ground")
        else:
            verdict = "FINGERPRINT-VANISHES"
            clause = ("neither primary profile separates DECORRELATED at "
                      f"matched reads ({len(in_window)} in-window pairs: "
                      + "; ".join(
                          f"{k} sign {separations[k]['dominant_sign']} "
                          f"{separations[k]['sign_consistency']:.2f}, "
                          f"mean|d| {separations[k]['mean_abs_d']:.4f}"
                          for k in PRIMARY)
                      + ") — the ZEPHYRA path does not show the "
                        "decorrelated-families signature below the "
                        "anneal; per the frozen bar THE SIGNATURE WAS THE "
                        "NAME INSTRUMENT'S (the decorrelation is a "
                        "TAVIREN-slot artifact; the fingerprint retracts; "
                        "x45's clause re-words)"
                      + ("; the COHERENT-ABOVE residue: "
                         + ", ".join(coherent_above)
                         + " separates with dominant sign + (the ZEPHYRA "
                           "path ABOVE the anneal — still not the "
                           "fingerprint)" if coherent_above else "")
                      + "; the registered mechanism ledger (P-e343a): the "
                        "name-instrument clause and the path-age reading "
                        "both remain live — the full-swap is the closer")

    adj = {
        "bars_verbatim": REGISTERED["bars_verbatim"],
        "read_span": read_span,
        "n_zeph_rows": len(zeph_rows), "n_ann_rows": len(ann_rows),
        "n_pairs": len(pairs), "n_in_window": len(in_window),
        "n_out_of_window": len(out_of_window),
        "out_of_window": [{"zeph_tag": p["zeph_tag"],
                           "zeph_read": p["zeph_read"],
                           "nearest_ann_read": p["ann_read"],
                           "abs_d_read": p["abs_d_read"]}
                          for p in out_of_window],
        "separations": separations,
        "subsets_disclosed": subsets,
        "walk_arm_committed_separation": walk_sep,
        "P-e343a": {"guess": REGISTERED["P-e343a"]["my_guess"],
                    "hit": bool(verdict == "FINGERPRINT-VANISHES"),
                    "scored": REGISTERED["P-e343a"]["scored"]},
        "verdict": verdict, "clause": clause,
        "composite_order": ("TEXTURE (hard gates) -> FINGERPRINT-HOLDS "
                            "(>= 1 primary profile separates DECORRELATED: "
                            "sign - + consistency >= 0.75 + mean|d| >= "
                            "0.15) -> FINGERPRINT-VANISHES (neither; a "
                            "sign+ separation named the COHERENT-ABOVE "
                            "residue)"),
    }
    metrics["adjudication"] = adj
    metrics["match"] = {"pairs": pairs}
    write_partial("P4 the match + adjudication done")
    log(f"P4: verdict {verdict} ({len(in_window)} in-window / "
        f"{len(out_of_window)} out)")
    return {"pairs": pairs, "adj": adj, "zeph_rows": zeph_rows,
            "ann_rows": ann_rows}


