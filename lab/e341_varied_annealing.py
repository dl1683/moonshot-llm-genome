# P3c — THE POOLS (the varied pool + the fixed control pool)
# ======================================================================
def phase_P3c(p0: dict) -> dict:
    log("P3c — THE POOLS (the cons's jittered install pool VERBATIM + the "
        f"fixed j={FIXED_J} control pool)")
    train_ids, corpus = p0["train_ids"], p0["corpus"]
    install_occ = p0["install_occ"]
    name_ids_t = corpus.encode("TAVIREN")
    assert len(name_ids_t) == 7, "TAVIREN must be 7 ids (the ZEPHYRA slot)"

    # the jittered install pool — g1's construction VERBATIM (lines quoted
    # + gated in G_CONSQUOTES), with the TAVIREN name
    jit_x, jit_mask = {}, {}
    for j in JITTERS:
        jwins = []
        for p, h in install_occ:
            pre = train_ids[p - G1.PRE - j: p]
            post = train_ids[p + len(h): p + len(h) + G1.POST_CAP - j]
            w = torch.cat([pre, name_ids_t, post])
            if len(w) != G1.BLOCK:
                raise RuntimeError(f"jit window len {len(w)} != "
                                   f"{G1.BLOCK} at j={j}")
            jwins.append(w)
        jit_x[j] = torch.stack(jwins)
        m = torch.zeros(len(jwins), G1.BLOCK - 1, dtype=torch.bool)
        m[:, G1.PRE - 1 + j: G1.PRE - 1 + j + len(name_ids_t)] = True
        jit_mask[j] = m
    pool_v_x = torch.cat([jit_x[j] for j in JITTERS])        # (300, 256)
    pool_v_mask = torch.cat([jit_mask[j] for j in JITTERS])

    # the fixed control pool: the j=0 block ALONE (the install's own
    # fixed contexts — the controller's own convention)
    pool_f_x = jit_x[FIXED_J]                                # (60, 256)
    pool_f_mask = jit_mask[FIXED_J]

    # the install windows rebuilt independently (the bit-check's oracle)
    def build_win(p, host):
        return torch.cat([train_ids[p - G1.PRE: p], name_ids_t,
                          train_ids[p + len(host):
                                    p + len(host) + G1.POST_CAP]])

    win_t = torch.stack([build_win(p, h) for p, h in install_occ])

    cons_anchor = p0["anchor_full"][:16]      # e113: first-16 originals

    # ---- G_POOLV: the varied pool -------------------------------------
    name_ok_v = all(
        torch.equal(pool_v_x[(bi * 60) + wi][G1.PRE + j:
                                            G1.PRE + j + 7], name_ids_t)
        for bi, j in enumerate(JITTERS) for wi in range(60))
    mask_ok_v = bool(int(pool_v_mask.sum()) == 300 * 7)
    g_poolv = {
        "shape": list(pool_v_x.shape), "jitters": list(JITTERS),
        "per_jitter": {str(j): [60, G1.BLOCK] for j in JITTERS},
        "name_in_place_every_window": bool(name_ok_v),
        "mask_positions": int(pool_v_mask.sum()), "expected": 300 * 7,
        "j0_block_bit_equal_fixed": bool(jit_x[0].equal(pool_f_x)),
        "claim": ("the varied pool == the cons's own construction: 5 "
                  "registered jitters x the 60 install contexts, the "
                  "TAVIREN name at column PRE+j in every window, the "
                  "name-mask at the loss positions"),
        "pass": bool(list(pool_v_x.shape) == [300, G1.BLOCK] and name_ok_v
                     and mask_ok_v and jit_x[0].equal(pool_f_x))}
    assert g_poolv["pass"], f"G_POOLV FAILED: {g_poolv}"

    # ---- G_POOLF: the fixed control pool ------------------------------
    name_ok_f = all(torch.equal(w[G1.PRE: G1.PRE + 7], name_ids_t)
                    for w in pool_f_x)
    mask_ok_f = bool(int(pool_f_mask.sum()) == 60 * 7)
    g_poolf = {
        "shape": list(pool_f_x.shape), "jitter": FIXED_J,
        "bit_equal_install_windows": bool(pool_f_x.equal(win_t)),
        "name_in_place_every_window": bool(name_ok_f),
        "mask_positions": int(pool_f_mask.sum()), "expected": 60 * 7,
        "claim": ("the fixed pool == the j=0 block ALONE == the install's "
                  "own 60 windows bit-exact (the controller's fixed-"
                  "context convention); matched 16-window draws/step with "
                  "the varied arm"),
        "pass": bool(list(pool_f_x.shape) == [60, G1.BLOCK] and name_ok_f
                     and mask_ok_f and pool_f_x.equal(win_t))}
    assert g_poolf["pass"], f"G_POOLF FAILED: {g_poolf}"

    metrics["gates"].update({"G_POOLV": g_poolv, "G_POOLF": g_poolf})
    log(f"G_POOLV PASS: varied pool {pool_v_x.shape} (jitters "
        f"{list(JITTERS)}; name in place; masks {int(pool_v_mask.sum())})")
    log(f"G_POOLF PASS: fixed pool {pool_f_x.shape} == the j=0 block == "
        f"the install windows bit-exact (the matched-amount control)")
    write_partial("P3c the pools built + gated")
    return {"pool_v_x": pool_v_x, "pool_v_mask": pool_v_mask,
            "pool_f_x": pool_f_x, "pool_f_mask": pool_f_mask,
            "cons_anchor": cons_anchor, "win_t": win_t}


