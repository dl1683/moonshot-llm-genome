def phase_P7(washes: dict, classes: dict) -> dict:
    tags = list(washes.keys())
    # G_DRAWS + G_INPUTS: bit-identical across ALL the washes
    ref_draws = washes[tags[0]]["draws"]
    ref_x = washes[tags[0]]["xhash"]
    g_draws = {"n_steps": len(ref_draws),
               "bit_identical": all(w["draws"] == ref_draws
                                    for w in washes.values()),
               "claim": f"all {len(tags)} washes consumed the IDENTICAL "
                        f"aj/rj sequence (e322's seed 10902)",
               "pass": bool(all(w["draws"] == ref_draws
                                for w in washes.values())
                            and len(ref_draws) == E38.WASH_STEPS)}
    g_inputs = {"n_steps": len(ref_x),
                "bit_identical": all(w["xhash"] == ref_x
                                     for w in washes.values()),
                "claim": "all the washes' input batches bit-identical "
                         "(per-step x md5; g1's G-INPUTS convention)",
                "pass": bool(all(w["xhash"] == ref_x
                                 for w in washes.values())
                             and len(ref_x) == E38.WASH_STEPS)}
    assert g_draws["pass"], f"G_DRAWS FAILED: {g_draws}"
    assert g_inputs["pass"], f"G_INPUTS FAILED: {g_inputs}"

