def main() -> None:
    log(f"E341 — THE VARIED-CONTEXT ANNEALING (smoke={SMOKE}) -> {RD}")
    metrics["birth_commit"] = BIRTH_COMMIT_PINNED
    write_partial("startup (bars registered, committed at birth)")
    set_seed(34101)              # global init only; every RNG is its own

    # ---- the harness's own phases (verbatim by import) ------------------
    p0 = E38.phase_P0()                        # the protocol rebuild
    p1 = E38.phase_P1(p0)                      # the subject (e311's)
    theta0 = p1["theta0"]
    phase_P2c()                                # the cons port gates
    pools = phase_P3c(p0)                      # the two pools

    # ---- the annealings (sequential; GPU single-lane) -------------------
    log("=" * 78)
    log("PHASE A — THE ANNEALINGS (the cons's e113 protocol on the fresh "
        "TAVIREN install)")
    anneal_v = anneal_arm("VARIED", theta0, pools["pool_v_x"],
                          pools["pool_v_mask"], pools["cons_anchor"], p0,
                          RD / "anneal_VARIED_resume.pt")
    if torch.cuda.is_available():
        E38.E261.burst_cooldown("between-annealings")
    anneal_f = anneal_arm("FIXED", theta0, pools["pool_f_x"],
                          pools["pool_f_mask"], pools["cons_anchor"], p0,
                          RD / "anneal_FIXED_resume.pt")
    anneal_v["pool_n"] = int(pools["pool_v_x"].shape[0])
    anneal_f["pool_n"] = int(pools["pool_f_x"].shape[0])

    # ---- the t0 reads + the expression-lottery check ---------------------
    deviations_live: list[str] = []
    t0_reads = {}
    for tag, sd in (("VARIED", anneal_v["sd"]), ("FIXED", anneal_f["sd"])):
        net = G1.evl_load(sd)
        net.eval()
        rd = G1.battery_cell(net, p0["g0_ids"], p0["tid"])["mean_pz"]
        rd12 = G1.battery_cell(net, p0["gm12_ids"], p0["tid"])["mean_pz"]
        ce = G1.ce_fixed_cpu(net, *p0["r_eval_xy"])
        del net
        t0_reads[tag] = {"g0": rd, "gm12": rd12, "ce_r": ce}
        traj_end = anneal_v["traj"][-1] if tag == "VARIED" else \
            anneal_f["traj"][-1]
        ok = (abs(rd - traj_end["read_g0_pT"]) <= 2e-6)
        assert ok, f"{tag} final-read repro FAILED: {rd} vs " \
                   f"{traj_end['read_g0_pT']}"
        if rd < T0_EXPRESS_FLOOR:
            deviations_live.append(
                f"the {tag} annealed t0 {rd:.4f} < the {T0_EXPRESS_FLOOR} "
                f"expression floor (the lottery owned the expression "
                f"channel; the arm ran anyway — the g1d precedent)")
        log(f"[{tag}] annealed t0: p(T)@g0 {rd:.6f} | gm12 {rd12:.4f} | "
            f"CE_R {ce:.4f}"
            + ("  <-- UNDER the expression floor" if rd <
               T0_EXPRESS_FLOOR else ""))
    metrics["annealed_t0"] = t0_reads
    write_partial("the annealings complete")

    # ---- the bands + the classes -----------------------------------------
    p3 = E38.phase_P3()
    classes = phase_classes(p3)

    # ---- the commits (the primary legs' event) ---------------------------
    log("=" * 78)
    log("PHASE B — THE COMMITS (the harness's own firing, per arm)")
    net0_v = fire_commit(anneal_v["sd"], "VARIED")
    net0_f = fire_commit(anneal_f["sd"], "FIXED")
    net0_t = fire_commit(theta0, "TWIN")
    bare_v = G1.evl_load(anneal_v["sd"])       # the secondary bare legs
    bare_f = G1.evl_load(anneal_f["sd"])

    # ---- the washes (five legs; bit-identical draws) ----------------------
    log("=" * 78)
    log("PHASE C — THE WASHES (e322's 100-step unbiased wash, seed 10902; "
        "all five legs on the identical draw sequence)")
    washes = {}
    legs = (("VARIED-COMMIT", net0_v, True), ("FIXED-COMMIT", net0_f, True),
            ("TWIN-COMMIT", net0_t, True), ("VARIED-BARE", bare_v, False),
            ("FIXED-BARE", bare_f, False))
    for i, (tag, net0, armed) in enumerate(legs):
        if i and torch.cuda.is_available():
            E38.E261.burst_cooldown(f"between-{tag}")
        washes[tag] = E38.wash_arm(tag, net0,
                                   RD / f"wash_{tag}_resume.pt", p0,
                                   armed=armed)
        del net0
    summaries = {tag: arm_wash_summary(w) for tag, w in washes.items()}
    metrics["washes"] = {k: {kk: vv for kk, vv in s.items() if kk != "traj"}
                         for k, s in summaries.items()}

    # ---- the match gates + the adjudication -------------------------------
    p7 = phase_P7(washes, classes)
    adj = adjudicate_e341(summaries["VARIED-COMMIT"],
                          summaries["FIXED-COMMIT"],
                          summaries["TWIN-COMMIT"],
                          summaries["VARIED-BARE"],
                          summaries["FIXED-BARE"],
                          classes, deviations_live)
    metrics["adjudication"] = adj
    metrics["thermal"] = {"max_temp": (max((r["temp"] for r in thermal_log),
                                           default=None)),
                          "polls": len(thermal_log),
                          "device_events": device_events}
    metrics["status"] = ("DONE (smoke; nothing adjudicated)" if SMOKE
                         else f"DONE: {adj['verdict']}")
    metrics["git_head_final"] = git_head()
    metrics["completed_utc"] = utcnow()
    save_json(RD / "metrics.json", metrics)

    make_png(adj, classes, anneal_v, anneal_f)
    write_report(adj, classes, anneal_v, anneal_f, p7)
    log(f"E341 VERDICT: {adj['verdict']}")


if __name__ == "__main__":
    main()
