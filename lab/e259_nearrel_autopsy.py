# ------------------------------------------------------------------ helpers

def softmax_p(L: np.ndarray, ans: np.ndarray, factor: float) -> np.ndarray:
    """float64 answer-probabilities under factor * L (e252's cooled read)."""
    Lc = L.astype(np.float64) * factor
    z = Lc - Lc.max(axis=1, keepdims=True)
    P = np.exp(z)
    P /= P.sum(axis=1, keepdims=True)
    return P[np.arange(len(ans)), ans]


def br_of(p_cooled: np.ndarray, p_raw: np.ndarray, p_t0: np.ndarray):
    """e252's BR on means; None-guarded if the denominator vanishes."""
    den = p_t0.mean() - p_raw.mean()
    return None if den == 0 else float((p_cooled.mean() - p_raw.mean()) / den)


def mrf_of(L: np.ndarray, ans: np.ndarray, factor: float,
           mr_t0: float) -> float | None:
    """e252's MRF convention: raw-margin revival fraction.

    margin_raw(factor*L) / factor = the state's own raw margin (exact: a
    positive scaling preserves the top-2 identity); the fraction of the t0
    margin gap closed by cooling.
    """
    rd = e252.cooled_read(L.astype(np.float64), ans, factor)
    mr_cooled = rd["mean_margin_raw"]
    mr_state = mr_cooled / factor
    den = mr_t0 - mr_state
    return None if den == 0 else float((mr_cooled - mr_state) / den)


def rho_of(p_read, p_t0):
    return e252.spearman(list(p_read), list(p_t0))[0]


def rf_of(rho_c, rho_r):
    """e252's guarded RF (undefined when the raw order never left t0)."""
    if rho_r is None or rho_r >= 1.0:
        return None
    return (rho_c - rho_r) / (1.0 - rho_r)


