FACT_COLORS = ["tab:green", "tab:blue", "tab:orange", "tab:red",
               "tab:purple"]


def make_multifact_plot(rd, metrics, verdict, clause, thermal_log,
                        budget_norm, baselines):
    """THE CELL'S HEADLINE FIGURE: the five survival curves vs the twin
    vs e288's cited curve + the bars; the controller traces; the budget
    split (the contention ledger); the contention windows (the funnel
    imaged); the corpus CE + lr; the thermal envelope + the paraphrase
    bars."""
    fig, axes = plt.subplots(2, 3, figsize=(19.5, 10.6))
    fiv = metrics["arms"][FIV_ARM]["phase"]
    twn = metrics["arms"][TWN_ARM]["phase"]
    adj = metrics["adjudication"]["reads"]

    # (0,0) THE FIVE SURVIVAL CURVES (+ the twin's fact-1 + e288 cited)
    ax = axes[0, 0]
    for i in range(N_ROOMS):
        fact = f"FACT{i + 1}"
        steps = [t["step"] for t in fiv["traj"]]
        vals = [max(t["panel_g0"][fact] / baselines[fact], 1e-7)
                for t in fiv["traj"]]
        ax.plot(steps, vals, "o-", lw=1.9, ms=4.5,
                color=FACT_COLORS[i], label=f"{fact}={NAME_BANK[i]} (five-distinct)")
    tt = [t["step"] for t in twn["traj"]]
    ax.plot(tt, [max(t["panel_g0"][FACT1] / baselines[FACT1], 1e-7)
                 for t in twn["traj"]], "s--", lw=2.2, ms=5,
            color="black", label=f"{FACT1}={NAME_BANK[0]} on the TWIN (alone, e288 form)")
    e288_steps = sorted(int(k) for k in E288_TRAJ_G0.keys())
    ax.plot(e288_steps,
            [max(E288_TRAJ_G0[k] / E264_K10K_POST_G0, 1e-7)
             for k in e288_steps], "^:", lw=1.5, ms=6, color="tab:gray",
            alpha=0.9, label=f"e288's committed curve (CITED; x"
                             f"{E288_RATIO:.3f})")
    ax.axhline(SURVIVE_FRAC, color="crimson", ls="--", lw=1.4,
               label=f"the {SURVIVE_FRAC:.0%}x HOLD bar")
    ax.set_yscale("log")
    ax.set_xlabel("corpus step t (maintenance every "
                  f"{MAINT_EVERY}; reads POST-maintenance)")
    ax.set_ylabel("fact read / its own loaded baseline (log)")
    ax.set_title("THE FIVE DISTINCT FAMILIES' SURVIVAL — five "
                 "controllers vs the isolation twin vs e288's single-"
                 "fact win", fontsize=9.0)
    ax.legend(fontsize=6.2)
    ax.grid(alpha=0.25, which="both")

    # (0,1) THE CONTROLLER TRACES (deficit + dose per controller) -------
    ax = axes[0, 1]
    ml = fiv["maint_ledger"]
    for i in range(N_ROOMS):
        fact = f"FACT{i + 1}"
        rows = [m for m in ml if m["fact"] == fact]
        if rows:
            ax.plot([m["step"] for m in rows], [m["deficit_t"] for m in rows],
                    "o-", lw=1.2, ms=3.2, color=FACT_COLORS[i],
                    alpha=0.85, label=f"{fact} deficit")
            ax.plot([m["step"] for m in rows],
                    [m["lr_maint"] / lr_m_max_5_plot for m in rows],
                    "^--", lw=0.9, ms=2.8, color=FACT_COLORS[i],
                    alpha=0.55, label=f"{fact} lr/LR_MAX")
    mt = twn["maint_ledger"]
    ax.plot([m["step"] for m in mt], [m["lr_maint"] / LR_M_MAX_E288
                                      for m in mt], "k:s", lw=1.6, ms=4,
            label="TWIN fact1 lr/LR_MAX (e288's)")
    ax.axhline(1.0, color="black", ls=":", lw=0.9)
    ax.set_ylim(-0.05, 1.25)
    ax.set_xlabel(f"corpus step t (one instant every {MAINT_EVERY})")
    ax.set_ylabel("deficit | lr / ceiling")
    ax.set_title("THE FIVE DISTINCT CONTROLLERS' TRACES (the dose "
                 "tracks each family's own deficit)", fontsize=9.0)
    ax.legend(fontsize=5.4, ncol=2)
    ax.grid(alpha=0.25)

    # (0,2) THE BUDGET SPLIT (the contention ledger) ---------------------
    ax = axes[0, 2]
    bl = fiv["budget_ledger"]
    if bl:
        ax.plot([b["step"] for b in bl], [b["S_corpus"] for b in bl], "o-",
                lw=1.7, ms=4, color="tab:cyan", label="S_corpus (B_C pool)")
        ax.plot([b["step"] for b in bl], [b["S_maint_all"] for b in bl],
                "^-", lw=1.9, ms=4.5, color="tab:orange",
                label="S_maint ALL (the SHARED B_M pool)")
        ax.plot([b["step"] for b in bl], [b["S_total"] for b in bl], "s-",
                lw=1.5, ms=3.5, color="tab:green", label="S_total (five)")
        tl = twn["budget_ledger"]
        ax.plot([b["step"] for b in tl],
                [b["S_corpus"] + b["S_maint_all"] for b in tl], "v--",
                lw=1.1, ms=3.2, color="black", alpha=0.7,
                label="the twin's S_total")
    ax.axhline(budget_norm, color="crimson", ls="--", lw=1.5,
               label=f"THE SHARED BUDGET {budget_norm:.3f} (= e288's)")
    ax.set_xlabel("corpus step t (milestone)")
    ax.set_ylabel("cumulative displacement (L2)")
    ax.set_title("THE CONTENTION LEDGER — one budget, five controllers "
                 "(e288's total)", fontsize=9.0)
    ax.legend(fontsize=6.2)
    ax.grid(alpha=0.25)

    # (1,0) THE CONTENTION WINDOWS (the funnel imaged) --------------------
    ax = axes[1, 0]
    got_labels = False
    for wl, wname, ls in ((WIN1[1], "win1", "-"), (WIN2[1], "win2", "--")):
        rows = [w for w in fiv["window_ledger"]
                if w["step"] == wl and w["window_phase"].startswith(wname)]
        order = ([w for w in rows if "pre" in w["window_phase"]]
                 + [w for w in rows if "-after-" in w["window_phase"]]
                 + [w for w in rows if "post" in w["window_phase"]
                    and "-after-" not in w["window_phase"]])
        if not order:
            continue
        xs = list(range(len(order)))
        labels = [w["window_phase"].split(":")[-1].replace(
            f"t{wl}-", "") for w in order]
        for i in range(N_ROOMS):
            fact = f"FACT{i + 1}"
            ax.plot(xs, [max(w["panel_g0"][fact] / baselines[fact], 1e-7)
                         for w in order], "o" + ls, lw=1.5, ms=4,
                    color=FACT_COLORS[i],
                    label=(fact if (wname == "win1" and not got_labels)
                           else None))
        got_labels = True
        ax.set_xticks(xs)
        ax.set_xticklabels(labels, fontsize=5.8, rotation=45)
    ax.set_yscale("log")
    ax.set_ylabel("fact read / baseline (log)")
    ax.set_title(f"THE CONTENTION WINDOWS — cross-family knocks? the "
                 f"panel after EACH controller's event (solid: "
                 f"t{WIN1[1]}; dashed: t{WIN2[1]})", fontsize=8.8)
    ax.legend(fontsize=6.4)
    ax.grid(alpha=0.25, which="both")

    # (1,1) THE FUNNEL + THE CORPUS CE ------------------------------------
    ax = axes[1, 1]
    static_probe = fiv["funnel"].get("static_probe")
    if static_probe:
        cm = np.array(static_probe["cos_matrix"])
        im = ax.imshow(cm, vmin=-1, vmax=1, cmap="RdBu_r")
        for a in range(cm.shape[0]):
            for b in range(cm.shape[1]):
                ax.text(b, a, f"{cm[a, b]:.2f}", ha="center", va="center",
                        fontsize=6.6,
                        color=("white" if abs(cm[a, b]) > 0.6 else "black"))
        ax.set_xticks(range(N_ROOMS))
        ax.set_xticklabels([f"F{i + 1}" for i in range(N_ROOMS)])
        ax.set_yticks(range(N_ROOMS))
        ax.set_yticklabels([f"F{i + 1}" for i in range(N_ROOMS)])
        plt.colorbar(im, ax=ax, fraction=0.046)
        ax.set_title(f"THE DISTINCTNESS MATRIX — t{static_probe['step']} "
                     f"static probe (offdiag mean "
                     f"{static_probe['offdiag_mean']:+.3f}; e291's same-"
                     f"name band 0.83-0.95)", fontsize=8.6)
    else:
        for a, col, mk in ((FIV_ARM, "tab:green", "o"),
                           (TWN_ARM, "black", "s")):
            cl = metrics["arms"][a]["phase"]["corpus_ledger"]
            steps = sorted(int(k) for k in cl.keys())

            def _ce(k):
                return cl[str(k)]["ce"] if str(k) in cl else cl[k]["ce"]
            ax.plot(steps, [_ce(k) for k in steps], mk + "-", lw=1.2,
                    ms=3, color=col, label=f"{a} corpus CE")
        ax.legend(fontsize=7)

    # (1,2) THE PARAPHRASE BARS + THE THERMAL ENVELOPE ---------------------
    ax = axes[1, 2]
    rider = adj["the_paraphrase_rider"]
    xs = np.arange(3)
    w = 0.35
    ax.bar(xs - w / 2,
           [adj[FIV_ARM]["ratios_vs_baseline"][FACT1],
            rider["five"]["paraphrase_ratio_vs_t0"] or 0,
            rider["five"]["rider_ratio"] or 0], w, color="tab:green",
           label=f"{FIV_ARM} family A")
    ax.bar(xs + w / 2,
           [adj[TWN_ARM]["fact1_ratio"],
            rider["twin"]["paraphrase_ratio_vs_t0"] or 0,
            rider["twin"]["rider_ratio"] or 0], w, color="black",
           label="TWIN family A")
    ax.axhline(1.0, color="gray", ls=":", lw=1.0)
    ax.axhline(TUMOR_RATIO_BAR, color="crimson", ls="--", lw=1.1,
               label=f"the TUMOR bar ({TUMOR_RATIO_BAR:.0f}x)")
    ax.set_xticks(xs)
    ax.set_xticklabels(["literal / baseline", "paraphrase / t0",
                        "rider ratio"], fontsize=7.5)
    ax.set_yscale("log")
    ax.set_title(f"THE PARAPHRASE RIDER @t400 — five {rider['five']['verdict']}"
                 f" / twin {rider['twin']['verdict']}", fontsize=8.6)
    ax.legend(fontsize=6.6)
    ax.grid(alpha=0.25, which="both")
    if thermal_log:
        ax2 = ax.twinx()
