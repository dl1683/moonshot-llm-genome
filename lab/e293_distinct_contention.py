            loss = (nm.sum() + cm.sum()) / (nm.numel() + cm.numel())
            opt.zero_grad(set_to_none=True)
            loss.backward()
            torch.nn.utils.clip_grad_norm_(net.parameters(), 1.0)
            # ---- THE HOOK (the room projection; e261's form) -----------
            g64 = torch.cat([p.grad.detach().reshape(-1)
                             for p in net.parameters()]) \
                .to(CPU).double().numpy().astype(np.float64)
            gn2 = float(g64 @ g64)
            gp = rooms.project_masked(g64, mask_np)
            gpn2 = float(gp @ gp)
            gp32 = torch.from_numpy(gp.astype(np.float32))
            with torch.no_grad():
                for p, (a, b), shp in zip(net.parameters(), rooms.offsets,
                                          rooms.shapes):
                    p.grad.copy_(gp32[a:b].to(dev).reshape(shp))
            led = {"gn": math.sqrt(gn2), "gpn": math.sqrt(gpn2),
                   "kept_frac": (math.sqrt(gpn2 / gn2) if gn2 > 0 else 0.0)}
            opt.step()
