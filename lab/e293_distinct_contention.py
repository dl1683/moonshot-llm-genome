    fig.suptitle(f"E293 — THE DISTINCT-NAME CONTENTION CELL (five "
                 f"DIFFERENT name families, five controllers, ONE "
                 f"five controllers, ONE shared budget = e288's total) -> "
                 f"{verdict}", fontsize=11)
