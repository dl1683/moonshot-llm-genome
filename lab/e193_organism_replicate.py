def plot_ladder(path, ladder_state, arm_out, ratio, f1_anchor, root_cells,
                verdict_front, clause_front, rms_den, g_kill):
    """The second-organism density ladder + the ratio replicate vs
    organism-1's committed rungs."""
    import textwrap
    fig = plt.figure(figsize=(22, 8.8))
    gs = fig.add_gridspec(1, 3, width_ratios=[1.2, 1.1, 1.0])

    ax = fig.add_subplot(gs[0, 0])
    colors = {"a_topk1": "tab:red", "a_topk10": "tab:blue",
              "a_topk50": "tab:cyan", "a_raw": "black", "a_sign":
              "darkorange"}
    labels = {"a_topk1": "TOPK-1% (the licensed new rung)",
              "a_topk10": "TOPK-10%", "a_topk50": "TOPK-50%",
              "a_raw": "RAW-G (opt1c's arm)", "a_sign": "SIGN (full)"}
    ax.plot([0.0], [root_cells["g-4"]], "*", ms=16, color="gold", mec="k",
            zorder=8, label=f"root (g-4 {root_cells['g-4']:.3f})")
    for t in ARM_ORDER:
        st = ladder_state[t]["stop"]
        pts = [(0.0, root_cells["g-4"])] + \
              [(r["cum_disp"], r["gm"]) for r in ladder_state[t]["traj"]]
        if st["kind"] == "kill" and st.get("dens"):
            for d in st["dens"]:
                pts.append((d["D"], d["gm"]))
        pts.sort(key=lambda p: p[0])
        ax.plot([p[0] for p in pts], [p[1] for p in pts], "o-", ms=5,
                lw=1.8, color=colors[t], alpha=0.9, label=labels[t])
        if st["kind"] == "kill":
            ax.plot([st["D_kill"]], [0.0], "*", ms=14, color=colors[t],
                    mec="k", zorder=7)
    for yv, col in ((SHUT_BAR, "tab:purple"),):
        ax.axhline(yv, ls="--", lw=1.0, color=col, alpha=0.8)
    ax.text(0.01, SHUT_BAR + 0.02, "0.27 DISSOLVE", fontsize=7,
            color="tab:purple", transform=ax.get_yaxis_transform())
    secax = ax.secondary_xaxis(
        "top", functions=((lambda d: d / rms_den), (lambda r: r * rms_den)))
    secax.set_xlabel("per-coordinate RMS (D/sqrt(N), N=873,472)", fontsize=8)
    ax.set_xlabel(r"cumulative displacement $D$ (absolute L2; per-step L2 "
                  r"= measured Adam step-1)", fontsize=9)
    ax.set_ylabel("g-4 battery mean p(Z)", fontsize=9.5)
    ax.set_ylim(-0.05, 1.0)
    ax.legend(fontsize=7, loc="lower left")
    ax.set_title("ORGANISM 2 — the density ladder, matched per-step L2 "
                 f"(stars = densified kills; g-kill {g_kill})", fontsize=9)

    ax = fig.add_subplot(gs[0, 1])
    names = [("a_topk1", "topk-1"), ("a_topk10", "topk-10"),
             ("a_topk50", "topk-50"), ("a_raw", "raw"), ("a_sign", "sign")]
    for i, (t, nm) in enumerate(names):
        yv = len(names) - i
        if t in f1_anchor:
            f1r = f1_anchor[t][1]
            ax.fill_betweenx([yv - 0.32, yv + 0.32],
                             f1r * 0.75, f1r * 1.25, color="lightgray",
                             alpha=0.8)
            ax.plot([f1r], [yv], "D", ms=9, color="dimgray",
                    label="organism-1 committed ratio" if i == 0 else None)
        if ratio[t] is not None:
            ax.plot([ratio[t]], [yv], "o", ms=11, color="tab:red",
                    mec="k", zorder=6,
                    label="organism-2 ratio (this run)" if i == 0 else None)
        else:
            ax.text(0.02, yv, "NO KILL (spares)", fontsize=7.5,
                    color="tab:red", va="center", transform=
                    ax.get_yaxis_transform())
    ax.set_yticks([len(names) - i for i in range(len(names))])
    ax.set_yticklabels([nm for _, nm in names], fontsize=9)
    ax.axvline(1.0, ls=":", lw=1.4, color="gray")
    ax.text(1.0, len(names) + 0.55, "r = 1 (the g-kill)", fontsize=7.5,
            ha="center", color="gray")
    ax.set_xlabel("kill-D ratio vs THIS organism's own g-kill "
                  "(gray band = organism-1's ratio +-25%)", fontsize=8.6)
    ax.set_xlim(0.0, 3.0)
    ax.legend(fontsize=7.5, loc="lower right")
    ax.set_title("THE RATIO REPLICATE — the front at n=2 organisms "
                 "(FRONT-REPLICATES bar)", fontsize=9)

    ax = fig.add_subplot(gs[0, 2])
    ax.axis("off")
    y = 0.985
    ax.text(0.02, y, f"E193 FRONT VERDICT: {verdict_front}", fontsize=10,
            va="top", family="monospace", weight="bold", color="darkred")
    y -= 0.05
    for wd in textwrap.wrap(clause_front, width=86, break_long_words=False):
        ax.text(0.02, y, f"  {wd}", fontsize=6.4, va="top", family="monospace")
        y -= 0.020
    y -= 0.02
    ax.text(0.02, y, "  arm        D_kill    ratio   f1 ratio  in band",
            fontsize=7.0, va="top", family="monospace")
    y -= 0.023
    for t, nm in names:
        dk = arm_out[t]["D_kill"]
        f1r = f1_anchor[t][1] if t in f1_anchor else None
        dk_txt = (f"{dk:7.4f}" if dk is not None
                  else f"alive>{arm_out[t]['final_D']:.1f}")
        rt_txt = (f"{ratio[t]:5.3f}" if ratio[t] is not None else "  n/a")
        f1_txt = (f"{f1r:5.3f}" if f1r is not None else "  NEW")
        if t not in f1_anchor:
            band_txt = "NEW (no f1 anchor)"
        elif (ratio[t] is not None
              and abs(ratio[t] - f1r) <= 0.25 * f1r):
            band_txt = "yes"
        else:
            band_txt = "NO"
        ax.text(0.02, y,
                f"  {nm:>8s}  {dk_txt}  {rt_txt}   {f1_txt}     {band_txt}",
                fontsize=6.8, va="top", family="monospace")
        y -= 0.022
    fig.suptitle("E193 — THE SECOND-ORGANISM DENSITY LADDER (opt2 ported + "
                 "the 1% rung + raw; the front clause at n=2)", fontsize=12)
    fig.tight_layout(rect=(0, 0, 1, 0.94))
    fig.savefig(path, dpi=130)
    plt.close(fig)


