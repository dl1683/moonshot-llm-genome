def phase_P1c(p0: dict, arms: dict) -> None:
    log("P1c — G_DECOMPMASK (the two masks' exact algebra + the bitwise "
        "conly-partition identity, over every draw) + G_DRAWS (the "
        "shared committed stream)")

    # ---- G_DECOMPMASK ---------------------------------------------------
    gen = torch.Generator().manual_seed(CONS_SEED)
    draw = make_draw(p0, ALL_T)
    n_draws_checked = CONS_STEPS
    cm_counts, rt_counts, conly_counts, canon_counts = set(), set(), set(), set()
    emit_ok = True
    disjoint_ok = True
    partition_ok = True
    canon_comp_ok = True
    for _ in range(n_draws_checked):
        x, y, nm16, _ = draw(gen, CPU)
        L = nm16.shape[1]
        # the emission mask is exactly 7 contiguous positions per name
        # window at the jitter-located offset (the classification count)
        for r in range(16):
            cols = nm16[r].nonzero().flatten().tolist()
            if len(cols) != 7 or cols != list(range(cols[0], cols[0] + 7)):
                emit_ok = False
        mcm = decomp_mask("cm", nm16)
        mrt = decomp_mask("rt", nm16)
        mconly = conly_mask(nm16)
        mcanon = canon_mask(nm16)
        cm_counts.add(int(mcm.sum()))
        rt_counts.add(int(mrt.sum()))
        conly_counts.add(int(mconly.sum()))
        canon_counts.add(int(mcanon.sum()))
        disjoint_ok &= bool(not (mcm & mrt).any())
        partition_ok &= bool(torch.equal(mcm | mrt, mconly))
        # the canon (ruler) mask == the name-emission rows UNION cmonly
        nm_rows = torch.zeros(32, L, dtype=torch.bool, device=nm16.device)
        nm_rows[:16] = nm16
        canon_comp_ok &= bool(torch.equal(mcanon, nm_rows | mcm))
    g_dm = {
        "draws_checked": n_draws_checked,
        "cm_counts_seen": sorted(cm_counts),
        "rt_counts_seen": sorted(rt_counts),
        "conly_counts_seen": sorted(conly_counts),
        "canon_counts_seen": sorted(canon_counts),
        "expected": {"cm": CM_TOKENS, "rt": RT_TOKENS,
                     "conly_x57": CONLY_TOKENS, "canon": CANON_TOKENS,
                     "tonly": TONLY_TOKENS, "full_batch": FULLBATCH_TOKENS},
        "emission_mask_7_contiguous_per_window": bool(emit_ok),
        "disjoint_every_draw": bool(disjoint_ok),
        "conly_partition_every_draw": bool(partition_ok),
        "canon_composition_every_draw": bool(canon_comp_ok),
        "claim": ("the cmonly mask == FULL nameless rows and EMPTY name "
                  "rows (4080 constant — G1's cm term alone); the rtonly "
                  "mask == the exact complement of the emission mask on "
                  "the name rows and EMPTY nameless rows (3968 constant); "
                  "the two are DISJOINT and their UNION IS EXACTLY X57'S "
                  "CONLY MASK (8048 constant) — the arms partition the "
                  "parent arm bitwise; the canon mask == nm-rows UNION "
                  "cmonly (x57's G_MASKUNION identity re-derived); every "
                  "name window's emission mask is exactly 7 contiguous "
                  "jitter-located positions"),
        "pass": bool(cm_counts == {CM_TOKENS}
                     and rt_counts == {RT_TOKENS}
                     and conly_counts == {CONLY_TOKENS}
                     and canon_counts == {CANON_TOKENS}
                     and emit_ok and disjoint_ok and partition_ok
                     and canon_comp_ok),
    }
    assert g_dm["pass"], f"G_DECOMPMASK FAILED: {g_dm}"
    metrics["gates"]["G_DECOMPMASK"] = g_dm
    log(f"G_DECOMPMASK PASS: counts constant {CM_TOKENS}/{RT_TOKENS}; "
        f"disjoint + union == conly ({CONLY_TOKENS}) + canon composition, "
        f"every draw of {n_draws_checked}")

    # ---- G_DRAWS ---------------------------------------------------------
    refs = [arms[a["tag"]]["draws"] for a in ARMS]
    n_expected = CONS_STEPS
    shape_ok = (len(refs[0]) == n_expected
                and all(len(d["ix"]) == 16 and len(d["aj"]) == 8
                        and len(d["rj"]) == 8 for d in refs[0])
                and all(len(d) == n_expected for d in refs))
    cross_equal = all(d == refs[0] for d in refs)
    k7_draws = p0["committed_k7_draws"]
    vs_k7resume = all(d == k7_draws[i] for i, d in enumerate(refs[0])) \
        and (SMOKE or len(k7_draws) == n_expected)
    first_ix_ok = refs[0][0]["ix"] == p0["committed_e345"]["first_ix"]
    g_draws = {
        "n_draws": len(refs[0]), "n_expected": n_expected,
        "shape_ok": bool(shape_ok),
        "cross_arm_bit_equal": bool(cross_equal),
        "vs_e346_k7_resume_bit_equal": bool(vs_k7resume),
        "first_ix": refs[0][0]["ix"],
        "e345_committed_first_ix": p0["committed_e345"]["first_ix"],
        "first_ix_matches_e345": bool(first_ix_ok),
        "claim": ("the two arms consumed ONE draw sequence (ix/aj/rj "
                  "bit-equal across arms, seed 10901, one fresh generator "
                  "per arm) BIT-EQUAL to e346's committed k7 resume record "
                  "(the 300-record reference loaded from the md5-bound "
                  "arm_resume_k7.pt) with the first draw == e345's "
                  "committed first_ix — THE SAME DRAW STREAM AS X57'S "
                  "ARMS: the arms sit on the committed canon stream itself "
                  "and differ in NOTHING but the decomp mask"),
        "pass": bool(shape_ok and cross_equal and vs_k7resume
                     and first_ix_ok),
    }
    assert g_draws["pass"], f"G_DRAWS FAILED: {g_draws}"
    metrics["gates"]["G_DRAWS"] = g_draws
    log(f"G_DRAWS PASS: {len(refs[0])} draws bit-equal across both arms "
        "AND vs e346's k7 resume (x57's own stream); first_ix == e345's "
        "committed")
    write_partial("P1c G_DECOMPMASK + G_DRAWS")


