def make_draw(p0: dict, slot_keys: tuple):
    """The canon cons stream's per-step draw, generalized ONLY in which
    keyed pool each of the 16 name-bearing slots reads (e345's
    'nw = pool_z_x[ix]' line, per-slot). The generator consumption is
    IDENTICAL for every keying. Returns the name-window emission mask
    (16, L) beside x/y — the decomp masks are built from it."""
    n_pool = p0["pool_z_x"].shape[0]
    cons_anchor = p0["cons_anchor"]
    train_ids = p0["train_ids"]
    pools_x = {"z": p0["pool_z_x"], "t": p0["pool_t_x"]}
    pools_m = {"z": p0["pool_z_mask"], "t": p0["pool_t_mask"]}

    def draw(gen, dev):
        ix = torch.randint(n_pool, (16,), generator=gen)
        aj = torch.randint(cons_anchor.shape[0], (8,), generator=gen)
        rj = torch.randint(len(train_ids) - G1.BLOCK - 1, (8,),
                           generator=gen)
        nw = torch.stack([pools_x[slot_keys[s]][ix[s]] for s in range(16)])
        nm = torch.stack([pools_m[slot_keys[s]][ix[s]] for s in range(16)])
        anc = torch.cat([cons_anchor[aj],
                         torch.stack([train_ids[s: s + G1.BLOCK]
                                      for s in rj])], 0)
        x = torch.cat([nw[:, :-1], anc[:, :-1]], 0).to(dev)
        y = torch.cat([nw[:, 1:], anc[:, 1:]], 0).to(dev)
        return x, y, nm.to(dev), (ix.tolist(), aj.tolist(), rj.tolist())
    return draw


def decomp_mask(role: str, nm16: torch.Tensor) -> torch.Tensor:
    """THE TWO FROZEN DECOMP-MASK CONSTRUCTIONS (the cell's only delta).

    cmonly ('cm'): the (32, L) mask = FULL on the 16 nameless rows and
    EMPTY on the 16 name rows (the canon's own cm term alone — G1's
    'cm = nll[16:]' slice; 4080 supervised tokens/step; the name windows
    neutralized — drawn, out of the loss).
    rtonly ('rt'): the exact complement of the name-emission mask on the
    16 name rows and EMPTY on the nameless rows (x57's read-through slice
    alone — the name present mid-window as pure input, never predicted;
    3968/step; the nameless windows neutralized).
    """
    L = nm16.shape[1]
    m = torch.zeros(32, L, dtype=torch.bool, device=nm16.device)
    if role == "cm":
        m[16:] = True
    elif role == "rt":
        m[:16] = ~nm16
    else:
        raise ValueError(f"unknown role {role}")
    return m


def conly_mask(nm16: torch.Tensor) -> torch.Tensor:
    """x57's conly mask (the parent this cell partitions): the complement
    on the name rows + FULL nameless rows (8048)."""
    L = nm16.shape[1]
    m = torch.zeros(32, L, dtype=torch.bool, device=nm16.device)
    m[:16] = ~nm16
    m[16:] = True
    return m


def canon_mask(nm16: torch.Tensor) -> torch.Tensor:
    """The canon (ruler) mask: nm on the name rows + full nameless rows."""
    L = nm16.shape[1]
    m = torch.zeros(32, L, dtype=torch.bool, device=nm16.device)
    m[:16] = nm16
    m[16:] = True
    return m


def train_step_role(net, opt, x, y, m):
    """The arm's training step: the SAME arithmetic as x57's (selected-
    token sum / count) over the arm's decomp mask."""
    logits, _ = net(x)
    nll = F.cross_entropy(logits.reshape(-1, logits.shape[-1]),
                          y.reshape(-1), reduction="none"
                          ).view(x.shape[0], x.shape[1])
    sel = nll[m]
    loss = sel.sum() / sel.numel()
    opt.zero_grad(set_to_none=True)
    loss.backward()
    torch.nn.utils.clip_grad_norm_(net.parameters(), 1.0)
    opt.step()
    return float(loss.item())


def train_step_canon(net, opt, x, y, nm16):
    """The canon's own step (nm + cm union) — the streamident probes'
    path (x55's inherited form, bit-faithful to G1/e345/e346/x57)."""
    logits, _ = net(x)
    nll = F.cross_entropy(logits.reshape(-1, logits.shape[-1]),
                          y.reshape(-1), reduction="none"
                          ).view(x.shape[0], x.shape[1])
    nm = nll[:16][nm16[:16]]
    cm = nll[16:]
    loss = (nm.sum() + cm.sum()) / (nm.numel() + cm.numel())
    opt.zero_grad(set_to_none=True)
    loss.backward()
    torch.nn.utils.clip_grad_norm_(net.parameters(), 1.0)
    opt.step()
    return float(loss.item())


