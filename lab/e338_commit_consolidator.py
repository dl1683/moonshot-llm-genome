def wash_arm(tag: str, net0, resume_ck: Path, p0: dict,
             armed: bool) -> dict:
    """THE WASH: e322's committed 100-step unbiased convention. The
    arithmetic (draws, batches, loss, optimizer, clip, seed, panels) is
    e322's run_wash VERBATIM (e335's port as the template); the ONLY
    delta between the arms is the event (the armed net's every-forward
    L2 projection)."""
    state = {"step": 0, "traj": [], "draws": [], "xhash": [], "zeph": 0}
    if resume_ck.exists():
        state = torch.load(resume_ck, map_location="cpu",
                           weights_only=False)
        log(f"  [{tag}] RESUMED at step {state['step']}/{WASH_STEPS}")
    if int(state.get("step", 0)) >= WASH_STEPS:
        log(f"  [{tag}] resume ckpt already COMPLETE")
        final_path = RD / f"e338_wash_{tag}_s{WASH_STEPS}.pt"
        if not final_path.exists():
            torch.save({"model": state["model"],
                        "meta": {"experiment": NAME, "arm": tag,
                                 "desc": (f"the {'COMMITTED' if armed else 'TWIN'}"
                                          f" arm's final state (recovered from"
                                          f" the completed resume ckpt)"),
                                 "seed": WASH_SEED, "steps": WASH_STEPS}},
                       final_path)
            log(f"  [ckpt] {tag} final wash state recovered -> "
                f"{final_path.name}")
        return {"traj": state["traj"], "draws": state["draws"],
                "xhash": state["xhash"], "zeph": state.get("zeph", 0),
                "resumed_final": True}

    have_cuda = torch.cuda.is_available()
    dev = torch.device("cuda") if have_cuda else CPU
    if have_cuda:
        t_burst = E261._open_burst(f"e338:{tag}")[0]   # launch gate + logged
    else:
        device_events.append({"tag": tag, "event": "NO CUDA — CPU PARK",
                              "cap_s": 1800.0})
        log("  [gpu] no CUDA device — the arm parks to CPU (recorded; "
            "2.74M is CPU-viable; cap 1800s)")
        t_burst = time.time()

    net = copy.deepcopy(net0).to(dev)       # the armed (or plain) train net
    net.train()
    opt = torch.optim.AdamW(net.parameters(), lr=WASH_LR,
                            betas=WASH_BETAS, weight_decay=WASH_WD)
    gen = torch.Generator().manual_seed(WASH_SEED)
    evl = copy.deepcopy(net0).to(CPU)       # the eval twin (ARMED if armed)
    theta0 = flat_params_cpu(net0)          # the PRISTINE subject body — the
                                            # displacement origin (stable
                                            # across resumes; net0 is never
                                            # trained)
    if resume_ck.exists():
        net.load_state_dict(state["model"])
        net.to(dev)
        net.train()
        opt.load_state_dict(state["opt"])
        gen.set_state(state["gen_state"])
    wall_R = getattr(net0, "R", None)
    n_anc = p0["anchor_full"].shape[0]
    train_ids, itos = p0["train_ids"], p0["itos"]
    g0_ids, gm12_ids = p0["g0_ids"], p0["gm12_ids"]
    tid, zid = p0["tid"], p0["zid"]

    def panel(step: int) -> None:
        sd_cpu = {k: v.detach().cpu().clone()
                  for k, v in net.state_dict().items()}
        evl.load_state_dict(sd_cpu)
        evl.eval()
        pt = G1.battery_cell(evl, g0_ids, tid)      # THE READ (p(T)@g0)
        pt12 = G1.battery_cell(evl, gm12_ids, tid)
        pz = G1.battery_cell(evl, g0_ids, zid)      # the host watch
        ce_r = G1.ce_fixed_cpu(evl, *p0["r_eval_xy"])
        cur = flat_params_cpu(net)
        d_raw = float(torch.norm(cur - theta0))
        row = {"step": step, "read_g0_pT": pt["mean_pz"],
               "read_frac_ge_05": pt["frac_pz_ge_0.5"],
               "read_frac_argmax_t": pt["frac_argmax_z"],
               "gm12_pT": pt12["mean_pz"], "host_g0_pZ": pz["mean_pz"],
               "ce_r": ce_r, "disp_raw": d_raw,
               "disp_proj": (min(d_raw, wall_R) if wall_R else None),
               "R": wall_R, "elapsed_s": round(time.time() - T0, 1)}
        state["traj"].append(row)
        log(f"  [{tag}] s{step:3d} READ p(T) {row['read_g0_pT']:.6f} | "
            f"gm12 {row['gm12_pT']:.4f} | host p(Z) "
            f"{row['host_g0_pZ']:.4f} | CE_R {row['ce_r']:.4f} | |d| "
            f"{d_raw:.4f}" + (f" (proj {row['disp_proj']:.2f})"
                              if wall_R else "")
            + ("  <-- BELOW 0.05" if step > 0
               and row["read_g0_pT"] < READ_BAR else ""))

    def save_resume() -> None:
        torch.save({"model": {k: v.detach().cpu().clone()
                              for k, v in net.state_dict().items()},
                    "opt": opt.state_dict(),
                    "gen_state": gen.get_state(), "step": state["step"],
                    "traj": state["traj"], "draws": state["draws"],
                    "xhash": state["xhash"],
                    "zeph": state["zeph"]}, resume_ck)

    t_burst = time.time()
    step = state["step"]
    if step == 0:
        panel(0)                                # t0 = the subject's read
    while step < WASH_STEPS:
        step += 1
        # e322's run_wash draws VERBATIM (aj 16 of the 60 anchors, rj 16)
        aj = torch.randint(n_anc, (WASH_ANC_BS,), generator=gen)
        rj = torch.randint(len(train_ids) - G1.BLOCK - 1, (WASH_RND_BS,),
                           generator=gen)
        state["draws"].append({"step": step, "aj": aj.tolist(),
                               "rj": rj.tolist()})
        anc = torch.cat([p0["anchor_full"][aj],
                         torch.stack([train_ids[s: s + G1.BLOCK]
                                      for s in rj])], 0)
        for w in anc[WASH_ANC_BS:]:             # the name-free guard
            txt = "".join(itos[int(c)] for c in w)
            if "ZEPH" in txt or "TAVI" in txt:
                state["zeph"] += 1
        x, y = anc[:, :-1].to(dev), anc[:, 1:].to(dev)
        state["xhash"].append(hashlib.md5(
            x.detach().cpu().contiguous().numpy().tobytes()
        ).hexdigest())
        logits, _ = net(x)          # <- the wall projects here (armed arm)
        nll = F.cross_entropy(logits.reshape(-1, logits.shape[-1]),
                              y.reshape(-1), reduction="none"
                              ).view(x.shape[0], x.shape[1])
        loss = nll.mean()           # e322: all-token mean CE
        opt.zero_grad(set_to_none=True)
        loss.backward()
        torch.nn.utils.clip_grad_norm_(net.parameters(), WASH_CLIP)
        opt.step()
        state["step"] = step
        if step in WASH_PANELS:
            panel(step)
        if have_cuda:
            ok_t, _t = E261.burst_temp_check(f"{tag}.s{step}")
            if not ok_t:
                save_resume()
                log(f"  [{tag}] burst ended (thermal margin); cooldown + "
                    f"resume next pass")
                E261.burst_cooldown(tag)
                t_burst = time.time()
        if (time.time() - t_burst) > E261.BURST_MAX_S:
            save_resume()
            log(f"  [{tag}] burst cap; cooldown + resume next pass")
            if have_cuda:
                E261.burst_cooldown(tag)
            t_burst = time.time()
    if have_cuda:
        E261.burst_cooldown(f"{tag}-end")
    save_resume()
    final_path = RD / f"e338_wash_{tag}_s{WASH_STEPS}.pt"
    torch.save({"model": {k: v.detach().cpu().clone()
                          for k, v in net.state_dict().items()},
                "meta": {"experiment": NAME, "arm": tag,
                         "desc": (f"the {'COMMITTED' if armed else 'TWIN'} "
                                  f"arm's final state after e322's "
                                  f"{WASH_STEPS}-step unbiased wash "
                                  f"(seed {WASH_SEED})"),
                         "seed": WASH_SEED, "steps": WASH_STEPS,
                         "R": wall_R}},
               final_path)
    log(f"  [ckpt] {tag} final wash state -> {final_path.name}")
    del net, opt, evl
    return {"traj": state["traj"], "draws": state["draws"],
            "xhash": state["xhash"], "zeph": state["zeph"],
            "resumed_final": False}


