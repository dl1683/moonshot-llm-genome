# P5 — THE MATCH GATES (draws + inputs + t0 identity + the wall's pin)
# ======================================================================
def phase_P5(comm: dict, twin: dict, arms: dict) -> dict:
    # G_DRAWS: bit-identical draw sequences
    same_draws = (comm["draws"] == twin["draws"])
    g_draws = {"n_steps": len(comm["draws"]), "bit_identical": same_draws,
               "claim": "both arms consumed the IDENTICAL aj/rj sequence "
                        "(e322's seed 10902 twice)",
               "pass": bool(same_draws and len(comm["draws"]) == WASH_STEPS)}

    # G_INPUTS: bit-identical input batches (per-step x md5)
    same_x = (comm["xhash"] == twin["xhash"])
    g_inputs = {"n_steps": len(comm["xhash"]), "bit_identical": same_x,
                "claim": "both arms' input batches bit-identical (per-step "
                         "x md5; g1's G-INPUTS convention)",
                "pass": bool(same_x and len(comm["xhash"]) == WASH_STEPS)}

    # G_TWIN_T0: both arms' t0 == the committed subject read
    c0 = comm["traj"][0]["read_g0_pT"]
    t0v = twin["traj"][0]["read_g0_pT"]
    g_t0 = {"committed_t0": {"arm_committed": c0, "arm_twin": t0v,
                             "bound": SUBJ_READ_T,
                             "abs_diffs": [abs(c0 - SUBJ_READ_T),
                                           abs(t0v - SUBJ_READ_T)]},
            "claim": "both arms start at the committed subject read "
                     "(the arms are matched at t0)",
            "pass": bool(abs(c0 - SUBJ_READ_T) <= READ_TOL
                         and abs(t0v - SUBJ_READ_T) <= READ_TOL)}

    # G_PIN: the committed arm's raw displacement <= R + fuzz at panels
    pins = [r["disp_raw"] for r in comm["traj"]]
    g_pin = {"R": EVENT_R, "bound": EVENT_R + PIN_FUZZ,
             "max_raw_disp_at_panels": max(pins),
             "per_panel": {r["step"]: r["disp_raw"] for r in comm["traj"]},
             "claim": "the committed arm never leaves R + the licensed "
                      "fuzz between forwards (g1b's G-PIN verbatim)",
             "pass": bool(max(pins) <= EVENT_R + PIN_FUZZ)}

    # G_NAMEFREE-WASH: the guard never fired
    g_guard = {"zeph_hits": comm["zeph"] + twin["zeph"],
               "claim": "the name-free guard never fired on either arm "
                        "(a no-op verify)",
               "pass": bool(comm["zeph"] == 0 and twin["zeph"] == 0)}

    # G_NET0: the classes recorded (the standing rule)
    g_net0 = {"subject_net0_class": NET0_CLASS,
              "arm_committed": NET0_CLASS + " + COMMIT(0.7) armed",
              "arm_twin": NET0_CLASS + " (uncommitted)",
              "reference_classes": {
                  "the ball's organism (g1c root)": "ROOT (install + e113 "
                                                    "cons final)",
                  "e335's bare root": "ROOT (the same cons final, "
                                      "unwalled)"},
              "claim": "every state classed (x32's standing rule)",
              "pass": True}

    metrics["gates"].update({"G_DRAWS": g_draws, "G_INPUTS": g_inputs,
                             "G_TWIN_T0": g_t0, "G_PIN": g_pin,
                             "G_GUARD": g_guard, "G_NET0": g_net0})
    for k, g in (("G_DRAWS", g_draws), ("G_INPUTS", g_inputs),
                 ("G_TWIN_T0", g_t0), ("G_PIN", g_pin),
                 ("G_GUARD", g_guard), ("G_NET0", g_net0)):
        log(f"{k}: {'PASS' if g['pass'] else 'FAIL'} "
            + (f"(max raw |d| {g_pin['max_raw_disp_at_panels']:.4f} <= "
               f"{EVENT_R + PIN_FUZZ:.2f})" if k == "G_PIN" else ""))
        assert g["pass"], f"{k} FAILED: {g}"
    return {"g_draws": g_draws, "g_inputs": g_inputs, "g_t0": g_t0,
            "g_pin": g_pin}


