def arm_summary(traj: list, band: dict, sand: dict) -> dict:
    reads = {r["step"]: r["read_g0_pT"] for r in traj}
    t0v = reads[0]
    s_end = reads[max(reads)]
    retention = s_end / t0v
    panel_steps = [s for s in WASH_PANELS if s > 0 and s in reads]
    first_below = next((s for s in panel_steps if reads[s] < READ_BAR), None)
    all_ge = all(reads[s] >= READ_BAR for s in panel_steps)
    strict_sand = SAND_STRICT[0] <= retention <= SAND_STRICT[1]
    sand_class = bool(retention <= SAND_OPS_CAP and s_end < READ_BAR)
    if not SMOKE:
        in_band = bool(band["lo"] <= retention <= band["hi"])
    else:
        in_band = None
    return {"t0": t0v, "s_end": s_end, "end_step": max(reads),
            "retention": retention, "first_below_005": first_below,
            "all_panels_ge_005": all_ge, "in_installed_band": in_band,
            "sand_class": sand_class,
            "sand_strict_band": strict_sand,
            "sand_stamp": ("SAND-STRICT" if strict_sand else
                           ("SAND-OR-DEEPER" if sand_class else
                            "NOT-SAND")),
            "min_panel_read": min(reads[s] for s in panel_steps),
            "traj": traj}


def adjudicate(comm_s: dict, twin_s: dict, band: dict, sand: dict) -> dict:
    verdict, clause = None, None
    if SMOKE:
        verdict, clause = "SMOKE", ("smoke horizon — nothing adjudicated "
                                    "(the bars need the 100-step horizon)")
    elif (comm_s["in_installed_band"] and comm_s["all_panels_ge_005"]
            and twin_s["sand_class"]):
        verdict = "BALL-FORMS"
        clause = (f"the committed arm's retention {comm_s['retention']:.4f} "
                  f"lands in the installed-fact band [{band['lo']:.4f}, "
                  f"{band['hi']:.4f}] (read {comm_s['t0']:.6f} -> "
                  f"s{comm_s['end_step']} {comm_s['s_end']:.6f}) while the "
                  f"twin's {twin_s['retention']:.4f} is "
                  f"{twin_s['sand_stamp']} (read -> "
                  f"{twin_s['s_end']:.6f}) — CONSOLIDATION IS ONE "
                  f"CONSTRUCTION EVENT")
    elif comm_s["sand_class"] and twin_s["sand_class"]:
        verdict = "STILL-SAND"
        clause = (f"both arms wash out: committed retention "
                  f"{comm_s['retention']:.4f} ({comm_s['sand_stamp']}), "
                  f"twin {twin_s['retention']:.4f} "
                  f"({twin_s['sand_stamp']}) — the commit event alone is "
                  f"not enough; the recipe is more than the event; the "
                  f"consolidation question decomposes. NEXT "
                  f"DISCRIMINATOR (named at birth): the read died WITHIN "
                  f"the ball (<= {EVENT_R} L2 of its install state) — "
                  f"either the cons leg (the e113 jitter pre-annealing "
                  f"the read's landscape) or the read-height margin "
                  f"(0.2859 vs 0.90+) decides: commit(0.7) on the "
                  f"CONS-SHAPED g1c root is the matched control the era "
                  f"already ran (W1, retention 1.038); commit(0.7) on an "
                  f"UNSHELLED 0.286-height install is the missing cell")
    else:
        verdict = "MIXED"
        if not comm_s["all_panels_ge_005"]:
            shape = ("the committed read fell below 0.05 (died WITHIN the "
                     "ball) but its retention is outside the sand class")
        elif not comm_s["in_installed_band"]:
            shape = (f"the committed arm SURVIVES (>= 0.05 everywhere) "
                     f"but retention {comm_s['retention']:.4f} is outside "
                     f"the installed-fact band [{band['lo']:.4f}, "
                     f"{band['hi']:.4f}] — THE RECOVERY DEFICIT: an "
                     f"install-fresh read holds inside the ball but not "
                     f"at the cons-shaped kinetics; the cons leg is the "
                     f"next cell")
        else:
            shape = ("the committed arm is in-band but the twin is not "
                     "sand-class (alive) — the fragility premise itself "
                     "re-opens")
        clause = (f"the table verbatim: committed retention "
                  f"{comm_s['retention']:.4f} (in_band "
                  f"{comm_s['in_installed_band']}; min panel read "
                  f"{comm_s['min_panel_read']:.6f}); twin retention "
                  f"{twin_s['retention']:.4f} ({twin_s['sand_stamp']}; "
                  f"min panel {twin_s['min_panel_read']:.6f}). {shape}")

    p_hit = None if SMOKE else bool(verdict == "BALL-FORMS")
    return {"verdict": verdict, "clause": clause,
            "P-e338a": {"guess": REGISTERED["P-e338a"]["my_guess"],
                        "lab_lean": REGISTERED["lab_lean_verbatim"],
                        "hit": p_hit,
                        "scored": REGISTERED["P-e338a"]["scored"]},
            "arm_committed": comm_s, "arm_twin": twin_s,
            "bands": {"installed_fact": {k: v for k, v in band.items()
                                         if k != "legs"},
                      "sand": {k: v for k, v in sand.items()
                               if k != "legs"}}}


