def main() -> None:
    log(f"E338 — THE COMMIT EVENT AS CONSOLIDATOR (smoke={SMOKE}) "
        f"-> {RD}")
    metrics["birth_commit"] = git_head()
    write_partial("startup (bars registered, committed at birth)")
    set_seed(33801)              # global init only; every RNG is its own

    p0 = phase_P0()
    p1 = phase_P1(p0)
    p2 = phase_P2(p1["theta0"])
    p3 = phase_P3()

    # ---- the arms (sequential; cooldown between; GPU single-lane) -------
    comm = wash_arm("COMMIT", p2["net0"], RD / "wash_committed_resume.pt",
                    p0, armed=True)
    if torch.cuda.is_available():
        E261.burst_cooldown("between-arms")
    twin = wash_arm("TWIN", p2["twin0"], RD / "wash_twin_resume.pt",
                    p0, armed=False)

    comm_s = arm_summary(comm["traj"], p3["band"], p3["sand"])
    twin_s = arm_summary(twin["traj"], p3["band"], p3["sand"])
    p5 = phase_P5(comm, twin, {"net0": p2["net0"]})
    adj = adjudicate(comm_s, twin_s, p3["band"], p3["sand"])

    metrics["arms"] = {
        "committed": {k: v for k, v in comm_s.items()},
        "twin": {k: v for k, v in twin_s.items()},
        "resumed_final": {"committed": comm["resumed_final"],
                          "twin": twin["resumed_final"]},
    }
    metrics["adjudication"] = adj
    metrics["thermal"] = {"max_temp": (max((r["temp"] for r in thermal_log),
                                           default=None)),
                          "polls": len(thermal_log),
                          "device_events": device_events}
    metrics["status"] = ("DONE (smoke; nothing adjudicated)" if SMOKE
                         else f"DONE: {adj['verdict']}")
    metrics["git_head_final"] = git_head()
    metrics["completed_utc"] = utcnow()
    write_partial("complete" if not SMOKE else "complete (SMOKE)")

    make_png(adj, comm_s, twin_s, p3["band"], p3["sand"])
    write_report(adj, comm_s, twin_s, p3["band"], p3["sand"],
                 p3["ball_ref"], p5)
    log(f"E338 VERDICT: {adj['verdict']}")


if __name__ == "__main__":
    main()
